#!/usr/bin/env node

import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { pathToFileURL } from 'node:url'
import { blogUiStagePolicy, blogUiStagePolicyDigest } from './ui-stage-policy.mjs'

export const executionProfilesSchemaUrl = new URL('../contracts/generated/ui-execution-profiles.schema.json', import.meta.url)
export const executionProfilesBindingUrl = new URL('../contracts/generated/ui-execution-profiles.binding.json', import.meta.url)
export const executionProfilesSchemaId = 'urn:fsusblog-design-conformance:ui-execution-profiles:v2'

function profileBindings(ids) {
    return {
        type: 'object',
        required: ['actualProfile', 'actualModel', 'actualEffort'],
        oneOf: [...new Set(ids)].map((id) => ({
            properties: {
                actualProfile: { const: id },
                actualModel: { const: blogUiStagePolicy.executionProfiles[id].model },
                actualEffort: { const: blogUiStagePolicy.executionProfiles[id].effort }
            }
        }))
    }
}

/** A projection of the trusted policy; it is not an independent profile registry. */
export function executionProfilesSchemaText() {
    return `${JSON.stringify({
        $schema: 'https://json-schema.org/draft/2020-12/schema',
        $id: executionProfilesSchemaId,
        $comment: 'Generated by scripts/generate-execution-profiles.mjs from contracts/blog-ui-stage-policy.json. Do not edit.',
        $defs: {
            stagePolicyDigest: { const: blogUiStagePolicyDigest },
            implementation: profileBindings(blogUiStagePolicy.implementation.allowedProfiles),
            adjudication: profileBindings(blogUiStagePolicy.adjudication.allowedProfiles),
            uxAcceptance: profileBindings(Object.values(blogUiStagePolicy.uxAcceptance.routing)),
            implementationProfileId: { enum: blogUiStagePolicy.implementation.allowedProfiles }
        }
    }, null, 2)}\n`
}

export function executionProfilesBindingText() {
    const prefix = '.agents/skills/fsusblog-design-conformance'
    return `${JSON.stringify({
        schema: 'fsusblog.generated-output-binding.v1',
        sources: [
            `${prefix}/contracts/blog-ui-stage-policy.json`,
            `${prefix}/scripts/ui-stage-policy.mjs`,
            `${prefix}/scripts/generate-execution-profiles.mjs`
        ],
        outputs: [{
            path: `${prefix}/contracts/generated/ui-execution-profiles.schema.json`,
            sha256: createHash('sha256').update(executionProfilesSchemaText()).digest('hex')
        }]
    }, null, 2)}\n`
}

export function checkExecutionProfilesSchema() {
    if (readFileSync(executionProfilesSchemaUrl, 'utf8') !== executionProfilesSchemaText() ||
        readFileSync(executionProfilesBindingUrl, 'utf8') !== executionProfilesBindingText()) {
        const error = new Error('execution profile schema is stale; run generate-execution-profiles.mjs --write')
        error.code = 'blog-ui-profile-schema-drift'
        throw error
    }
}

function main() {
    const args = process.argv.slice(2)
    if (args.length !== 1 || !['--check', '--write'].includes(args[0])) {
        throw new Error('usage: node generate-execution-profiles.mjs --check|--write')
    }
    if (args[0] === '--write') {
        mkdirSync(new URL('../contracts/generated/', import.meta.url), { recursive: true })
        writeFileSync(executionProfilesSchemaUrl, executionProfilesSchemaText())
        writeFileSync(executionProfilesBindingUrl, executionProfilesBindingText())
    } else {
        checkExecutionProfilesSchema()
    }
    process.stdout.write(`[blog-ui-execution-profiles] ${args[0].slice(2)} ok\n`)
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) main()
