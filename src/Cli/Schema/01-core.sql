-- FsusBlog V2 Core Schema: schema marker, identities, authentication, articles, taxonomy, and publication authority.

CREATE TABLE public.v2_schema (
    singleton boolean CONSTRAINT v2_schema_pk PRIMARY KEY CONSTRAINT v2_schema_singleton CHECK (singleton),
    version integer NOT NULL
);

CREATE TABLE public.blog_user (
    id uuid CONSTRAINT blog_user_pk PRIMARY KEY,
    name text NOT NULL CONSTRAINT blog_user_name_key UNIQUE,
    enabled boolean NOT NULL,
    generation bigint NOT NULL CONSTRAINT blog_user_generation CHECK (generation > 0)
);

CREATE TABLE public.admin_principal (
    id uuid PRIMARY KEY,
    handle text NOT NULL UNIQUE CHECK (handle ~ '^[a-z][a-z0-9_.-]{0,63}$'),
    user_handle bytea NOT NULL UNIQUE CHECK (octet_length(user_handle) = 32),
    enabled boolean NOT NULL,
    generation bigint NOT NULL CHECK (generation > 0),
    generation_changed_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE public.login_ticket (
    digest bytea CONSTRAINT login_ticket_pk PRIMARY KEY
        CONSTRAINT login_ticket_digest_size CHECK (octet_length(digest) = 32),
    user_id uuid NOT NULL CONSTRAINT login_ticket_user_fk REFERENCES public.blog_user (id),
    expires_at timestamptz NOT NULL
);
CREATE INDEX login_ticket_user ON public.login_ticket (user_id);

CREATE TABLE public.passkey_subject (
    user_id uuid PRIMARY KEY REFERENCES public.blog_user (id),
    account_id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL UNIQUE CHECK (account_id > 0),
    user_handle bytea NOT NULL UNIQUE CHECK (octet_length(user_handle) = 32)
);

CREATE TABLE public.passkey_credential (
    credential_id bytea PRIMARY KEY CHECK (octet_length(credential_id) BETWEEN 1 AND 1023),
    user_id uuid NOT NULL REFERENCES public.passkey_subject (user_id),
    public_key bytea NOT NULL CHECK (octet_length(public_key) BETWEEN 1 AND 16384),
    sign_count bigint NOT NULL CHECK (sign_count BETWEEN 0 AND 4294967295),
    backup_eligible boolean NOT NULL,
    backed_up boolean NOT NULL CHECK (NOT backed_up OR backup_eligible),
    created_at timestamptz NOT NULL DEFAULT now(),
    last_used_at timestamptz,
    UNIQUE (credential_id, user_id)
);
CREATE INDEX passkey_credential_user ON public.passkey_credential (user_id);

CREATE TABLE public.site_passkey_name (
    credential_id bytea PRIMARY KEY,
    user_id uuid NOT NULL,
    revision bigint NOT NULL CHECK (revision > 0),
    name text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 64 AND octet_length(name) <= 256),
    FOREIGN KEY (credential_id, user_id) REFERENCES public.passkey_credential (credential_id, user_id) ON DELETE CASCADE
);

CREATE TABLE public.user_session (
    digest bytea CONSTRAINT user_session_pk PRIMARY KEY
        CONSTRAINT user_session_digest_size CHECK (octet_length(digest) = 32),
    user_id uuid NOT NULL CONSTRAINT user_session_user_fk REFERENCES public.blog_user (id),
    generation bigint NOT NULL CONSTRAINT user_session_generation CHECK (generation > 0),
    expires_at timestamptz NOT NULL,
    passkey_credential_id bytea,
    totp_verified_at timestamptz,
    CONSTRAINT user_session_passkey_credential_owner FOREIGN KEY (passkey_credential_id, user_id)
        REFERENCES public.passkey_credential (credential_id, user_id)
);
CREATE INDEX user_session_user ON public.user_session (user_id);

CREATE TABLE public.passkey_challenge (
    digest bytea PRIMARY KEY CHECK (octet_length(digest) = 32),
    user_id uuid REFERENCES public.passkey_subject (user_id),
    generation bigint,
    options text NOT NULL CHECK (octet_length(options) BETWEEN 1 AND 8192),
    expires_at timestamptz NOT NULL,
    binding_digest bytea CHECK (octet_length(binding_digest) = 32),
    CHECK ((user_id IS NULL AND generation IS NULL AND binding_digest IS NULL) OR
           (user_id IS NOT NULL AND generation IS NOT NULL AND generation > 0 AND binding_digest IS NOT NULL))
);
CREATE INDEX passkey_challenge_expires ON public.passkey_challenge (expires_at);

CREATE TABLE public.mfa_totp (
    user_id uuid PRIMARY KEY REFERENCES public.passkey_subject (user_id),
    sealed_seed bytea NOT NULL CHECK (octet_length(sealed_seed) = 49),
    last_step bigint NOT NULL CHECK (last_step >= 0),
    verified_at timestamptz NOT NULL,
    retry_after timestamptz NOT NULL,
    failed_count integer NOT NULL CHECK (failed_count >= 0 AND failed_count <= 5)
);

CREATE TABLE public.mfa_recovery_code (
    user_id uuid NOT NULL REFERENCES public.mfa_totp (user_id),
    digest bytea NOT NULL CHECK (octet_length(digest) = 32),
    PRIMARY KEY (user_id, digest)
);

CREATE TABLE public.mfa_setup (
    user_id uuid PRIMARY KEY REFERENCES public.passkey_subject (user_id),
    generation bigint NOT NULL CHECK (generation > 0),
    session_digest bytea NOT NULL CHECK (octet_length(session_digest) = 32),
    sealed_seed bytea NOT NULL CHECK (octet_length(sealed_seed) = 49),
    expires_at timestamptz NOT NULL,
    failed_count integer NOT NULL CHECK (failed_count >= 0 AND failed_count <= 5)
);

CREATE TABLE public.mfa_flow (
    digest bytea PRIMARY KEY CHECK (octet_length(digest) = 32),
    user_id uuid NOT NULL REFERENCES public.passkey_subject (user_id),
    generation bigint NOT NULL CHECK (generation > 0),
    kind integer NOT NULL CHECK (kind >= 1 AND kind <= 5),
    scope bytea NOT NULL CHECK (octet_length(scope) >= 1 AND octet_length(scope) <= 1055),
    options text NOT NULL CHECK (octet_length(options) <= 8192),
    expires_at timestamptz NOT NULL
);
CREATE INDEX mfa_flow_expiry ON public.mfa_flow (expires_at);
CREATE INDEX mfa_flow_user ON public.mfa_flow (user_id, kind);

CREATE TABLE public.site_session_refresh (
    family_id uuid PRIMARY KEY,
    access_digest bytea NOT NULL UNIQUE REFERENCES public.user_session (digest) ON DELETE CASCADE ON UPDATE CASCADE
        CHECK (octet_length(access_digest) = 32),
    refresh_digest bytea NOT NULL UNIQUE CHECK (octet_length(refresh_digest) = 32),
    previous_access_digest bytea CHECK (octet_length(previous_access_digest) = 32),
    generation bigint NOT NULL CHECK (generation >= 0),
    idle_expires_at timestamptz NOT NULL,
    absolute_expires_at timestamptz NOT NULL,
    rotated_at timestamptz NOT NULL,
    CHECK (idle_expires_at <= absolute_expires_at)
);

CREATE TABLE public.site_session_refresh_tombstone (
    refresh_digest bytea PRIMARY KEY CHECK (octet_length(refresh_digest) = 32),
    family_id uuid NOT NULL REFERENCES public.site_session_refresh (family_id) ON DELETE CASCADE,
    generation bigint NOT NULL CHECK (generation >= 0),
    used_at timestamptz NOT NULL,
    expires_at timestamptz NOT NULL,
    CHECK (used_at < expires_at)
);
CREATE INDEX site_session_refresh_tombstone_expiry ON public.site_session_refresh_tombstone (expires_at);
CREATE INDEX site_session_refresh_tombstone_family ON public.site_session_refresh_tombstone (family_id);

CREATE TABLE public.site_recovery_key (
    user_id uuid PRIMARY KEY REFERENCES public.passkey_subject (user_id),
    lookup_digest bytea NOT NULL UNIQUE CHECK (octet_length(lookup_digest) = 32),
    salt bytea NOT NULL CHECK (octet_length(salt) = 16),
    verifier bytea NOT NULL CHECK (octet_length(verifier) = 32),
    version bigint NOT NULL CHECK (version > 0),
    created_at timestamptz NOT NULL,
    used_at timestamptz,
    failed_count smallint NOT NULL CHECK (failed_count BETWEEN 0 AND 8),
    failure_until timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.site_recovery_flow (
    digest bytea PRIMARY KEY CHECK (octet_length(digest) = 32),
    user_id uuid NOT NULL REFERENCES public.passkey_subject (user_id),
    generation bigint NOT NULL CHECK (generation > 0),
    session_digest bytea NOT NULL CHECK (octet_length(session_digest) = 32),
    purpose smallint NOT NULL CHECK (purpose BETWEEN 1 AND 2),
    kind smallint NOT NULL,
    options text CHECK (octet_length(options) BETWEEN 1 AND 8192),
    expires_at timestamptz NOT NULL,
    UNIQUE (user_id, purpose, kind),
    CHECK ((kind = 1 AND options IS NOT NULL) OR (kind = 2 AND options IS NULL))
);

CREATE TABLE public.site_recovery_rebind (
    user_id uuid PRIMARY KEY REFERENCES public.passkey_subject (user_id),
    generation bigint NOT NULL CHECK (generation > 0),
    ticket_digest bytea NOT NULL UNIQUE CHECK (octet_length(ticket_digest) = 32),
    expires_at timestamptz NOT NULL,
    challenge_digest bytea CHECK (octet_length(challenge_digest) = 32),
    options text CHECK (octet_length(options) BETWEEN 1 AND 8192),
    challenge_expires_at timestamptz,
    request_digest bytea CHECK (octet_length(request_digest) = 32),
    completed_at timestamptz,
    CHECK ((challenge_digest IS NULL) = (options IS NULL)),
    CHECK ((challenge_digest IS NULL) = (challenge_expires_at IS NULL)),
    CHECK ((request_digest IS NULL) = (completed_at IS NULL))
);

