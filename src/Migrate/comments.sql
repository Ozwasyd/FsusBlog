CREATE TABLE public.comment (
    article_id integer NOT NULL REFERENCES public.article (id),
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    parent_id bigint,
    root_id bigint NOT NULL,
    parent_depth integer,
    reply_to_id bigint,
    depth integer NOT NULL,
    moderation_status smallint NOT NULL CHECK (moderation_status >= 0 AND moderation_status <= 3),
    deleted boolean NOT NULL,
    body text NOT NULL CHECK (octet_length(body) <= 12288),
    author_mode smallint NOT NULL CHECK (author_mode IN (1, 3, 4)),
    display_name text NOT NULL CHECK (octet_length(display_name) BETWEEN 1 AND 384),
    display_language text NOT NULL CHECK (display_language IN ('zh-CN', 'en')),
    scope_label text CHECK (scope_label IS NULL OR (author_mode <> 3 AND octet_length(scope_label) <= 512)),
    created_at timestamptz NOT NULL,
    edited_at timestamptz,
    PRIMARY KEY (article_id, id),
    UNIQUE (article_id, root_id, id),
    UNIQUE (article_id, root_id, id, depth),
    FOREIGN KEY (article_id, root_id, parent_id, parent_depth) REFERENCES public.comment (article_id, root_id, id, depth),
    FOREIGN KEY (article_id, root_id, reply_to_id) REFERENCES public.comment (article_id, root_id, id),
    CHECK (id > 0),
    CHECK (depth >= 0 AND depth <= 256),
    CHECK ((parent_id IS NULL AND parent_depth IS NULL AND depth = 0 AND root_id = id AND reply_to_id IS NULL)
        OR (parent_id IS NOT NULL AND parent_depth IS NOT NULL AND parent_id < id AND parent_depth = depth - 1 AND depth > 0)),
    CHECK (reply_to_id IS NULL OR reply_to_id < id)
);

CREATE INDEX comment_scope_parent ON public.comment (article_id, parent_id, id);

CREATE TABLE public.comment_blocked_region (
    article_id integer NOT NULL,
    comment_id bigint NOT NULL,
    region_code text NOT NULL CHECK (octet_length(region_code) BETWEEN 1 AND 16),
    PRIMARY KEY (article_id, comment_id, region_code),
    FOREIGN KEY (article_id, comment_id) REFERENCES public.comment (article_id, id)
);
