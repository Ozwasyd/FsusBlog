CREATE TABLE public.inbox_conversation (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id uuid NOT NULL REFERENCES public.blog_user (id),
    subject text NOT NULL CHECK (octet_length(subject) BETWEEN 1 AND 640),
    status smallint NOT NULL CHECK (status >= 0 AND status <= 2),
    is_system boolean NOT NULL,
    read_through bigint,
    last_message_id bigint,
    last_message_at timestamptz NOT NULL,
    UNIQUE (account_id, id)
);

CREATE TABLE public.inbox_message (
    conversation_id bigint NOT NULL REFERENCES public.inbox_conversation (id),
    id bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE NOT NULL,
    sender smallint NOT NULL CHECK (sender >= 0 AND sender <= 2),
    is_internal boolean NOT NULL,
    body text NOT NULL CHECK (octet_length(body) BETWEEN 1 AND 16000),
    sent_at timestamptz NOT NULL,
    PRIMARY KEY (conversation_id, id)
);

ALTER TABLE public.inbox_conversation
    ADD FOREIGN KEY (id, read_through) REFERENCES public.inbox_message (conversation_id, id),
    ADD FOREIGN KEY (id, last_message_id) REFERENCES public.inbox_message (conversation_id, id);

CREATE TABLE public.inbox_command (
    account_id uuid NOT NULL,
    is_service boolean NOT NULL,
    command_id text NOT NULL CHECK (octet_length(command_id) BETWEEN 1 AND 64),
    fingerprint bytea NOT NULL CHECK (octet_length(fingerprint) = 32),
    conversation_id bigint NOT NULL,
    message_id bigint NOT NULL,
    PRIMARY KEY (account_id, is_service, command_id),
    FOREIGN KEY (account_id, conversation_id) REFERENCES public.inbox_conversation (account_id, id),
    FOREIGN KEY (conversation_id, message_id) REFERENCES public.inbox_message (conversation_id, id)
);

CREATE TABLE public.inbox_delivery (
    account_id uuid PRIMARY KEY REFERENCES public.blog_user (id),
    last_sequence bigint NOT NULL CHECK (last_sequence >= 0)
);

CREATE TABLE public.inbox_event (
    account_id uuid NOT NULL REFERENCES public.inbox_delivery (account_id),
    sequence bigint NOT NULL CHECK (sequence > 0),
    kind smallint NOT NULL CHECK (kind >= 12 AND kind <= 14),
    conversation_id bigint NOT NULL,
    message_id bigint NOT NULL,
    occurred_at timestamptz NOT NULL,
    PRIMARY KEY (account_id, sequence),
    FOREIGN KEY (account_id, conversation_id) REFERENCES public.inbox_conversation (account_id, id),
    FOREIGN KEY (conversation_id, message_id) REFERENCES public.inbox_message (conversation_id, id)
);

CREATE INDEX inbox_conversation_activity ON public.inbox_conversation (account_id, last_message_id DESC);
CREATE INDEX inbox_message_visible ON public.inbox_message (conversation_id, id) WHERE NOT is_internal;
CREATE INDEX inbox_command_audience ON public.inbox_command (account_id, conversation_id);
CREATE INDEX inbox_command_message ON public.inbox_command (conversation_id, message_id);
CREATE INDEX inbox_event_audience ON public.inbox_event (account_id, conversation_id);
CREATE INDEX inbox_event_message ON public.inbox_event (conversation_id, message_id);
