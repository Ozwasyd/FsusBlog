CREATE TABLE public.inbox_admin_status (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id bigint NOT NULL REFERENCES public.inbox_conversation (id),
    principal_id uuid NOT NULL REFERENCES public.admin_principal (id),
    session_reference bytea NOT NULL CHECK (octet_length(session_reference) = 32),
    previous_status smallint NOT NULL CHECK (previous_status BETWEEN 0 AND 2),
    current_status smallint NOT NULL CHECK (current_status BETWEEN 0 AND 2),
    reason text NOT NULL CHECK (octet_length(reason) BETWEEN 1 AND 1024),
    happened_at timestamptz NOT NULL,
    CHECK (current_status <> previous_status)
);

CREATE INDEX inbox_admin_status_thread ON public.inbox_admin_status (conversation_id, id);
CREATE INDEX inbox_admin_status_actor ON public.inbox_admin_status (principal_id, id);
