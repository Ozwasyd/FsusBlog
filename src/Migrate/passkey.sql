CREATE TABLE public.passkey_subject (
    user_id uuid PRIMARY KEY REFERENCES public.blog_user (id),
    account_id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL UNIQUE CHECK (account_id > 0),
    user_handle bytea NOT NULL UNIQUE CHECK (octet_length(user_handle) = 32)
);

CREATE TABLE public.passkey_credential (
    credential_id bytea PRIMARY KEY CHECK (octet_length(credential_id) BETWEEN 1 AND 1023),
    user_id uuid NOT NULL REFERENCES public.passkey_subject (user_id),
    public_key bytea NOT NULL CHECK (octet_length(public_key) BETWEEN 1 AND 16384),
    sign_count bigint NOT NULL CHECK (sign_count BETWEEN 0 AND 4294967295),
    backup_eligible boolean NOT NULL,
    backed_up boolean NOT NULL CHECK (NOT backed_up OR backup_eligible),
    created_at timestamptz NOT NULL DEFAULT now(),
    last_used_at timestamptz,
    UNIQUE (credential_id, user_id)
);
CREATE INDEX passkey_credential_user ON public.passkey_credential (user_id);

ALTER TABLE public.user_session
    ADD COLUMN passkey_credential_id bytea,
    ADD CONSTRAINT user_session_passkey_credential_owner FOREIGN KEY (passkey_credential_id, user_id)
        REFERENCES public.passkey_credential (credential_id, user_id);

CREATE TABLE public.passkey_challenge (
    digest bytea PRIMARY KEY CHECK (octet_length(digest) = 32),
    user_id uuid REFERENCES public.passkey_subject (user_id),
    generation bigint,
    options text NOT NULL CHECK (octet_length(options) BETWEEN 1 AND 8192),
    expires_at timestamptz NOT NULL,
    binding_digest bytea CHECK (octet_length(binding_digest) = 32),
    CHECK ((user_id IS NULL AND generation IS NULL AND binding_digest IS NULL) OR
           (user_id IS NOT NULL AND generation IS NOT NULL AND generation > 0 AND binding_digest IS NOT NULL))
);
CREATE INDEX passkey_challenge_expires ON public.passkey_challenge (expires_at);
