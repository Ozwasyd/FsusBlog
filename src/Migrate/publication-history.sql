CREATE TABLE public.article_publication_history (
    article_id integer NOT NULL,
    event_no integer NOT NULL CHECK (event_no > 0),
    revision bigint NOT NULL,
    publication_no integer NOT NULL CHECK (publication_no >= 0),
    publication_id bigint,
    supersedes_id bigint,
    kind text NOT NULL,
    reason text NOT NULL,
    happened_at timestamptz,
    recorded_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    actor_id uuid,
    command_id uuid,
    PRIMARY KEY (article_id, event_no),
    UNIQUE (article_id, revision),
    UNIQUE (article_id, publication_id),
    UNIQUE (publication_id),
    UNIQUE (actor_id, command_id),
    FOREIGN KEY (article_id, revision) REFERENCES public.article_revision (article_id, revision),
    FOREIGN KEY (article_id, supersedes_id) REFERENCES public.article_publication_history (article_id, publication_id),
    FOREIGN KEY (actor_id, command_id) REFERENCES public.article_command (actor_id, command_id),
    CHECK ((actor_id IS NULL) = (command_id IS NULL)),
    CHECK (publication_id IS NULL OR publication_id > 0),
    CHECK (supersedes_id IS NULL OR supersedes_id IS DISTINCT FROM publication_id),
    CHECK (kind IN ('retained-active','retained-hidden','publish','replace','retract','delete'))
);
