CREATE TABLE public.v2_schema (
    singleton boolean CONSTRAINT v2_schema_pk PRIMARY KEY CONSTRAINT v2_schema_singleton CHECK (singleton),
    version integer NOT NULL
);

CREATE TABLE public.blog_user (
    id uuid CONSTRAINT blog_user_pk PRIMARY KEY,
    name text NOT NULL CONSTRAINT blog_user_name_key UNIQUE,
    can_author boolean NOT NULL,
    enabled boolean NOT NULL,
    generation bigint NOT NULL CONSTRAINT blog_user_generation CHECK (generation > 0)
);

CREATE TABLE public.login_ticket (
    digest bytea CONSTRAINT login_ticket_pk PRIMARY KEY
        CONSTRAINT login_ticket_digest_size CHECK (octet_length(digest) = 32),
    user_id uuid NOT NULL CONSTRAINT login_ticket_user_fk REFERENCES public.blog_user (id),
    expires_at timestamptz NOT NULL
);

CREATE TABLE public.user_session (
    digest bytea CONSTRAINT user_session_pk PRIMARY KEY
        CONSTRAINT user_session_digest_size CHECK (octet_length(digest) = 32),
    user_id uuid NOT NULL CONSTRAINT user_session_user_fk REFERENCES public.blog_user (id),
    generation bigint NOT NULL CONSTRAINT user_session_generation CHECK (generation > 0),
    expires_at timestamptz NOT NULL
);

CREATE TABLE public.article (
    id integer GENERATED ALWAYS AS IDENTITY CONSTRAINT article_pk PRIMARY KEY,
    owner_id uuid NOT NULL CONSTRAINT article_owner_fk REFERENCES public.blog_user (id),
    revision bigint NOT NULL CONSTRAINT article_revision_positive CHECK (revision > 0),
    title text NOT NULL,
    body text NOT NULL,
    published_revision bigint,
    publication_count integer NOT NULL DEFAULT 0 CONSTRAINT article_publication_count_nonnegative CHECK (publication_count >= 0),
    deleted boolean NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.article_revision (
    article_id integer NOT NULL CONSTRAINT article_revision_article_fk REFERENCES public.article (id),
    revision bigint NOT NULL CONSTRAINT article_revision_number CHECK (revision > 0),
    title text NOT NULL,
    body text NOT NULL,
    happened_at timestamptz NOT NULL,
    CONSTRAINT article_revision_pk PRIMARY KEY (article_id, revision)
);

ALTER TABLE public.article
    ADD CONSTRAINT article_published_revision_fk FOREIGN KEY (id, published_revision)
    REFERENCES public.article_revision (article_id, revision) DEFERRABLE INITIALLY DEFERRED;
ALTER TABLE public.article
    ADD CONSTRAINT article_current_revision_fk FOREIGN KEY (id, revision)
    REFERENCES public.article_revision (article_id, revision) DEFERRABLE INITIALLY DEFERRED;

CREATE TABLE public.article_command (
    actor_id uuid NOT NULL CONSTRAINT article_command_actor_fk REFERENCES public.blog_user (id),
    command_id uuid NOT NULL,
    fingerprint bytea NOT NULL CONSTRAINT article_command_fingerprint_size CHECK (octet_length(fingerprint) = 32),
    article_id integer NOT NULL CONSTRAINT article_command_article_fk REFERENCES public.article (id),
    revision bigint NOT NULL,
    title text NOT NULL,
    body text NOT NULL,
    published boolean NOT NULL,
    CONSTRAINT article_command_pk PRIMARY KEY (actor_id, command_id),
    CONSTRAINT article_command_revision_fk FOREIGN KEY (article_id, revision)
        REFERENCES public.article_revision (article_id, revision)
);

CREATE TABLE public.article_publication (
    article_id integer CONSTRAINT article_publication_pk PRIMARY KEY
        CONSTRAINT article_publication_article_fk REFERENCES public.article (id),
    publication_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL CONSTRAINT article_publication_id_key UNIQUE,
    revision bigint NOT NULL,
    publication_no integer NOT NULL DEFAULT 1 CONSTRAINT article_publication_no_positive CHECK (publication_no > 0),
    published_at timestamptz NOT NULL,
    CONSTRAINT article_publication_revision_fk FOREIGN KEY (article_id, revision)
        REFERENCES public.article_revision (article_id, revision)
);

CREATE TABLE public.blog_outbox (
    id bigint GENERATED ALWAYS AS IDENTITY CONSTRAINT blog_outbox_pk PRIMARY KEY,
    article_id integer NOT NULL CONSTRAINT blog_outbox_article_fk REFERENCES public.article (id),
    revision bigint NOT NULL,
    kind text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    processed_at timestamptz,
    CONSTRAINT blog_outbox_revision_fk FOREIGN KEY (article_id, revision)
        REFERENCES public.article_revision (article_id, revision)
);

CREATE INDEX blog_outbox_pending ON public.blog_outbox (id) WHERE processed_at IS NULL;
CREATE INDEX login_ticket_user ON public.login_ticket (user_id);
CREATE INDEX user_session_user ON public.user_session (user_id);
