CREATE TABLE public.category (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE CHECK (char_length(name) BETWEEN 1 AND 128),
    description text CHECK (char_length(description) BETWEEN 1 AND 500)
);

CREATE TABLE public.tag (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE CHECK (char_length(name) BETWEEN 1 AND 128),
    description text CHECK (char_length(description) BETWEEN 1 AND 500)
);

CREATE TABLE public.tag_url_name (
    name_key text PRIMARY KEY CHECK (char_length(name_key) BETWEEN 1 AND 256),
    tag_id integer NOT NULL REFERENCES public.tag (id)
);
CREATE INDEX tag_url_name_tag ON public.tag_url_name (tag_id);

CREATE TABLE public.article_revision_category (
    article_id integer NOT NULL,
    revision bigint NOT NULL,
    category_id integer NOT NULL REFERENCES public.category (id),
    PRIMARY KEY (article_id, revision),
    FOREIGN KEY (article_id, revision) REFERENCES public.article_revision (article_id, revision)
);
CREATE INDEX article_revision_category_find ON public.article_revision_category (category_id);

CREATE TABLE public.article_revision_tag (
    article_id integer NOT NULL,
    revision bigint NOT NULL,
    tag_id integer NOT NULL REFERENCES public.tag (id),
    PRIMARY KEY (article_id, revision, tag_id),
    FOREIGN KEY (article_id, revision) REFERENCES public.article_revision (article_id, revision)
);
CREATE INDEX article_revision_tag_find ON public.article_revision_tag (tag_id);
