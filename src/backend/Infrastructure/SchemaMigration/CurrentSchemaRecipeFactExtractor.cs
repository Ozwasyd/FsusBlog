using System.Text.RegularExpressions;

using FsusBlog.Contracts.Schema;

namespace FsusBlog.Server.Infrastructure.SchemaMigration;

/// <summary>
/// Extracts the sole current owner's existing recipe, rather than maintaining a
/// second business-field mapping. Unknown source syntax refuses the entire export.
/// </summary>
internal static class CurrentSchemaRecipeFactExtractor
{
    private const string Id = "[a-z_][a-z0-9_]*";

    internal static CurrentSchemaRecipeFacts Extract(CurrentSchemaRuntimeRollupTable recipe)
    {
        Match create = Match(recipe.CreateSql, $"CREATE TABLE IF NOT EXISTS (?<table>{Id}) \\((?<body>.*)\\);");
        if (create.Groups["table"].Value != recipe.TableName) Fail("table_owner_mismatch");
        var columns = new Dictionary<string, SchemaColumnModel>(StringComparer.Ordinal);
        var constraints = new Dictionary<string, SchemaConstraintModel>(StringComparer.Ordinal);
        foreach (string part in Split(create.Groups["body"].Value))
        {
            if (Starts(part, "CONSTRAINT ") || Starts(part, "PRIMARY KEY"))
            {
                SchemaConstraintModel constraint = Constraint(part, recipe.TableName);
                constraints.Add(constraint.Name, constraint);
            }
            else
            {
                (SchemaColumnModel column, IReadOnlyList<SchemaConstraintModel> inline) = Column(part, recipe.TableName);
                columns.Add(column.Name, column);
                foreach (SchemaConstraintModel constraint in inline) constraints.Add(constraint.Name, constraint);
            }
        }
        if (columns.Count == 0) Fail("empty_table");
        foreach (SchemaConstraintModel constraint in constraints.Values.Where(static value => value.Kind == "primary-key"))
        {
            foreach (string name in constraint.Columns)
            {
                if (!columns.TryGetValue(name, out SchemaColumnModel? column)) Fail("primary_key_column_missing");
                columns[name] = column! with { IsPrimaryKey = true, IsNullable = false };
            }
        }
        var table = new SchemaTableModel(recipe.TableName, columns, [], constraints: constraints,
            owner: new("current-runtime-recipe", "CurrentSchemaRuntimeRollupTables.Tables"));
        CurrentSchemaRecipeOperation[] operations = (recipe.AdditionalSql ?? []).Select(Additional).ToArray();
        return new CurrentSchemaRecipeFacts(table, operations);
    }

    private static (SchemaColumnModel, IReadOnlyList<SchemaConstraintModel>) Column(string source, string table)
    {
        Match match = Match(source, $"(?<name>{Id}) (?<type>varchar\\([1-9][0-9]*\\)|double precision|timestamp(?: without time zone)?|smallint|integer|bigint|boolean|bytea|uuid|jsonb|date)\\s*(?<tail>.*)");
        string name = match.Groups["name"].Value;
        string type = match.Groups["type"].Value.ToLowerInvariant();
        string tail = match.Groups["tail"].Value.Trim();
        bool identity = Consume(ref tail, "GENERATED BY DEFAULT AS IDENTITY");
        bool nullable = !Consume(ref tail, "NOT NULL");
        if (nullable) Consume(ref tail, "NULL");
        bool primary = Consume(ref tail, "PRIMARY KEY");
        var constraints = new List<SchemaConstraintModel>();
        if (primary) constraints.Add(new($"{table}_pkey", "primary-key", [name]));
        string? defaultValue = null;
        if (Consume(ref tail, "DEFAULT"))
        {
            defaultValue = tail;
            tail = "";
            ValidateExpression(defaultValue);
        }
        if (Starts(tail, "REFERENCES"))
        {
            constraints.Add(ForeignKey($"{table}_{name}_fkey", [name], tail));
            tail = "";
        }
        if (tail.Length != 0) Fail("column_tail_unavailable");
        int? maxLength = type.StartsWith("varchar(", StringComparison.Ordinal)
            ? int.Parse(type[8..^1], System.Globalization.CultureInfo.InvariantCulture) : null;
        string semantic = SchemaPhysicalTypeProjection.NormalizeDeclaredSemantic(type);
        string physical = maxLength is not null ? $"character varying({maxLength})"
            : type == "timestamp" ? "timestamp without time zone" : type;
        var column = new SchemaColumnModel(name, nullable && !primary, primary, identity, maxLength, semantic,
            DefaultValue: defaultValue, PhysicalType: physical,
            Collation: SchemaPhysicalTypeProjection.ToCollation(SchemaProviderKind.PostgreSql, semantic),
            GenerationKind: identity ? "identity-by-default" : "none");
        return (column, constraints);
    }

    private static SchemaConstraintModel Constraint(string source, string table)
    {
        string name;
        string body;
        if (Starts(source, "CONSTRAINT "))
        {
            Match named = Match(source, $"CONSTRAINT (?<name>{Id}) (?<body>.*)");
            name = named.Groups["name"].Value;
            body = named.Groups["body"].Value;
        }
        else
        {
            name = $"{table}_pkey";
            body = source;
        }
        if (Starts(body, "CHECK"))
        {
            Match check = Match(body, "CHECK\\s*\\((?<expression>.*)\\)");
            string expression = check.Groups["expression"].Value;
            ValidateExpression(expression);
            return new(name, "check", [], Expression: expression);
        }
        if (Starts(body, "FOREIGN KEY"))
        {
            Match foreign = Match(body, "FOREIGN KEY\\s*\\((?<columns>[^)]+)\\)\\s*(?<target>REFERENCES.*)");
            return ForeignKey(name, Names(foreign.Groups["columns"].Value), foreign.Groups["target"].Value);
        }
        Match unique = Match(body, "(?<kind>PRIMARY KEY|UNIQUE)\\s*\\((?<columns>[^)]+)\\)\\s*(?<state>DEFERRABLE INITIALLY DEFERRED)?");
        bool deferred = unique.Groups["state"].Success;
        return new(name, Starts(unique.Groups["kind"].Value, "PRIMARY") ? "primary-key" : "unique",
            Names(unique.Groups["columns"].Value), IsDeferrable: deferred, IsInitiallyDeferred: deferred);
    }

    private static SchemaConstraintModel ForeignKey(string name, IReadOnlyList<string> columns, string source)
    {
        Match match = Match(source, $"REFERENCES (?<table>{Id})\\s*\\((?<columns>[^)]+)\\)\\s*(?:ON DELETE (?<action>CASCADE|RESTRICT|SET NULL))?\\s*(?<state>DEFERRABLE INITIALLY DEFERRED)?");
        bool deferred = match.Groups["state"].Success;
        return new(name, "foreign-key", columns, match.Groups["table"].Value,
            Names(match.Groups["columns"].Value), IsDeferrable: deferred, IsInitiallyDeferred: deferred,
            ForeignKeyDeleteAction: match.Groups["action"].Success
                ? match.Groups["action"].Value.ToLowerInvariant().Replace(' ', '-') : "no-action",
            ForeignKeyUpdateAction: "no-action", ForeignKeyMatchType: "simple", ReferencedSchema: "public");
    }

    private static CurrentSchemaRecipeOperation Additional(string source)
    {
        source = source.Trim();
        if (Starts(source, "CREATE INDEX") || Starts(source, "CREATE UNIQUE INDEX"))
        {
            Match match = Match(source, $"CREATE (?<unique>UNIQUE )?INDEX IF NOT EXISTS (?<name>{Id}) ON (?<table>{Id})\\s*\\((?<keys>[^)]+)\\)\\s*(?:WHERE (?<predicate>.*?))?;");
            SchemaIndexKeyModel[] keys = Split(match.Groups["keys"].Value).Select(static key =>
            {
                Match parsed = Match(key, $"(?<name>{Id})(?: (?<direction>ASC|DESC))?");
                bool descending = parsed.Groups["direction"].Value.Equals("DESC", StringComparison.OrdinalIgnoreCase);
                return new SchemaIndexKeyModel(parsed.Groups["name"].Value, descending ? "desc" : "asc",
                    descending ? "first" : "last", "default", "default");
            }).ToArray();
            string? predicate = match.Groups["predicate"].Success ? match.Groups["predicate"].Value : null;
            if (predicate is not null) ValidateExpression(predicate);
            var index = new SchemaIndexModel(match.Groups["name"].Value, match.Groups["unique"].Success,
                keys, [], "btree", predicate, false);
            return new(CurrentSchemaRecipeOperationKind.CreateIndex, index.Name, match.Groups["table"].Value, Index: index);
        }
        if (Starts(source, "CREATE SEQUENCE"))
        {
            Match match = Match(source, $"CREATE SEQUENCE IF NOT EXISTS (?<name>{Id}) AS bigint;");
            return new(CurrentSchemaRecipeOperationKind.CreateSequence, match.Groups["name"].Value,
                Sequence: CurrentSchemaIndependentSequenceFacts.PostgreSqlBigIntDefaults);
        }
        if (Starts(source, "CREATE OR REPLACE FUNCTION"))
        {
            Match match = Match(source, $"CREATE OR REPLACE FUNCTION (?<name>{Id})\\(\\) RETURNS trigger AS \\$\\$ BEGIN RAISE EXCEPTION '(?<error>[a-z_][a-z0-9_]*)'; END; \\$\\$ LANGUAGE plpgsql;");
            return new(CurrentSchemaRecipeOperationKind.DefineImmutableGuard, match.Groups["name"].Value,
                ErrorCode: match.Groups["error"].Value);
        }
        if (Starts(source, "DROP TRIGGER"))
        {
            Match match = Match(source, $"DROP TRIGGER IF EXISTS (?<name>{Id}) ON (?<table>{Id});");
            return new(CurrentSchemaRecipeOperationKind.RemoveTrigger, match.Groups["name"].Value, match.Groups["table"].Value);
        }
        if (Starts(source, "CREATE TRIGGER"))
        {
            Match match = Match(source, $"CREATE TRIGGER (?<name>{Id}) BEFORE UPDATE OR DELETE ON (?<table>{Id}) FOR EACH ROW EXECUTE FUNCTION (?<function>{Id})\\(\\);");
            return new(CurrentSchemaRecipeOperationKind.CreateImmutableTrigger, match.Groups["name"].Value,
                match.Groups["table"].Value, Function: match.Groups["function"].Value);
        }
        if (Starts(source, "INSERT INTO"))
        {
            Match match = Match(source, $"INSERT INTO (?<table>{Id})\\s*\\((?<columns>[^)]+)\\) VALUES\\s*\\((?<values>.*)\\) ON CONFLICT\\s*\\((?<conflict>{Id})\\) DO NOTHING;");
            string[] values = Split(match.Groups["values"].Value).ToArray();
            foreach (string value in values) ValidateExpression(value);
            string[] columns = Names(match.Groups["columns"].Value);
            if (columns.Length != values.Length) Fail("seed_arity_invalid");
            return new(CurrentSchemaRecipeOperationKind.InsertIfAbsent, match.Groups["table"].Value,
                match.Groups["table"].Value, Columns: columns, Values: values, ConflictColumn: match.Groups["conflict"].Value);
        }
        if (Starts(source, "ALTER TABLE"))
        {
            Match match = Match(source, $"ALTER TABLE (?<table>{Id}) ADD COLUMN IF NOT EXISTS (?<column>.*);");
            (SchemaColumnModel column, IReadOnlyList<SchemaConstraintModel> constraints) = Column(match.Groups["column"].Value, match.Groups["table"].Value);
            if (constraints.Count != 0) Fail("add_column_constraint_unavailable");
            return new(CurrentSchemaRecipeOperationKind.AddColumnIfAbsent, column.Name, match.Groups["table"].Value, Column: column);
        }
        if (Starts(source, "DO $$"))
        {
            Match match = Match(source, $"DO \\$\\$ BEGIN IF NOT EXISTS \\( SELECT 1 FROM pg_constraint WHERE conname = '(?<name>{Id})'\\) THEN ALTER TABLE (?<table>{Id}) ADD CONSTRAINT (?<declaration>.*); END IF; END \\$\\$;");
            SchemaConstraintModel constraint = Constraint("CONSTRAINT " + match.Groups["declaration"].Value, match.Groups["table"].Value);
            if (constraint.Name != match.Groups["name"].Value) Fail("constraint_guard_owner_mismatch");
            return new(CurrentSchemaRecipeOperationKind.AddConstraintIfAbsent, constraint.Name,
                match.Groups["table"].Value, Constraint: constraint);
        }
        throw new InvalidOperationException("current_schema_recipe_operation_unavailable");
    }

    private static Match Match(string source, string expression)
    {
        // Whitespace is insignificant outside literals; preserve literal contents.
        string normalized = Normalize(source);
        Match result = Regex.Match(normalized, "\\A(?:" + expression + ")\\z",
            RegexOptions.IgnoreCase | RegexOptions.CultureInvariant | RegexOptions.Singleline, TimeSpan.FromSeconds(1));
        if (!result.Success) Fail("syntax_unavailable");
        return result;
    }

    private static string Normalize(string value)
    {
        var builder = new System.Text.StringBuilder();
        bool quote = false;
        bool space = false;
        for (int index = 0; index < value.Length; index++)
        {
            char character = value[index];
            if (character == '\'')
            {
                if (space && builder.Length != 0) builder.Append(' ');
                space = false;
                builder.Append(character);
                if (quote && index + 1 < value.Length && value[index + 1] == '\'') builder.Append(value[++index]);
                else quote = !quote;
            }
            else if (!quote && char.IsWhiteSpace(character)) space = true;
            else
            {
                if (space && builder.Length != 0) builder.Append(' ');
                space = false;
                builder.Append(character);
            }
        }
        if (quote) Fail("unterminated_literal");
        return builder.ToString().Trim();
    }

    private static IReadOnlyList<string> Split(string value)
    {
        var result = new List<string>();
        int depth = 0;
        int start = 0;
        bool quote = false;
        for (int index = 0; index < value.Length; index++)
        {
            char character = value[index];
            if (character == '\'')
            {
                if (quote && index + 1 < value.Length && value[index + 1] == '\'') index++;
                else quote = !quote;
            }
            else if (!quote)
            {
                if (character == '(') depth++;
                if (character == ')' && --depth < 0) Fail("unbalanced_expression");
                if (character == ',' && depth == 0)
                {
                    result.Add(value[start..index].Trim());
                    start = index + 1;
                }
            }
        }
        if (depth != 0 || quote) Fail("unbalanced_expression");
        result.Add(value[start..].Trim());
        if (result.Any(static item => item.Length == 0)) Fail("empty_member");
        return result;
    }

    private static string[] Names(string source)
        => Split(source).Select(static name => Match(name, Id).Value).ToArray();

    private static bool Starts(string value, string prefix)
        => value.StartsWith(prefix, StringComparison.OrdinalIgnoreCase);

    private static bool Consume(ref string value, string prefix)
    {
        if (!Starts(value, prefix) || (value.Length > prefix.Length && !char.IsWhiteSpace(value[prefix.Length]))) return false;
        value = value[prefix.Length..].Trim();
        return true;
    }

    private static void ValidateExpression(string value)
    {
        if (string.IsNullOrWhiteSpace(value) || value.Contains(';') || value.Contains("--", StringComparison.Ordinal)
            || value.Contains("/*", StringComparison.Ordinal) || value.Contains("$$", StringComparison.Ordinal)) Fail("expression_unavailable");
        _ = Split(value); // Require balanced delimiters and literals; no discarded tail.
    }

    private static void Fail(string reason)
        => throw new InvalidOperationException($"current_schema_recipe_{reason}");
}
