namespace FsusBlog.Server.Infrastructure.SchemaMigration.Definitions;

internal static class ArticlePublicationMigrationDefinitions
{
    internal static ISchemaMigrationDescriptor BuildArticlePublicationCoordinatesMigration()
        => new SchemaMigrationDescriptor(
            "20260719-pre-article-publication-coordinates",
            "Separate mutable authoring revisions from immutable public article publication records and backfill exact coordinates.",
            SchemaMigrationPhase.PreCodeFirst,
            Transactional: true,
            Steps:
            [
                new EnsureColumnStep("article", "current_revision_id", "bigint NULL"),
                new EnsureColumnStep("article", "current_publication_id", "bigint NULL"),
                new EnsureColumnStep("article", "pending_publication_at", "timestamp NULL"),
                new EnsureColumnStep("article_mutation_outbox", "article_revision_id", "bigint NULL"),
                new EnsureColumnStep("article_mutation_outbox", "revision_no", "integer NULL"),
                new EnsureColumnStep("article_mutation_outbox", "article_publication_id", "bigint NULL"),
                new EnsureColumnStep("article_mutation_outbox", "publication_no", "integer NULL"),
                new EnsureTableStep(
                    "article_publication",
                    """
                    CREATE TABLE IF NOT EXISTS article_publication (
                        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        article_id integer NOT NULL,
                        publication_no integer NOT NULL,
                        article_revision_id bigint NOT NULL,
                        revision_no integer NOT NULL,
                        rights_snapshot_id bigint NOT NULL,
                        responsibility_snapshot_id bigint NULL,
                        transition_kind varchar(32) NOT NULL,
                        published_at timestamp NOT NULL,
                        created_at timestamp NOT NULL,
                        CONSTRAINT ck_article_publication_positive_coordinates
                            CHECK (publication_no > 0 AND article_revision_id > 0 AND revision_no > 0 AND rights_snapshot_id > 0)
                    );
                    """),
                new CreateIndexStep(
                    "ux_article_publication_article_no",
                    "CREATE UNIQUE INDEX IF NOT EXISTS ux_article_publication_article_no ON article_publication(article_id, publication_no);"),
                new CreateIndexStep(
                    "idx_article_publication_revision",
                    "CREATE INDEX IF NOT EXISTS idx_article_publication_revision ON article_publication(article_revision_id);"),
                new CreateIndexStep(
                    "idx_article_pending_publication_due",
                    "CREATE INDEX IF NOT EXISTS idx_article_pending_publication_due ON article(pending_publication_at, id) WHERE isdeleted = false AND pending_publication_at IS NOT NULL;"),
                new BackfillSqlStep(
                    """
                    DO $$
                    BEGIN
                    IF to_regclass('article') IS NOT NULL
                       AND to_regclass('article_revision') IS NOT NULL
                       AND to_regclass('article_body') IS NOT NULL
                       AND to_regclass('article_tag') IS NOT NULL
                       AND to_regclass('article_revision_content_block') IS NOT NULL THEN
                    INSERT INTO article_revision_content_block (
                        content_hash, markdown_content, byte_length, created_at)
                    SELECT
                        encode(sha256(convert_to(COALESCE(body.markdown_content, ''), 'UTF8')), 'hex'),
                        COALESCE(body.markdown_content, ''),
                        octet_length(convert_to(COALESCE(body.markdown_content, ''), 'UTF8')),
                        MIN(article.createtime)
                    FROM article
                    LEFT JOIN article_body body ON body.article_id = article.id
                    WHERE NOT EXISTS (
                        SELECT 1 FROM article_revision revision WHERE revision.article_id = article.id
                    )
                    GROUP BY COALESCE(body.markdown_content, '')
                    ON CONFLICT (content_hash) DO NOTHING;

                    INSERT INTO article_revision (
                        article_id, revision_no, title, summary, cover_image_url, categoryid,
                        tag_ids, content_block_id, markdown_content, diff_summary,
                        created_by_admin_principal_id, created_at)
                    SELECT
                        article.id,
                        1,
                        article.title,
                        article.summary,
                        article.coverimageurl,
                        article.categoryid,
                        COALESCE((
                            SELECT string_agg(article_tag.tagid::text, ',' ORDER BY article_tag.tagid)
                            FROM article_tag
                            WHERE article_tag.articleid = article.id
                        ), ''),
                        block.id,
                        '',
                        'publication-coordinate migration',
                        0,
                        article.createtime
                    FROM article
                    LEFT JOIN article_body body ON body.article_id = article.id
                    JOIN article_revision_content_block block
                      ON block.content_hash = encode(sha256(convert_to(COALESCE(body.markdown_content, ''), 'UTF8')), 'hex')
                     AND block.markdown_content = COALESCE(body.markdown_content, '')
                    WHERE NOT EXISTS (
                        SELECT 1 FROM article_revision revision WHERE revision.article_id = article.id
                    )
                    ON CONFLICT (article_id, revision_no) DO NOTHING;

                    UPDATE article article
                    SET current_revision_id = (
                        SELECT revision.id
                        FROM article_revision revision
                        WHERE revision.article_id = article.id
                        ORDER BY revision.revision_no DESC, revision.id DESC
                        LIMIT 1
                    )
                    WHERE article.current_revision_id IS NULL;
                    END IF;
                    END $$;
                    """),
                new BackfillSqlStep(
                    """
                    DO $$
                    BEGIN
                    IF to_regclass('article') IS NOT NULL
                       AND to_regclass('article_revision') IS NOT NULL
                       AND to_regclass('article_rights_policy') IS NOT NULL
                       AND to_regclass('article_rights_snapshot') IS NOT NULL THEN
                    INSERT INTO article_rights_policy (
                        article_id, enabled, license_type, copy_policy, max_excerpt_chars,
                        allow_code_copy, show_public_badge, proof_binding_enabled, created_at, updated_at)
                    SELECT
                        article.id, true, 'all-rights-reserved', 'append-attribution', 300,
                        true, true, true, article.createtime, article.createtime
                    FROM article
                    WHERE NOT EXISTS (
                        SELECT 1 FROM article_rights_policy policy WHERE policy.article_id = article.id
                    )
                    ON CONFLICT (article_id) DO NOTHING;

                    INSERT INTO article_rights_snapshot (
                        article_id, article_revision_id, revision_no, article_rights_policy_id,
                        enabled, license_type, copy_policy, max_excerpt_chars, allow_code_copy,
                        show_public_badge, proof_binding_enabled, policy_hash, content_canonical_hash, created_at)
                    SELECT
                        article.id,
                        revision.id,
                        revision.revision_no,
                        policy.id,
                        policy.enabled,
                        policy.license_type,
                        policy.copy_policy,
                        policy.max_excerpt_chars,
                        policy.allow_code_copy,
                        policy.show_public_badge,
                        policy.proof_binding_enabled,
                        'rights-v3:policy-hash:recompute',
                        'rights-v3:content-hash:recompute',
                        revision.created_at
                    FROM article
                    JOIN article_revision revision ON revision.id = article.current_revision_id
                    JOIN article_rights_policy policy ON policy.article_id = article.id
                    WHERE NOT EXISTS (
                        SELECT 1
                        FROM article_rights_snapshot snapshot
                        WHERE snapshot.article_id = article.id
                          AND snapshot.article_revision_id = revision.id
                    )
                    ON CONFLICT (article_id, article_revision_id) DO NOTHING;
                    END IF;
                    END $$;
                    """),
                new BackfillSqlStep(
                    """
                    DO $$
                    BEGIN
                    IF to_regclass('article') IS NOT NULL
                       AND to_regclass('article_revision') IS NOT NULL
                       AND to_regclass('article_rights_snapshot') IS NOT NULL
                       AND to_regclass('article_responsibility_snapshot') IS NOT NULL THEN
                    INSERT INTO article_publication (
                        article_id, publication_no, article_revision_id, revision_no,
                        rights_snapshot_id, responsibility_snapshot_id, transition_kind,
                        published_at, created_at)
                    SELECT
                        article.id,
                        1,
                        revision.id,
                        revision.revision_no,
                        rights.id,
                        responsibility.id,
                        'legacy-backfill',
                        COALESCE(article.published_at, article.createtime),
                        COALESCE(article.published_at, article.createtime)
                    FROM article
                    JOIN article_revision revision ON revision.id = article.current_revision_id
                    JOIN article_rights_snapshot rights
                      ON rights.article_id = article.id
                     AND rights.article_revision_id = revision.id
                    LEFT JOIN article_responsibility_snapshot responsibility
                      ON responsibility.article_revision_id = revision.id
                    WHERE article.status = 2
                      AND article.isdeleted = false
                      AND article.current_publication_id IS NULL
                    ON CONFLICT (article_id, publication_no) DO NOTHING;

                    UPDATE article article
                    SET current_publication_id = publication.id
                    FROM article_publication publication
                    WHERE publication.article_id = article.id
                      AND publication.publication_no = (
                          SELECT MAX(candidate.publication_no)
                          FROM article_publication candidate
                          WHERE candidate.article_id = article.id
                      )
                      AND article.status = 2
                      AND article.isdeleted = false
                      AND article.current_publication_id IS NULL;
                    END IF;
                    END $$;
                    """),
                new BackfillSqlStep(
                    """
                    DO $$
                    BEGIN
                    IF to_regclass('article') IS NOT NULL
                       AND to_regclass('article_mutation_outbox') IS NOT NULL
                       AND to_regclass('article_revision') IS NOT NULL
                       AND to_regclass('article_rights_snapshot') IS NOT NULL
                       AND to_regclass('article_responsibility_snapshot') IS NOT NULL THEN
                    UPDATE article_mutation_outbox event
                    SET article_revision_id = revision.id,
                        revision_no = revision.revision_no,
                        article_publication_id = publication.id,
                        publication_no = publication.publication_no,
                        payload_json = jsonb_strip_nulls(jsonb_build_object(
                            'articleId', event.aggregate_id,
                            'eventType', event.event_type,
                            'articleRevisionId', revision.id,
                            'revisionNo', revision.revision_no,
                            'rightsSnapshotId', rights.id,
                            'responsibilitySnapshotId', responsibility.id,
                            'articlePublicationId', publication.id,
                            'publicationNo', publication.publication_no))::text
                    FROM article article
                    JOIN article_revision revision ON revision.id = article.current_revision_id
                    JOIN article_rights_snapshot rights
                      ON rights.article_id = article.id
                     AND rights.article_revision_id = revision.id
                    LEFT JOIN article_responsibility_snapshot responsibility
                      ON responsibility.article_revision_id = revision.id
                    LEFT JOIN article_publication publication ON publication.id = article.current_publication_id
                    WHERE event.aggregate_id = article.id
                      AND event.status IN ('pending', 'retry')
                      AND event.article_revision_id IS NULL;
                    END IF;
                    END $$;
                    """)
            ]);

    internal static ISchemaMigrationDescriptor BuildArticlePublicationConsistencyViewMigration()
        => new SchemaMigrationDescriptor(
            "20260719-post-article-publication-consistency",
            "Install the exact article revision/publication consistency checker after CodeFirst bootstrap.",
            SchemaMigrationPhase.PostCodeFirst,
            Transactional: true,
            Steps:
            [
                .. BuildArticlePublicationCoordinatesMigration().Steps.OfType<BackfillSqlStep>(),
                new RawSqlStep(
                    """
                    CREATE OR REPLACE VIEW article_publication_consistency_v1 AS
                    SELECT article.id AS article_id, 'current_revision_missing'::text AS issue
                    FROM article
                    WHERE article.current_revision_id IS NULL
                    UNION ALL
                    SELECT article.id, 'published_record_missing'
                    FROM article
                    WHERE article.status = 2
                      AND article.isdeleted = false
                      AND article.current_publication_id IS NULL
                    UNION ALL
                    SELECT article.id, 'publication_revision_mismatch'
                    FROM article
                    JOIN article_publication publication ON publication.id = article.current_publication_id
                    LEFT JOIN article_revision revision ON revision.id = publication.article_revision_id
                    WHERE publication.article_id <> article.id
                       OR revision.id IS NULL
                       OR publication.revision_no <> revision.revision_no
                    UNION ALL
                    SELECT article.id, 'publication_rights_mismatch'
                    FROM article
                    JOIN article_publication publication ON publication.id = article.current_publication_id
                    LEFT JOIN article_rights_snapshot rights ON rights.id = publication.rights_snapshot_id
                    WHERE rights.id IS NULL
                       OR rights.article_id <> article.id
                       OR rights.article_revision_id <> publication.article_revision_id
                    UNION ALL
                    SELECT event.aggregate_id, 'pending_outbox_coordinate_missing'
                    FROM article_mutation_outbox event
                    JOIN article ON article.id = event.aggregate_id
                    WHERE event.status IN ('pending', 'retry')
                      AND (
                          event.article_revision_id IS NULL
                          OR event.revision_no IS NULL
                          OR (
                              article.current_publication_id IS NOT NULL
                              AND (event.article_publication_id IS NULL OR event.publication_no IS NULL)
                          )
                      );
                    """)
            ]);
