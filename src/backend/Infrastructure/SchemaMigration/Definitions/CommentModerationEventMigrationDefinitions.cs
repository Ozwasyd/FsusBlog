namespace FsusBlog.Server.Infrastructure.SchemaMigration.Definitions;

internal static class CommentModerationEventMigrationDefinitions
{
    internal static ISchemaMigrationDescriptor BuildCommentModerationEventMigration()
        => new SchemaMigrationDescriptor(
            "20260719-post-comment-moderation-event",
            "Persist every initial and changed comment moderation state as an append-only event.",
            SchemaMigrationPhase.PostCodeFirst,
            Transactional: true,
            Steps:
            [
                new EnsureTableStep(
                    "comment_moderation_event",
                    """
                    CREATE TABLE IF NOT EXISTS comment_moderation_event (
                        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        comment_id bigint NOT NULL,
                        previous_status integer NULL,
                        next_status integer NOT NULL,
                        reason_code varchar(256) NULL,
                        transition_source varchar(32) NOT NULL,
                        admin_principal_id bigint NULL,
                        occurred_at_utc timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
                        CONSTRAINT fk_comment_moderation_event_comment
                            FOREIGN KEY (comment_id) REFERENCES comment(id) ON DELETE RESTRICT,
                        CONSTRAINT ck_comment_moderation_event_status
                            CHECK (next_status BETWEEN 0 AND 3 AND (previous_status IS NULL OR previous_status BETWEEN 0 AND 3)),
                        CONSTRAINT ck_comment_moderation_event_source
                            CHECK (transition_source IN ('initial', 'model', 'admin', 'system'))
                    );
                    """),
                new CreateIndexStep(
                    "idx_comment_moderation_event_comment_time",
                    "CREATE INDEX IF NOT EXISTS idx_comment_moderation_event_comment_time ON comment_moderation_event(comment_id, occurred_at_utc, id);"),
                new RawSqlStep(
                    """
                    CREATE OR REPLACE FUNCTION fsus_append_comment_moderation_event()
                    RETURNS trigger
                    LANGUAGE plpgsql
                    AS $$
                    BEGIN
                        IF TG_OP = 'INSERT' THEN
                            INSERT INTO comment_moderation_event(
                                comment_id, previous_status, next_status, reason_code,
                                transition_source, admin_principal_id, occurred_at_utc)
                            VALUES (
                                NEW.id, NULL, NEW.moderation_status, NEW.moderation_reason,
                                'initial', NEW.moderated_by_admin_principal_id,
                                COALESCE(NEW.moderated_at, NEW.create_time, now() AT TIME ZONE 'utc'));
                        ELSIF NEW.moderation_status IS DISTINCT FROM OLD.moderation_status THEN
                            INSERT INTO comment_moderation_event(
                                comment_id, previous_status, next_status, reason_code,
                                transition_source, admin_principal_id, occurred_at_utc)
                            VALUES (
                                NEW.id, OLD.moderation_status, NEW.moderation_status, NEW.moderation_reason,
                                CASE
                                    WHEN NEW.moderated_by_admin_principal_id IS NOT NULL THEN 'admin'
                                    WHEN COALESCE(NEW.moderation_reason, '') LIKE 'model_policy:%' THEN 'model'
                                    ELSE 'system'
                                END,
                                NEW.moderated_by_admin_principal_id,
                                COALESCE(NEW.moderated_at, now() AT TIME ZONE 'utc'));
                        END IF;
                        RETURN NEW;
                    END;
                    $$;

                    DROP TRIGGER IF EXISTS trg_comment_moderation_event ON comment;
                    CREATE TRIGGER trg_comment_moderation_event
                    AFTER INSERT OR UPDATE OF moderation_status ON comment
                    FOR EACH ROW EXECUTE FUNCTION fsus_append_comment_moderation_event();

                    CREATE OR REPLACE FUNCTION fsus_reject_comment_moderation_event_mutation()
                    RETURNS trigger
                    LANGUAGE plpgsql
                    AS $$
                    BEGIN
                        RAISE EXCEPTION 'comment_moderation_event is append-only';
                    END;
                    $$;

                    DROP TRIGGER IF EXISTS trg_comment_moderation_event_append_only ON comment_moderation_event;
                    CREATE TRIGGER trg_comment_moderation_event_append_only
                    BEFORE UPDATE OR DELETE ON comment_moderation_event
                    FOR EACH ROW EXECUTE FUNCTION fsus_reject_comment_moderation_event_mutation();
                    """)
            ]);
}
