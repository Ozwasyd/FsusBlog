using System.Security.Cryptography;
using System.Text;

using FsusBlog.Server.Entities;

using SqlSugar;

namespace FsusBlog.Server.Infrastructure.SchemaMigration.Definitions;

internal static class CommentRevisionManagementMigrationDefinitions
{
    internal const string MigrationId = "20260720-pre-comment-revision-management";

    internal static ISchemaMigrationDescriptor BuildMigration()
        => new SchemaMigrationDescriptor(
            MigrationId,
            "Add comment revision history and unlinkable anonymous author-management capabilities.",
            SchemaMigrationPhase.PreCodeFirst,
            Transactional: true,
            Steps:
            [
                new EnsureColumnStep("comment", "current_version", "integer NOT NULL DEFAULT 1"),
                new EnsureColumnStep("comment", "edited_at_utc", "timestamp without time zone NULL"),
                new EnsureColumnStep("comment", "management_capability_hash", "varchar(64) NULL"),
                // Create without FKs so fresh bootstrap can run before CodeFirst creates comment.
                new EnsureTableStep(
                    "comment_revision",
                    """
                    CREATE TABLE IF NOT EXISTS comment_revision (
                        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        comment_id bigint NOT NULL,
                        version integer NOT NULL,
                        content text NOT NULL,
                        content_sha256 varchar(64) NOT NULL,
                        operation varchar(24) NOT NULL,
                        created_at_utc timestamp without time zone NOT NULL,
                        actor_account_id integer NULL,
                        actor_admin_principal_id bigint NULL,
                        actor_mode varchar(32) NOT NULL,
                        CONSTRAINT ck_comment_revision_version CHECK (version > 0),
                        CONSTRAINT ck_comment_revision_operation CHECK (operation IN ('created', 'edited', 'deleted')),
                        CONSTRAINT ux_comment_revision_comment_version UNIQUE (comment_id, version)
                    );
                    """),
                new EnsureTableStep(
                    "comment_management_challenge",
                    """
                    CREATE TABLE IF NOT EXISTS comment_management_challenge (
                        challenge_hash varchar(64) PRIMARY KEY,
                        comment_id bigint NOT NULL,
                        purpose varchar(24) NOT NULL,
                        expires_at_utc timestamp without time zone NOT NULL,
                        used_at_utc timestamp without time zone NULL,
                        CONSTRAINT ck_comment_management_challenge_purpose CHECK (purpose IN ('edit', 'delete', 'status', 'appeal'))
                    );
                    """),
                new EnsureTableStep(
                    "comment_author_appeal",
                    """
                    CREATE TABLE IF NOT EXISTS comment_author_appeal (
                        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        comment_id bigint NOT NULL,
                        reason varchar(1000) NOT NULL,
                        created_at_utc timestamp without time zone NOT NULL,
                        author_mode varchar(32) NOT NULL,
                        account_id integer NULL,
                        status varchar(24) NOT NULL DEFAULT 'pending'
                    );
                    """),
                new CreateIndexStep(
                    "idx_comment_revision_comment_time",
                    "CREATE INDEX IF NOT EXISTS idx_comment_revision_comment_time ON comment_revision(comment_id, created_at_utc DESC, id DESC);"),
                new CreateIndexStep(
                    "idx_comment_management_challenge_expiry",
                    "CREATE INDEX IF NOT EXISTS idx_comment_management_challenge_expiry ON comment_management_challenge(expires_at_utc);"),
                new CreateIndexStep(
                    "idx_comment_author_appeal_comment_created",
                    "CREATE INDEX IF NOT EXISTS idx_comment_author_appeal_comment_created ON comment_author_appeal(comment_id, created_at_utc DESC);"),
                new RawSqlStep(
                    """
                    DO $$
                    BEGIN
                    IF to_regclass('comment') IS NOT NULL THEN
                        IF to_regclass('comment_revision') IS NOT NULL
                           AND NOT EXISTS (
                               SELECT 1 FROM pg_constraint
                               WHERE conname = 'fk_comment_revision_comment'
                           ) THEN
                            EXECUTE 'ALTER TABLE comment_revision
                                ADD CONSTRAINT fk_comment_revision_comment
                                FOREIGN KEY (comment_id) REFERENCES comment(id) ON DELETE RESTRICT';
                        END IF;
                        IF to_regclass('comment_management_challenge') IS NOT NULL
                           AND NOT EXISTS (
                               SELECT 1 FROM pg_constraint
                               WHERE conname = 'fk_comment_management_challenge_comment'
                           ) THEN
                            EXECUTE 'ALTER TABLE comment_management_challenge
                                ADD CONSTRAINT fk_comment_management_challenge_comment
                                FOREIGN KEY (comment_id) REFERENCES comment(id) ON DELETE CASCADE';
                        END IF;
                        IF to_regclass('comment_author_appeal') IS NOT NULL
                           AND NOT EXISTS (
                               SELECT 1 FROM pg_constraint
                               WHERE conname = 'fk_comment_author_appeal_comment'
                           ) THEN
                            EXECUTE 'ALTER TABLE comment_author_appeal
                                ADD CONSTRAINT fk_comment_author_appeal_comment
                                FOREIGN KEY (comment_id) REFERENCES comment(id) ON DELETE RESTRICT';
                        END IF;
                    END IF;
                    END $$;
                    """),
                new BackfillCommentInitialRevisionStep()
            ]);

    private sealed record BackfillCommentInitialRevisionStep : SchemaMigrationStep
    {
        private const int BatchSize = 500;

        internal override string Kind => "BackfillCommentInitialRevision";
        internal override string Fingerprint => "comment_revision:v1:sha256:batch500";
        internal override SchemaMigrationCommand? BuildCommand(ISchemaDdlProvider ddl) => null;

        internal override async Task ExecuteAsync(ISqlSugarClient db, CancellationToken cancellationToken)
        {
            int commentExists = await db.Ado.GetIntAsync(
                "SELECT CASE WHEN to_regclass('comment') IS NULL THEN 0 ELSE 1 END");
            if (commentExists == 0)
            {
                return;
            }

            long lastId = 0;
            while (true)
            {
                cancellationToken.ThrowIfCancellationRequested();
                List<CommentRevisionBackfillSource> comments = await db.Queryable<Comment>()
                    .Where(item => item.Id > lastId)
                    .OrderBy(item => item.Id, OrderByType.Asc)
                    .Take(BatchSize)
                    .Select(item => new CommentRevisionBackfillSource
                    {
                        Id = item.Id,
                        Content = item.Content,
                        CreateTime = item.CreateTime,
                        UserId = item.UserId,
                        AuthorMode = item.AuthorMode
                    })
                    .ToListAsync(cancellationToken);
                if (comments.Count == 0)
                {
                    return;
                }

                long[] ids = comments.Select(static item => item.Id).ToArray();
                HashSet<long> existing = (await db.Queryable<CommentRevision>()
                    .Where(item => ids.Contains(item.CommentId) && item.Version == 1)
                    .Select(item => item.CommentId)
                    .ToListAsync(cancellationToken)).ToHashSet();
                CommentRevision[] missing = comments
                    .Where(item => !existing.Contains(item.Id))
                    .Select(static item => new CommentRevision
                    {
                        CommentId = item.Id,
                        Version = 1,
                        Content = item.Content,
                        ContentSha256 = Convert.ToHexString(
                            SHA256.HashData(Encoding.UTF8.GetBytes(item.Content))).ToLowerInvariant(),
                        Operation = CommentRevisionOperations.Created,
                        CreatedAtUtc = DateTime.SpecifyKind(item.CreateTime, DateTimeKind.Utc),
                        ActorAccountId = item.UserId,
                        ActorAdminPrincipalId = null,
                        ActorMode = string.IsNullOrWhiteSpace(item.AuthorMode) ? "public" : item.AuthorMode
                    })
                    .ToArray();
                if (missing.Length > 0)
                {
                    await db.Insertable(missing).ExecuteCommandAsync(cancellationToken);
                }

                lastId = comments[^1].Id;
            }
        }

        private sealed class CommentRevisionBackfillSource
        {
            public long Id
            {
                get; init;
            }

            public string Content { get; init; } = string.Empty;

            public DateTime CreateTime
            {
                get; init;
            }

            public int? UserId
            {
                get; init;
            }

            public string AuthorMode { get; init; } = string.Empty;
        }
    }
}
