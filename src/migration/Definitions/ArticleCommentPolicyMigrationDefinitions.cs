namespace FsusBlog.Migration.Definitions;

internal static class ArticleCommentPolicyMigrationDefinitions
{
    internal const string MigrationId = "20260720-post-article-thread-comment-policy";

    internal static ISchemaMigrationDescriptor BuildMigration()
        => new SchemaMigrationDescriptor(
            MigrationId,
            "Add inheritable article comment policy, thread locks, privacy-safe slow mode and audit events.",
            SchemaMigrationPhase.PostCodeFirst,
            Transactional: true,
            Steps:
            [
                new EnsureTableStep("article_comment_policy", """
                    CREATE TABLE IF NOT EXISTS article_comment_policy (
                        article_id integer PRIMARY KEY REFERENCES article(id) ON DELETE CASCADE,
                        enabled boolean NULL,
                        public_comments_enabled boolean NULL,
                        anonymous_comments_enabled boolean NULL,
                        moderation_mode varchar(24) NULL,
                        slow_mode_seconds integer NULL,
                        closed_at_utc timestamp without time zone NULL,
                        updated_by_admin_principal_id bigint NOT NULL,
                        policy_version bigint NOT NULL DEFAULT 1,
                        updated_at_utc timestamp without time zone NOT NULL,
                        CONSTRAINT ck_article_comment_moderation_mode CHECK (moderation_mode IS NULL OR moderation_mode IN ('direct','premoderated','risk_based')),
                        CONSTRAINT ck_article_comment_slow_mode CHECK (slow_mode_seconds IS NULL OR slow_mode_seconds BETWEEN 0 AND 86400)
                    );
                    """),
                new EnsureTableStep("comment_thread_policy", """
                    CREATE TABLE IF NOT EXISTS comment_thread_policy (
                        root_comment_id bigint PRIMARY KEY REFERENCES comment(id) ON DELETE CASCADE,
                        article_id integer NOT NULL REFERENCES article(id) ON DELETE CASCADE,
                        locked_at_utc timestamp without time zone NULL,
                        locked_by_admin_principal_id bigint NULL,
                        lock_reason varchar(256) NULL,
                        policy_version bigint NOT NULL DEFAULT 1
                    );
                    """),
                new CreateIndexStep("idx_comment_thread_policy_article", "CREATE INDEX IF NOT EXISTS idx_comment_thread_policy_article ON comment_thread_policy(article_id, root_comment_id);"),
                new EnsureTableStep("comment_slow_mode_state", """
                    CREATE TABLE IF NOT EXISTS comment_slow_mode_state (
                        article_id integer NOT NULL REFERENCES article(id) ON DELETE CASCADE,
                        subject_hash varchar(64) NOT NULL,
                        next_allowed_at_utc timestamp without time zone NOT NULL,
                        PRIMARY KEY(article_id, subject_hash)
                    );
                    """),
                new CreateIndexStep("idx_comment_slow_mode_expiry", "CREATE INDEX IF NOT EXISTS idx_comment_slow_mode_expiry ON comment_slow_mode_state(next_allowed_at_utc);"),
                new EnsureTableStep("comment_policy_audit_event", """
                    CREATE TABLE IF NOT EXISTS comment_policy_audit_event (
                        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        article_id integer NOT NULL REFERENCES article(id) ON DELETE RESTRICT,
                        root_comment_id bigint NULL REFERENCES comment(id) ON DELETE RESTRICT,
                        policy_version bigint NOT NULL,
                        action varchar(32) NOT NULL,
                        reason varchar(256) NULL,
                        admin_principal_id bigint NOT NULL,
                        occurred_at_utc timestamp without time zone NOT NULL
                    );
                    """),
                new CreateIndexStep("idx_comment_policy_audit_article", "CREATE INDEX IF NOT EXISTS idx_comment_policy_audit_article ON comment_policy_audit_event(article_id, occurred_at_utc DESC, id DESC);")
            ]);
}
