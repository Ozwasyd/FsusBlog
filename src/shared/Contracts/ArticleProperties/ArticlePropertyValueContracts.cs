namespace FsusBlog.Shared.Contracts.ArticleProperties;

/// <summary>Presence is independent of the eight definition-owned value types.</summary>
public enum ArticlePropertyValuePresence : byte
{
    Missing = 0,
    Null = 1,
    Present = 2
}

/// <summary>Closed typed payloads; type registration remains owned by PropertyDefinition.</summary>
public abstract record ArticlePropertyTypedValue
{
    private protected ArticlePropertyTypedValue()
    {
    }
}

/// <summary>Plain Unicode text; definition-owned normalization and bounds apply.</summary>
public sealed record ArticlePropertyTextValue(string Text) : ArticlePropertyTypedValue;
/// <summary>Exact decimal number, retaining zero without string or floating-point coercion.</summary>
public sealed record ArticlePropertyNumberValue(decimal Number) : ArticlePropertyTypedValue;
/// <summary>Explicit boolean, retaining false independently of missing/null.</summary>
public sealed record ArticlePropertyBooleanValue(bool Boolean) : ArticlePropertyTypedValue;
/// <summary>UTC instant; local or unspecified DateTime kinds are invalid.</summary>
public sealed record ArticlePropertyDateValue(DateTime Utc) : ArticlePropertyTypedValue;
/// <summary>One stable definition-owned option identity, never its label.</summary>
public sealed record ArticlePropertySingleSelectValue(Guid OptionId) : ArticlePropertyTypedValue;
/// <summary>URL subject to the definition's allowed schemes and canonical normalization.</summary>
public sealed record ArticlePropertyUrlValue(string Url) : ArticlePropertyTypedValue;

/// <summary>Owned immutable copy of stable option identities; duplicate identities are invalid.</summary>
public sealed record ArticlePropertyMultiSelectValue : ArticlePropertyTypedValue
{
    public ArticlePropertyMultiSelectValue(IEnumerable<Guid> optionIds)
    {
        ArgumentNullException.ThrowIfNull(optionIds);
        OptionIds = Array.AsReadOnly(optionIds.ToArray());
    }

    public IReadOnlyList<Guid> OptionIds
    {
        get;
    }
}

/// <summary>Owned immutable copy of article identities; target permission/lifecycle requires its authority.</summary>
public sealed record ArticlePropertyArticleReferenceValue : ArticlePropertyTypedValue
{
    public ArticlePropertyArticleReferenceValue(IEnumerable<long> articleIds)
    {
        ArgumentNullException.ThrowIfNull(articleIds);
        ArticleIds = Array.AsReadOnly(articleIds.ToArray());
    }

    public IReadOnlyList<long> ArticleIds
    {
        get;
    }
}

/// <summary>Expected definition coordinates are mandatory even for missing/null values.</summary>
public sealed record ArticlePropertyValueInput(
    Guid DefinitionId,
    long DefinitionSchemaRevision,
    string DefinitionDigest,
    ArticlePropertyValuePresence Presence,
    ArticlePropertyTypedValue? Value);

/// <summary>
/// Pure normalized value bound to the exact observed definition. DefaultApplied records normalization
/// provenance and is part of the digest; it is not caller authority or a durable receipt.
/// </summary>
public sealed record ArticlePropertyValueEntry(
    Guid DefinitionId,
    long DefinitionSchemaRevision,
    string DefinitionDigest,
    ArticlePropertyValuePresence Presence,
    ArticlePropertyTypedValue? Value,
    string ValueDigest,
    bool DefaultApplied = false);

/// <summary>Coordinates supplied by the canonical article authority, never generated by a planner.</summary>
public sealed record ArticlePropertySnapshotCoordinates(
    long? DefinitionOwnerUserId,
    string SiteScope,
    int ArticleId,
    long PropertyRevision,
    long ArticleRevisionId,
    long? DraftId = null,
    long? DraftServerRevision = null,
    long? PublicationId = null);

/// <summary>
/// Immutable value snapshot candidate. Validation and a digest do not establish persistence,
/// current authorization, or transaction acceptance; the article writer must recheck its inputs.
/// </summary>
public sealed record ArticlePropertyValueSnapshot
{
    public const int CurrentSchemaVersion = 1;

    public ArticlePropertyValueSnapshot(
        int schemaVersion,
        ArticlePropertySnapshotCoordinates coordinates,
        IEnumerable<ArticlePropertyValueEntry> values,
        string contentDigest)
    {
        ArgumentNullException.ThrowIfNull(coordinates);
        ArgumentNullException.ThrowIfNull(values);
        SchemaVersion = schemaVersion;
        Coordinates = coordinates;
        Values = Array.AsReadOnly(values.ToArray());
        ContentDigest = contentDigest;
    }

    public int SchemaVersion
    {
        get;
    }
    public ArticlePropertySnapshotCoordinates Coordinates
    {
        get;
    }
    public IReadOnlyList<ArticlePropertyValueEntry> Values
    {
        get;
    }
    public string ContentDigest
    {
        get;
    }
}
