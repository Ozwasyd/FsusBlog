def _iso(day_offset: int) -> str:
    return (BASE_TIME + timedelta(days=day_offset)).isoformat().replace("+00:00", "Z")


def _article(
    article_id: int,
    title: str,
    summary: str,
    body: str,
    category_id: int,
    tag_ids: list[int],
    day_offset: int,
    topic_group: str,
) -> dict[str, Any]:
    cat_map = dict(CATEGORIES)
    tag_map = dict(TAGS)
    return {
        "id": article_id,
        "revision": 1,
        "publication": 100_000 + article_id,
        "revisionNo": 1,
        "publicationNo": 1,
        "title": title,
        "summary": summary,
        "body": body,
        "createdAt": _iso(day_offset),
        "updatedAt": _iso(day_offset),
        "publishedAt": _iso(day_offset),
        "category": {"id": category_id, "name": cat_map[category_id]},
        "tags": [{"id": tid, "name": tag_map[tid]} for tid in tag_ids],
        "synthetic": True,
        "topicGroup": topic_group,
    }


