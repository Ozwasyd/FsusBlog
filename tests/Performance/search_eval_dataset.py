def generate() -> None:
    EVAL_DIR.mkdir(parents=True, exist_ok=True)
    articles, queries = _build_corpus_and_queries()
    corpus_payload = {
        "schemaVersion": "fsusblog-search-eval-corpus-v1",
        "corpusVersion": CORPUS_VERSION,
        "synthetic": True,
        "articleCount": len(articles),
        "articles": articles,
    }
    queries_payload = {
        "schemaVersion": "fsusblog-search-eval-queries-v1",
        "querySetVersion": QUERY_SET_VERSION,
        "judgmentsVersion": JUDGMENTS_VERSION,
        "synthetic": True,
        "queryCount": len(queries),
        "categories": list(QUERY_CATEGORIES),
        "queries": queries,
    }
    corpus_text = canonical_json(corpus_payload)
    queries_text = canonical_json(queries_payload)
    config_payload = build_config(sha256_text(corpus_text), sha256_text(queries_text), len(articles), len(queries))
    config_text = canonical_json(config_payload)

    CORPUS_PATH.write_text(corpus_text, encoding="utf-8")
    QUERIES_PATH.write_text(queries_text, encoding="utf-8")
    CONFIG_PATH.write_text(config_text, encoding="utf-8")
    print(f"Generated {len(articles)} synthetic articles and {len(queries)} synthetic queries in {EVAL_DIR}")


def verify() -> None:
    config = json.loads(CONFIG_PATH.read_text(encoding="utf-8"))
    corpus_text = CORPUS_PATH.read_text(encoding="utf-8")
    queries_text = QUERIES_PATH.read_text(encoding="utf-8")
    corpus = json.loads(corpus_text)
    queries_doc = json.loads(queries_text)

    prov = config["provenance"]
    assert prov["corpusType"] == "synthetic", "Corpus must be explicitly labeled synthetic"
    assert prov["containsPrivateDrafts"] is False
    assert prov["containsReaderQueryHistory"] is False
    assert sha256_text(corpus_text) == prov["corpusSha256"], "corpus.v1.json SHA-256 mismatch"
    assert sha256_text(queries_text) == prov["queriesSha256"], "queries.v1.json SHA-256 mismatch"

    articles = corpus["articles"]
    queries = queries_doc["queries"]
    assert 300 <= len(queries) <= 500, f"Expected 300..500 queries, got {len(queries)}"
    assert len(articles) == prov["articleCount"] == corpus["articleCount"]
    assert len(queries) == prov["queryCount"] == queries_doc["queryCount"]

    article_ids = {a["id"] for a in articles}
    assert len(article_ids) == len(articles), "Duplicate article IDs in corpus"
    assert all(a["synthetic"] is True for a in articles), "Every article must be labeled synthetic"

    seen_qids: set[str] = set()
    by_cat_split: dict[tuple[str, str], int] = {}
    for q in queries:
        assert q["synthetic"] is True, f"Query {q['id']} missing synthetic=true"
        assert q["id"] not in seen_qids, f"Duplicate query id {q['id']}"
        seen_qids.add(q["id"])
        assert q["split"] in ("tuning", "holdout"), f"Invalid split {q['split']}"
        assert q["category"] in QUERY_CATEGORIES, f"Unknown category {q['category']}"
        key = (q["category"], q["split"])
        by_cat_split[key] = by_cat_split.get(key, 0) + 1
        for tid in q["targetArticleIds"]:
            assert tid in article_ids, f"Query {q['id']} references unknown target article {tid}"
            assert str(tid) in q["judgments"], f"Query {q['id']} target {tid} missing judgment grade"
        for aid_str, grade in q["judgments"].items():
            assert int(aid_str) in article_ids, f"Query {q['id']} judgment references unknown article {aid_str}"
            assert grade in (1, 2, 3), f"Invalid grade {grade}"
        if q["expectedEmpty"]:
            assert not q["targetArticleIds"] and not q["judgments"]

    for cat in QUERY_CATEGORIES:
        t_cnt = by_cat_split.get((cat, "tuning"), 0)
        h_cnt = by_cat_split.get((cat, "holdout"), 0)
        assert t_cnt > 0 and h_cnt > 0, f"Category {cat} must appear in both tuning and holdout splits"

    gates = config["provisionalGates"]
    assert gates["provisional"] is True, "Initial gates must be explicitly marked provisional"
    print(f"Verified search eval dataset: {len(articles)} articles, {len(queries)} queries across {len(QUERY_CATEGORIES)} categories.")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=("generate", "verify"))
    args = parser.parse_args()
    if args.action == "generate":
        generate()
    else:
        verify()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
