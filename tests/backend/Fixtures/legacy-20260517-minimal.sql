CREATE TABLE sys_visit_log (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ip varchar(255) NOT NULL,
    userid integer,
    region varchar(255) NOT NULL,
    createtime timestamp NOT NULL
);

CREATE TABLE tag (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL
);

