using FsusBlog.Core.Services.Articles;
using FsusBlog.Server.Entities;
using FsusBlog.Server.Services;
using FsusBlog.Server.Tests.TestInfrastructure;

using SqlSugar;

namespace FsusBlog.Server.Tests;

[Trait("Category", "Integration")]
[Trait("Dependency", "Docker")]
[Collection(nameof(SchemaMigrationPostgresCollectionA))]
public sealed class ArticleStatusTransitionIntegrationTests(PostgresSchemaMigrationFixture fixture)
{
    private static readonly DateTime s_now = new(2026, 7, 19, 8, 0, 0, DateTimeKind.Utc);

    [Fact]
    public async Task Writer_ValidatesPersistedSourceAndAppliesArchiveAndRestoreWithFixedTime()
    {
        string databaseName = await fixture.CreateDatabaseAsync();
        string connectionString = fixture.BuildDatabaseConnectionString(databaseName);
        await fixture.ExecuteAsync(connectionString, """
            CREATE TABLE article (
                id integer PRIMARY KEY,
                current_revision_id bigint NULL,
                current_publication_id bigint NULL,
                status integer NOT NULL,
                scheduled_publish_at timestamp NULL,
                pending_publication_at timestamp NULL,
                published_at timestamp NULL,
                last_published_at timestamp NULL,
                public_updated_at timestamp NULL,
                archived_at timestamp NULL,
                deleted_at timestamp NULL,
                isdeleted boolean NOT NULL DEFAULT false
            );

            CREATE TABLE article_publication (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                article_id integer NOT NULL,
                publication_no integer NOT NULL,
                article_revision_id bigint NOT NULL,
                revision_no integer NOT NULL,
                rights_snapshot_id bigint NOT NULL,
                responsibility_snapshot_id bigint NULL,
                transition_kind varchar(64) NOT NULL,
                published_at timestamp NOT NULL,
                created_at timestamp NOT NULL
            );

            INSERT INTO article(id, status, isdeleted)
            VALUES (42, 0, false);
            """);
        using SqlSugarClient db = PostgresSqlSugarTestClient.Create(connectionString);
        ArticleVersionCoordinates revision = ArticleVersionCoordinates.Revision(101, 1, 201);

        await ArticlePublicationTransitionWriter.ApplyAsync(
            db,
            new ArticlePublicationTransitionRequest(
                42,
                revision,
                ArticleStatus.Archived,
                null,
                s_now,
                ArticlePublicationTransitionKinds.Archive,
                ArticleStatusTransitionOperation.Update));

        int archivedStatus = await fixture.QueryScalarAsync<int>(
            connectionString,
            "SELECT status FROM article WHERE id = 42;");
        DateTime archivedAt = await fixture.QueryScalarAsync<DateTime>(
            connectionString,
            "SELECT archived_at FROM article WHERE id = 42;");
        Assert.Equal((int)ArticleStatus.Archived, archivedStatus);
        Assert.Equal(s_now, DateTime.SpecifyKind(archivedAt, DateTimeKind.Utc));

        ArticleStatusTransitionValidationException invalidRestore = await Assert.ThrowsAsync<ArticleStatusTransitionValidationException>(
            () => ArticlePublicationTransitionWriter.ApplyAsync(
                db,
                new ArticlePublicationTransitionRequest(
                    42,
                    revision,
                    ArticleStatus.Published,
                    null,
                    s_now.AddMinutes(1),
                    ArticlePublicationTransitionKinds.Restore,
                    ArticleStatusTransitionOperation.Restore)));
        Assert.Equal(ArticleStatusTransitionErrorCodes.InvalidTransition, invalidRestore.Validation.Code);

        await fixture.ExecuteAsync(connectionString, """
            UPDATE article
            SET status = 4,
                isdeleted = false,
                deleted_at = NULL
            WHERE id = 42;
            """);

        ArticleVersionCoordinates restored = await ArticlePublicationTransitionWriter.ApplyAsync(
            db,
            new ArticlePublicationTransitionRequest(
                42,
                revision,
                ArticleStatus.Published,
                null,
                s_now.AddMinutes(2),
                ArticlePublicationTransitionKinds.Restore,
                ArticleStatusTransitionOperation.Restore));

        Assert.NotNull(restored.PublicationId);
        Assert.Equal(1, restored.PublicationNo);
        int restoredStatus = await fixture.QueryScalarAsync<int>(
            connectionString,
            "SELECT status FROM article WHERE id = 42;");
        long publicationCount = await fixture.QueryScalarAsync<long>(
            connectionString,
            "SELECT COUNT(*) FROM article_publication WHERE article_id = 42;");
        DateTime firstPublishedAt = await fixture.QueryScalarAsync<DateTime>(
            connectionString,
            "SELECT published_at FROM article WHERE id = 42;");
        DateTime lastPublishedAt = await fixture.QueryScalarAsync<DateTime>(
            connectionString,
            "SELECT last_published_at FROM article WHERE id = 42;");
        DateTime publicUpdatedAt = await fixture.QueryScalarAsync<DateTime>(
            connectionString,
            "SELECT public_updated_at FROM article WHERE id = 42;");
        Assert.Equal((int)ArticleStatus.Published, restoredStatus);
        Assert.Equal(1, publicationCount);
        Assert.Equal(s_now.AddMinutes(2), DateTime.SpecifyKind(firstPublishedAt, DateTimeKind.Utc));
        Assert.Equal(s_now.AddMinutes(2), DateTime.SpecifyKind(lastPublishedAt, DateTimeKind.Utc));
        Assert.Equal(s_now.AddMinutes(2), DateTime.SpecifyKind(publicUpdatedAt, DateTimeKind.Utc));

        await ArticlePublicationTransitionWriter.ApplyAsync(
            db,
            new ArticlePublicationTransitionRequest(
                42,
                revision,
                ArticleStatus.Published,
                null,
                s_now.AddMinutes(3),
                ArticlePublicationTransitionKinds.ImmediatePublish,
                ArticleStatusTransitionOperation.Update));

        firstPublishedAt = await fixture.QueryScalarAsync<DateTime>(
            connectionString,
            "SELECT published_at FROM article WHERE id = 42;");
        lastPublishedAt = await fixture.QueryScalarAsync<DateTime>(
            connectionString,
            "SELECT last_published_at FROM article WHERE id = 42;");
        publicUpdatedAt = await fixture.QueryScalarAsync<DateTime>(
            connectionString,
            "SELECT public_updated_at FROM article WHERE id = 42;");
        publicationCount = await fixture.QueryScalarAsync<long>(
            connectionString,
            "SELECT COUNT(*) FROM article_publication WHERE article_id = 42;");
        Assert.Equal(s_now.AddMinutes(2), DateTime.SpecifyKind(firstPublishedAt, DateTimeKind.Utc));
        Assert.Equal(s_now.AddMinutes(3), DateTime.SpecifyKind(lastPublishedAt, DateTimeKind.Utc));
        Assert.Equal(s_now.AddMinutes(3), DateTime.SpecifyKind(publicUpdatedAt, DateTimeKind.Utc));
        Assert.Equal(2, publicationCount);
    }

    [Fact]
    public async Task Writer_RejectsDeletedTargetBeforeMutatingPostgres()
    {
        string databaseName = await fixture.CreateDatabaseAsync();
        string connectionString = fixture.BuildDatabaseConnectionString(databaseName);
        await fixture.ExecuteAsync(connectionString, """
            CREATE TABLE article (
                id integer PRIMARY KEY,
                current_revision_id bigint NULL,
                current_publication_id bigint NULL,
                status integer NOT NULL,
                scheduled_publish_at timestamp NULL,
                pending_publication_at timestamp NULL,
                published_at timestamp NULL,
                archived_at timestamp NULL,
                isdeleted boolean NOT NULL DEFAULT false
            );

            CREATE TABLE article_publication (
                id bigint PRIMARY KEY,
                article_id integer NOT NULL,
                publication_no integer NOT NULL
            );

            INSERT INTO article(id, status, isdeleted)
            VALUES (43, 2, false);
            """);
        using SqlSugarClient db = PostgresSqlSugarTestClient.Create(connectionString);

        ArticleStatusTransitionValidationException error = await Assert.ThrowsAsync<ArticleStatusTransitionValidationException>(
            () => ArticlePublicationTransitionWriter.ApplyAsync(
                db,
                new ArticlePublicationTransitionRequest(
                    43,
                    ArticleVersionCoordinates.Revision(102, 1, 202),
                    ArticleStatus.Deleted,
                    null,
                    s_now,
                    ArticlePublicationTransitionKinds.Archive,
                    ArticleStatusTransitionOperation.Update)));

        Assert.Equal(ArticleStatusTransitionErrorCodes.DeletedRequiresDeleteFlow, error.Validation.Code);
        int persistedStatus = await fixture.QueryScalarAsync<int>(
            connectionString,
            "SELECT status FROM article WHERE id = 43;");
        Assert.Equal((int)ArticleStatus.Published, persistedStatus);
    }
}
