using Npgsql;

namespace FsusBlog.Server.Tests;

[Trait("Category", "Integration")]
[Trait("Dependency", "Docker")]
[Collection(nameof(SchemaMigrationPostgresCollectionA))]
public sealed class PostgresLockTimeoutRecoveryIntegrationTests(PostgresSchemaMigrationFixture fixture)
{
    [Fact]
    public async Task PostgresLockTimeoutSimulation_RollsBackAndAllowsFollowUpQuery()
    {
        string databaseName = await fixture.CreateDatabaseAsync();
        string connectionString = fixture.BuildDatabaseConnectionString(databaseName);

        await fixture.ExecuteAsync(connectionString, """
            CREATE TABLE article (
                id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                title varchar(256) NOT NULL
            );

            INSERT INTO article(title) VALUES ('baseline');
            """);

        await using var holder = new NpgsqlConnection(connectionString);
        await holder.OpenAsync();
        await using NpgsqlTransaction holderTransaction = await holder.BeginTransactionAsync();
        await using (NpgsqlCommand lockCommand = holder.CreateCommand())
        {
            lockCommand.Transaction = holderTransaction;
            lockCommand.CommandText = """
                LOCK TABLE article IN ACCESS EXCLUSIVE MODE;
                INSERT INTO article(title) VALUES ('holder-uncommitted');
                """;
            await lockCommand.ExecuteNonQueryAsync();
            lockCommand.CommandText = "SELECT COUNT(1) FROM article;";
            Assert.Equal(2L, await lockCommand.ExecuteScalarAsync());
        }

        await using var contender = new NpgsqlConnection(connectionString);
        await contender.OpenAsync();
        Assert.NotEqual(holder.ProcessID, contender.ProcessID);
        await using (NpgsqlCommand timeoutCommand = contender.CreateCommand())
        {
            timeoutCommand.CommandText = "SET lock_timeout = '500ms';";
            await timeoutCommand.ExecuteNonQueryAsync();
            timeoutCommand.CommandText = "SHOW lock_timeout;";
            Assert.Equal("500ms", await timeoutCommand.ExecuteScalarAsync());
        }

        await using (NpgsqlTransaction contenderTransaction = await contender.BeginTransactionAsync())
        {
            await using NpgsqlCommand writeCommand = contender.CreateCommand();
            writeCommand.Transaction = contenderTransaction;
            writeCommand.CommandText = "INSERT INTO article(title) VALUES ('blocked-write');";

            Task<int> blockedWrite = writeCommand.ExecuteNonQueryAsync();
            bool observedLockWait = false;
            try
            {
                await using NpgsqlCommand observationCommand = holder.CreateCommand();
                observationCommand.Transaction = holderTransaction;
                observationCommand.CommandText = """
                    SELECT EXISTS (
                        SELECT 1
                        FROM pg_locks AS waiting_lock
                        WHERE waiting_lock.pid = @contender_pid
                          AND @holder_pid = ANY(pg_blocking_pids(waiting_lock.pid))
                          AND waiting_lock.relation = 'article'::regclass
                          AND waiting_lock.mode = 'RowExclusiveLock'
                          AND NOT waiting_lock.granted
                    );
                    """;
                observationCommand.Parameters.AddWithValue("contender_pid", contender.ProcessID);
                observationCommand.Parameters.AddWithValue("holder_pid", holder.ProcessID);
                while (!blockedWrite.IsCompleted)
                {
                    if (await observationCommand.ExecuteScalarAsync() is true)
                    {
                        observedLockWait = true;
                        break;
                    }

                    await Task.Delay(10);
                }
            }
            finally
            {
                // Finish the in-flight command before either connection or transaction is disposed.
                PostgresException exception = await Assert.ThrowsAsync<PostgresException>(
                    async () => await blockedWrite);
                Assert.Equal(PostgresErrorCodes.LockNotAvailable, exception.SqlState);
            }

            Assert.True(observedLockWait, "The contender must wait on the holder's article table lock.");

            await using NpgsqlCommand failedTransactionQuery = contender.CreateCommand();
            failedTransactionQuery.Transaction = contenderTransaction;
            failedTransactionQuery.CommandText = "SELECT 1;";
            PostgresException abortedTransaction = await Assert.ThrowsAsync<PostgresException>(
                async () => await failedTransactionQuery.ExecuteScalarAsync());
            Assert.Equal(PostgresErrorCodes.InFailedSqlTransaction, abortedTransaction.SqlState);
            await contenderTransaction.RollbackAsync();
        }

        await using (NpgsqlCommand recoveredQuery = contender.CreateCommand())
        {
            recoveredQuery.CommandText = "SELECT 1;";
            Assert.Equal(1, await recoveredQuery.ExecuteScalarAsync());
        }

        await holderTransaction.RollbackAsync();

        await using (NpgsqlCommand recoveredQuery = contender.CreateCommand())
        {
            recoveredQuery.CommandText = "SELECT COUNT(1) FROM article;";
            Assert.Equal(1L, await recoveredQuery.ExecuteScalarAsync());
            recoveredQuery.CommandText = "SELECT title FROM article;";
            Assert.Equal("baseline", await recoveredQuery.ExecuteScalarAsync());
            recoveredQuery.CommandText = "SELECT 1;";
            Assert.Equal(1, await recoveredQuery.ExecuteScalarAsync());
        }

        await using (NpgsqlCommand holderQuery = holder.CreateCommand())
        {
            holderQuery.CommandText = "SELECT COUNT(1) FROM article;";
            Assert.Equal(1L, await holderQuery.ExecuteScalarAsync());
            holderQuery.CommandText = "SELECT 1;";
            Assert.Equal(1, await holderQuery.ExecuteScalarAsync());
        }

        int articleRows = await fixture.QueryScalarAsync<int>(connectionString, "SELECT COUNT(1) FROM article;");
        int followUpQuery = await fixture.QueryScalarAsync<int>(connectionString, "SELECT 1;");

        Assert.Equal(1, articleRows);
        Assert.Equal(1, followUpQuery);
    }
}
