using System.Data;

using FsusBlog.Server.Infrastructure.SchemaMigration;
using FsusBlog.Server.Infrastructure.SchemaMigration.Definitions;
using FsusBlog.Server.Tests.TestInfrastructure;

using SqlSugar;

namespace FsusBlog.Server.Tests.Unit;

public sealed class ArticleDraftServerRevisionMigrationContractTests
{
    [Fact]
    public void Descriptor_IsAdditiveAndExplicitlyClassified()
    {
        ISchemaMigrationDescriptor descriptor = ArticleDraftServerRevisionMigrationDefinitions.BuildMigration();
        OnlineSchemaMigrationMetadata metadata = new OnlineSchemaMigrationCatalog().GetMetadata()[descriptor.MigrationId];

        Assert.Equal(SchemaMigrationPhase.PreCodeFirst, descriptor.Phase);
        Assert.True(descriptor.Transactional);
        Assert.Equal(OnlineSchemaMigrationPhase.Expand, metadata.Phase);
        Assert.False(metadata.Destructive);
        Assert.False(metadata.RequiresExclusiveMode);
        Assert.Equal(OnlineSchemaMigrationRollbackMode.CompatibleCode, metadata.RollbackMode);
        Assert.Contains("mixed_release_draft_write_fence", metadata.Validators);
        Assert.DoesNotContain("n_minus_one_read_write", metadata.Validators);
        Assert.Contains("server_revision", Assert.Single(descriptor.Steps).Fingerprint, StringComparison.Ordinal);
    }
}

[Trait("Dependency", "Docker")]
[Collection(nameof(SchemaMigrationPostgresCollectionB))]
public sealed class ArticleDraftServerRevisionMigrationDatabaseTests(PostgresSchemaMigrationFixture fixture)
{
    [Fact]
    public async Task ExistingDraftsBecomeVersionOneAndMigrationIsIdempotent()
    {
        using SqlSugarClient db = await PostgresSqlSugarTestClient.CreateAsync(fixture);
        await db.Ado.ExecuteCommandAsync(
            """
            CREATE TABLE article_draft (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                owner_admin_principal_id bigint NOT NULL,
                draft_key varchar(96) NOT NULL
            );
            INSERT INTO article_draft(owner_admin_principal_id, draft_key) VALUES (7, 'existing');
            """);
        ISchemaMigrationDescriptor descriptor = ArticleDraftServerRevisionMigrationDefinitions.BuildMigration();

        await ApplyAsync(db, descriptor);
        await ApplyAsync(db, descriptor);

        DataTable result = await db.Ado.GetDataTableAsync(
            "SELECT server_revision FROM article_draft WHERE draft_key = 'existing';");
        Assert.Equal(1L, Convert.ToInt64(result.Rows[0]["server_revision"]));
    }

    private static async Task ApplyAsync(ISqlSugarClient db, ISchemaMigrationDescriptor descriptor)
    {
        foreach (SchemaMigrationStep step in descriptor.Steps)
        {
            await step.ExecuteAsync(db, CancellationToken.None);
        }
    }
}
