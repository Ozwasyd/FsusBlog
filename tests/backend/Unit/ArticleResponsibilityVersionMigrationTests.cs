using System.Data;

using FsusBlog.Server.Infrastructure.SchemaMigration;
using FsusBlog.Server.Infrastructure.SchemaMigration.Definitions;
using FsusBlog.Server.Tests.TestInfrastructure;

using SqlSugar;

namespace FsusBlog.Server.Tests.Unit;

public sealed class ArticleResponsibilityVersionMigrationContractTests
{
    [Fact]
    public void Descriptor_IsAdditiveAppendOnlyAndBackfillsExactCoordinates()
    {
        ISchemaMigrationDescriptor descriptor = ArticleResponsibilityVersionMigrationDefinitions.BuildMigration();
        string fingerprint = string.Join('\n', descriptor.Steps.Select(step => step.Fingerprint));

        Assert.Equal(SchemaMigrationPhase.PreCodeFirst, descriptor.Phase);
        Assert.True(descriptor.Transactional);
        Assert.Contains("responsibility_version", fingerprint, StringComparison.Ordinal);
        Assert.Contains("previous_snapshot_id", fingerprint, StringComparison.Ordinal);
        Assert.Contains("ux_article_responsibility_revision_version", fingerprint, StringComparison.Ordinal);
        Assert.Contains("article_publication", fingerprint, StringComparison.Ordinal);
        Assert.Contains("article_mutation_outbox", fingerprint, StringComparison.Ordinal);
        Assert.DoesNotContain("DELETE FROM article_responsibility_snapshot", fingerprint, StringComparison.OrdinalIgnoreCase);
    }
}

[Trait("Dependency", "Docker")]
[Collection(nameof(SchemaMigrationPostgresCollectionB))]
public sealed class ArticleResponsibilityVersionMigrationDatabaseTests(PostgresSchemaMigrationFixture fixture)
{
    [Fact]
    public async Task ExistingRowsBecomeVersionOneAndPublicationOutboxPointersAreBackfilledIdempotently()
    {
        using SqlSugarClient db = await PostgresSqlSugarTestClient.CreateAsync(fixture);
        await db.Ado.ExecuteCommandAsync(
            """
            CREATE TABLE article_responsibility_snapshot (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                article_id integer NOT NULL,
                article_revision_id bigint NOT NULL,
                revision_no integer NOT NULL
            );
            CREATE UNIQUE INDEX ux_article_responsibility_revision
                ON article_responsibility_snapshot(article_revision_id);
            CREATE INDEX idx_article_responsibility_article_revision
                ON article_responsibility_snapshot(article_id, revision_no DESC);
            CREATE TABLE article_publication (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                article_id integer NOT NULL,
                article_revision_id bigint NOT NULL,
                responsibility_snapshot_id bigint NULL
            );
            CREATE TABLE article_mutation_outbox (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                aggregate_id integer NOT NULL,
                article_revision_id bigint NULL
            );
            INSERT INTO article_responsibility_snapshot(article_id, article_revision_id, revision_no)
            VALUES (7, 701, 4);
            INSERT INTO article_publication(article_id, article_revision_id, responsibility_snapshot_id)
            VALUES (7, 701, NULL);
            INSERT INTO article_mutation_outbox(aggregate_id, article_revision_id)
            VALUES (7, 701);
            """);
        ISchemaMigrationDescriptor descriptor = ArticleResponsibilityVersionMigrationDefinitions.BuildMigration();

        await ApplyAsync(db, descriptor);
        await ApplyAsync(db, descriptor);

        DataTable snapshot = await db.Ado.GetDataTableAsync(
            "SELECT id, responsibility_version, previous_snapshot_id FROM article_responsibility_snapshot;");
        Assert.Equal(1, Convert.ToInt32(snapshot.Rows[0]["responsibility_version"]));
        Assert.Equal(DBNull.Value, snapshot.Rows[0]["previous_snapshot_id"]);
        long snapshotId = Convert.ToInt64(snapshot.Rows[0]["id"]);
        Assert.Equal(snapshotId, await db.Ado.GetIntAsync("SELECT responsibility_snapshot_id FROM article_publication;"));
        Assert.Equal(snapshotId, await db.Ado.GetIntAsync("SELECT responsibility_snapshot_id FROM article_mutation_outbox;"));
        Assert.Equal(1, await db.Ado.GetIntAsync(
            "SELECT COUNT(1) FROM pg_indexes WHERE indexname = 'ux_article_responsibility_revision_version';"));
        Assert.Equal(0, await db.Ado.GetIntAsync(
            "SELECT COUNT(1) FROM pg_indexes WHERE indexname = 'ux_article_responsibility_revision';"));
    }

    private static async Task ApplyAsync(ISqlSugarClient db, ISchemaMigrationDescriptor descriptor)
    {
        foreach (SchemaMigrationStep step in descriptor.Steps)
        {
            await step.ExecuteAsync(db, CancellationToken.None);
        }
    }
}
