using System.Data;

using FsusBlog.Server.Infrastructure.SchemaMigration;
using FsusBlog.Server.Tests.TestInfrastructure;

using SqlSugar;

namespace FsusBlog.Server.Tests;

public sealed class ArticleRevisionRollbackMigrationTests
{
    [Fact]
    public void Descriptor_ExpandsRollbackProvenanceWithoutDestructiveDdl()
    {
        ISchemaMigrationDescriptor descriptor = Assert.Single(
            new SchemaMigrationRegistry().GetDescriptors(),
            static migration => migration.MigrationId == "20260720-pre-article-revision-rollback-package");
        string fingerprint = string.Join('\n', descriptor.Steps.Select(static step => step.Fingerprint));
        OnlineSchemaMigrationMetadata metadata = new OnlineSchemaMigrationCatalog()
            .GetMetadata()[descriptor.MigrationId];

        Assert.Equal(SchemaMigrationPhase.PreCodeFirst, descriptor.Phase);
        Assert.True(descriptor.Transactional);
        Assert.Contains("article_revision.rollback_source_revision_id", fingerprint, StringComparison.Ordinal);
        Assert.Contains("article_revision.rollback_reason", fingerprint, StringComparison.Ordinal);
        Assert.Contains("idx_article_revision_rollback_source", fingerprint, StringComparison.Ordinal);
        Assert.Equal(OnlineSchemaMigrationPhase.Expand, metadata.Phase);
        Assert.Equal(OnlineSchemaMigrationRollbackMode.CompatibleCode, metadata.RollbackMode);
        Assert.False(metadata.Destructive);
        Assert.False(metadata.RequiresExclusiveMode);
    }
}

[Trait("Dependency", "Docker")]
[Collection(nameof(SchemaMigrationPostgresCollectionB))]
public sealed class ArticleRevisionRollbackMigrationDatabaseTests(PostgresSchemaMigrationFixture fixture)
{
    [Fact]
    public async Task PreCodeFirstMigration_AddsNullableProvenanceAndIsIdempotent()
    {
        using SqlSugarClient db = await PostgresSqlSugarTestClient.CreateAsync(fixture);
        await db.Ado.ExecuteCommandAsync("""
            CREATE TABLE article_revision (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                article_id integer NOT NULL
            );
            INSERT INTO article_revision(article_id) VALUES (7);
            """);
        ISchemaMigrationDescriptor descriptor = Assert.Single(
            new SchemaMigrationRegistry().GetDescriptors(),
            static migration => migration.MigrationId == "20260720-pre-article-revision-rollback-package");

        await ApplyAsync(db, descriptor);
        await ApplyAsync(db, descriptor);

        DataTable columns = await db.Ado.GetDataTableAsync("""
            SELECT column_name, is_nullable, character_maximum_length
            FROM information_schema.columns
            WHERE table_schema = 'public'
              AND table_name = 'article_revision';
            """);
        Assert.Contains(columns.Rows.Cast<DataRow>(), static row =>
            string.Equals(Convert.ToString(row["column_name"]), "rollback_source_revision_id", StringComparison.Ordinal)
            && string.Equals(Convert.ToString(row["is_nullable"]), "YES", StringComparison.Ordinal));
        Assert.Contains(columns.Rows.Cast<DataRow>(), static row =>
            string.Equals(Convert.ToString(row["column_name"]), "rollback_reason", StringComparison.Ordinal)
            && string.Equals(Convert.ToString(row["is_nullable"]), "YES", StringComparison.Ordinal)
            && Convert.ToInt32(row["character_maximum_length"]) == 500);
        Assert.Equal(1, await db.Ado.GetIntAsync("""
            SELECT COUNT(1)
            FROM pg_indexes
            WHERE schemaname = 'public'
              AND tablename = 'article_revision'
              AND indexname = 'idx_article_revision_rollback_source';
            """));
        Assert.Equal(1, await db.Ado.GetIntAsync("SELECT COUNT(1) FROM article_revision;"));
    }

    private static async Task ApplyAsync(ISqlSugarClient db, ISchemaMigrationDescriptor descriptor)
    {
        foreach (SchemaMigrationStep step in descriptor.Steps)
        {
            await step.ExecuteAsync(db, CancellationToken.None);
        }
    }
}
