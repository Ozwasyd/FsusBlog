using FsusBlog.Server.Infrastructure.SchemaMigration;
using FsusBlog.Server.Tests.TestInfrastructure;

using SqlSugar;

namespace FsusBlog.Server.Tests.Unit;

[Trait("Dependency", "Docker")]
[Collection(nameof(SchemaMigrationPostgresCollectionB))]
public sealed class ReadEventRetirementMigrationDatabaseTests(PostgresSchemaMigrationFixture fixture)
{
    [Fact]
    public async Task RetirementDescriptors_RepairPartialLegacyTableThenDropAllTrajectoryStorage()
    {
        using SqlSugarClient db = await PostgresSqlSugarTestClient.CreateAsync(fixture);
        await db.Ado.ExecuteCommandAsync("""
            CREATE TABLE sys_visit_log (
                id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                ip varchar(64) NOT NULL DEFAULT '',
                userid integer NULL,
                user_id integer NULL,
                region varchar(64) NOT NULL DEFAULT '',
                createtime timestamp NOT NULL DEFAULT now()
            );
            INSERT INTO sys_visit_log(ip, userid, user_id, region)
            VALUES ('192.0.2.1', 7, 7, 'precise-region');

            CREATE TABLE article_view_projection_watermark (id integer PRIMARY KEY);
            CREATE TABLE daily_read_stats (
                stat_date date PRIMARY KEY,
                total_reads bigint NOT NULL,
                human_verified_reads bigint NOT NULL,
                unique_viewer_estimate bigint NOT NULL,
                updated_at_utc timestamp NOT NULL
            );
            INSERT INTO daily_read_stats VALUES (CURRENT_DATE, 1, 1, 1, now());
            CREATE TABLE region_read_stats (region text PRIMARY KEY, read_count bigint NOT NULL);
            INSERT INTO region_read_stats VALUES ('precise-region', 1);
            CREATE TABLE author_route_stats (route_key text PRIMARY KEY);
            INSERT INTO author_route_stats VALUES ('article:7');
            CREATE TABLE author_daily_read_stats (stat_date date PRIMARY KEY);
            INSERT INTO author_daily_read_stats VALUES (CURRENT_DATE);
            """);

        await ApplyAsync(db, "20260715-pre-read-event-retirement-compat");
        await ApplyAsync(db, "20260715-pre-visit-log-ip-pseudonym-epoch");
        await ApplyAsync(db, "20260715-post-read-event-retirement");

        Assert.Equal(0, await CountTableAsync(db, "sys_visit_log"));
        Assert.Equal(0, await CountTableAsync(db, "article_view_projection_watermark"));
        Assert.Equal(0, await db.Ado.GetIntAsync("SELECT unique_viewer_estimate FROM daily_read_stats;"));
        Assert.Equal(0, await db.Ado.GetIntAsync("SELECT COUNT(1) FROM region_read_stats;"));
        Assert.Equal(0, await db.Ado.GetIntAsync("SELECT COUNT(1) FROM author_route_stats;"));
        Assert.Equal(0, await db.Ado.GetIntAsync("SELECT COUNT(1) FROM author_daily_read_stats;"));
    }

    private static async Task ApplyAsync(ISqlSugarClient db, string migrationId)
    {
        ISchemaMigrationDescriptor descriptor = Assert.Single(
            new SchemaMigrationRegistry().GetDescriptors(),
            item => item.MigrationId == migrationId);
        foreach (SchemaMigrationStep step in descriptor.Steps)
        {
            await step.ExecuteAsync(db, CancellationToken.None);
        }
    }

    private static Task<int> CountTableAsync(ISqlSugarClient db, string tableName)
        => db.Ado.GetIntAsync($"""
            SELECT COUNT(1)
            FROM information_schema.tables
            WHERE table_schema = 'public' AND table_name = '{tableName}';
            """);
}
