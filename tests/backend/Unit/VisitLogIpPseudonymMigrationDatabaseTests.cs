using System.Data;

using FsusBlog.Server.Infrastructure.SchemaMigration;
using FsusBlog.Server.Tests.TestInfrastructure;

using SqlSugar;
namespace FsusBlog.Server.Tests.Unit;

[Trait("Dependency", "Docker")]
[Collection(nameof(SchemaMigrationPostgresCollectionB))]
public sealed class VisitLogIpPseudonymMigrationDatabaseTests(PostgresSchemaMigrationFixture fixture)
{
    [Fact]
    public async Task PreCodeFirstMigration_DeletesLegacyStableHashBeforeNarrowingColumn()
    {
        using SqlSugarClient db = await PostgresSqlSugarTestClient.CreateAsync(fixture);
        await db.Ado.ExecuteCommandAsync("""
            CREATE TABLE sys_visit_log (
                id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                ip_hash varchar(64) NOT NULL DEFAULT ''
            );
            INSERT INTO sys_visit_log(ip_hash) VALUES (
                'aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa'
            );
            """);

        await ApplyMigrationAsync(db);

        Assert.Equal(0, await db.Ado.GetIntAsync("SELECT COUNT(1) FROM sys_visit_log;"));
        DataTable columns = await db.Ado.GetDataTableAsync("""
            SELECT column_name, character_maximum_length
            FROM information_schema.columns
            WHERE table_schema = 'public'
              AND table_name = 'sys_visit_log';
            """);
        Assert.Contains(columns.Rows.Cast<DataRow>(), row =>
            string.Equals(Convert.ToString(row["column_name"]), "ip_hash", StringComparison.Ordinal)
            && Convert.ToInt32(row["character_maximum_length"]) == 32);
        Assert.Contains(columns.Rows.Cast<DataRow>(), row =>
            string.Equals(Convert.ToString(row["column_name"]), "ip_hash_key_epoch", StringComparison.Ordinal));
        Assert.Contains(columns.Rows.Cast<DataRow>(), row =>
            string.Equals(Convert.ToString(row["column_name"]), "ip_hash_window_utc", StringComparison.Ordinal));

    }

    [Fact]
    public async Task PreCodeFirstMigration_FreshDatabaseSkipsAbsentTableAndCodeFirstCreatesFinalShape()
    {
        using SqlSugarClient db = await PostgresSqlSugarTestClient.CreateAsync(fixture);

        await ApplyMigrationAsync(db);
        Assert.Equal(0, await db.Ado.GetIntAsync("""
            SELECT COUNT(1)
            FROM information_schema.tables
            WHERE table_schema = 'public' AND table_name = 'sys_visit_log';
            """));
    }

    private static async Task ApplyMigrationAsync(ISqlSugarClient db)
    {
        ISchemaMigrationDescriptor descriptor = Assert.Single(
            new SchemaMigrationRegistry().GetDescriptors(),
            static item => item.MigrationId == "20260715-pre-visit-log-ip-pseudonym-epoch");
        Assert.Equal(SchemaMigrationPhase.PreCodeFirst, descriptor.Phase);
        foreach (SchemaMigrationStep step in descriptor.Steps)
        {
            await step.ExecuteAsync(db, CancellationToken.None);
        }
    }
}
