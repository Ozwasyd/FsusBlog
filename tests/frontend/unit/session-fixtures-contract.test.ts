import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { describe, expect, it } from 'vitest'

const repoRoot = resolve(__dirname, '../../..')

function readRepoFile(relativePath: string): string {
  return readFileSync(resolve(repoRoot, relativePath), 'utf8')
}

describe('dev auth fixture persistence contract', () => {
  it('keeps local fixture sessions reusable instead of password-flow only', () => {
    const sessionFixtures = readRepoFile('tests/frontend/support/session-fixtures.mjs')
    const authUsers = readRepoFile('tests/frontend/fixtures/prepare-auth-smoke-users.mjs')
    const devStart = readRepoFile('tools/dev/start.sh')
    const acceptanceBootstrap = readRepoFile('tools/bootstrap-acceptance-env.sh')
    const acceptanceShared = readRepoFile('tests/frontend/support/playwright/acceptance-shared.ts')
    const localAuthFixtureEndpoints = readRepoFile('src/backend/Modules/Endpoints/LocalAuthFixtureEndpoints.cs')
    const viteConfig = readRepoFile('src/frontend/vite.config.ts')
    const viteEnv = readRepoFile('src/frontend/src/vite-env.d.ts')
    const router = readRepoFile('src/frontend/src/router/index.ts')
    const localFixtureSession = readRepoFile('src/frontend/src/services/localFixtureSession.ts')
    const authSessionRuntime = readRepoFile('src/frontend/src/services/authSessionRuntime.ts')
    const userStore = readRepoFile('src/frontend/src/store/user.ts')
    const adminStore = readRepoFile('src/frontend/src/store/admin.ts')

    expect(sessionFixtures).toContain('stableFixtureSessionId')
    expect(sessionFixtures).toContain('persistAuthFixtureManifest')
    expect(sessionFixtures).toContain('FSUSBLOG_PERSIST_AUTH_FIXTURES')
    expect(sessionFixtures).toContain('ON CONFLICT (sessionid) DO UPDATE')
    expect(sessionFixtures).toContain("const isHostPrefixed = name.startsWith('__Host-')")
    expect(sessionFixtures).toContain('secure: isHostPrefixed')
    expect(sessionFixtures).toContain("sameSite: isHostPrefixed ? 'Strict' : 'Lax'")
    expect(sessionFixtures).not.toContain('void rememberMe;')
    expect(authUsers).toContain('persistAuthFixtureManifest')
    expect(authUsers).not.toContain('FSUSBLOG_USER_PASSWORD')
    expect(authUsers).not.toContain('FSUSBLOG_ADMIN_PASSWORD')
    expect(devStart).toContain('AuthCookies__AllowLegacyPlainCookieRead="true"')
    expect(acceptanceBootstrap).toContain('AuthCookies__AllowLegacyPlainCookieRead=true')
    expect(acceptanceBootstrap).toContain('Jwt__SecretKey="$JWT_SECRET"')
    expect(acceptanceBootstrap).toContain('Jwt__Issuer="$JWT_ISSUER"')
    expect(acceptanceBootstrap).toContain('Jwt__Audience="$JWT_AUDIENCE"')
    expect(acceptanceBootstrap).toContain('Jwt__AccessTokenExpiresMinutes="$JWT_ACCESS_TOKEN_EXPIRES_MINUTES"')
    expect(acceptanceShared).toContain("baseUrl.protocol !== 'https:'")
    expect(acceptanceShared).toContain("cookie.name.startsWith('__Host-')")
    expect(devStart).toContain('Jwt__SecretKey=')
    expect(devStart).toContain('Jwt__AccessTokenExpiresMinutes=')
    expect(devStart).toContain('FSUSBLOG_JWT_ACCESS_TOKEN_EXPIRES_MINUTES="$Jwt__AccessTokenExpiresMinutes"')
    expect(devStart).toContain('LOCAL_AUTH_FIXTURE_SECRET=')
    expect(devStart).toContain('fsus__localAuthFixtureSecret="$LOCAL_AUTH_FIXTURE_SECRET"')
    expect(devStart).toContain('VITE_FSUSBLOG_LOCAL_AUTH_FIXTURE_SECRET="$LOCAL_AUTH_FIXTURE_SECRET"')
    expect(devStart).toContain('prepare:binary-smoke:auth-users')
    expect(localAuthFixtureEndpoints).toContain('RefreshPersistedAuthFixturesAsync')
    expect(localAuthFixtureEndpoints).toContain('prepare-auth-smoke-users.mjs')
    expect(localAuthFixtureEndpoints).toContain('FSUSBLOG_PG_CONTAINER')
    expect(localAuthFixtureEndpoints).toContain('fsusblog-dev-postgres')
    expect(localAuthFixtureEndpoints).toContain('hasHostAccessToken')
    expect(router).toContain('activateLocalFixtureSession')
    expect(router).toContain('hasCompleteFixtureCookies')
    expect(router).toContain('ensureLocalFixtureSessionCookies(to.fullPath)')
    expect(router).toContain('const fixtureRouteNeedsCookies = forceLocalFixtureSession && Boolean(to.meta.requiresAuth)')
    expect(router).toContain('isLocalFixtureSessionActive')
    expect(router).toContain('isLocalFixtureAdminSessionActive')
    expect(router).toContain('createLocalFixtureAccountSnapshot')
    expect(router).toContain('createLocalFixtureAdminPrincipal')
    expect(localFixtureSession).toContain('VITE_FSUSBLOG_LOCAL_AUTH_FIXTURE_SECRET')
    expect(localFixtureSession).toContain('X-Fsus-Local-Auth-Fixture-Secret')
    expect(localFixtureSession).toContain('refreshLocalFixtureAdminCookies')
    expect(localFixtureSession).toContain("credentials: 'include'")
    expect(viteEnv).toContain('VITE_FSUSBLOG_LOCAL_AUTH_FIXTURE_SECRET')
    expect(authSessionRuntime).toContain('isLocalFixtureSessionActive')
    expect(authSessionRuntime).toContain('ensureLocalFixtureSessionCookies')
    expect(authSessionRuntime).toContain('this.stopTimer()')
    expect(viteConfig).toContain("'^/__local/.*$'")
    expect(userStore).toContain('clearLocalFixtureSession')
    expect(adminStore).toContain('clearLocalFixtureSession')
  })

  it('keeps account fixture sessions separate from admin fixture elevation', () => {
    const localFixtureSession = readRepoFile('src/frontend/src/services/localFixtureSession.ts')
    const sessionBootstrap = readRepoFile('src/frontend/src/composables/useSessionBootstrap.ts')
    const router = readRepoFile('src/frontend/src/router/index.ts')
    const publicBrowserEnvMatrix = readRepoFile('tests/frontend/checks/public/check-public-browser-env-hydration-matrix.mjs')

    expect(localFixtureSession).toContain('isLocalFixtureAdminSessionActive')
    expect(localFixtureSession).toContain("get('fsusLocalFixtureAdmin') === '1'")
    expect(router).toContain('if (isLocalFixtureAdminSessionActive())')
    expect(router).not.toContain('if (manageRoute && forceLocalFixtureSession)')
    expect(sessionBootstrap).toContain('isLocalFixtureAdminSessionActive')
    expect(sessionBootstrap).toContain('if (isLocalFixtureAdminSessionActive())')
    expect(sessionBootstrap).not.toContain('if (isLocalFixtureSessionActive()) {\n      adminStore.setAdminPrincipal(createLocalFixtureAdminPrincipal())')
    expect(publicBrowserEnvMatrix).toContain("cell.sessionState === 'admin'")
    expect(publicBrowserEnvMatrix).toContain('fsusLocalFixtureAdmin=1')
  })
})
