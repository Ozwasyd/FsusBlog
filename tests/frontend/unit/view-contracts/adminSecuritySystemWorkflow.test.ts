import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'

const repoFile = (path: string): string => fileURLToPath(new URL(`../../../../${path}`, import.meta.url))
const readRepoFile = (path: string): string => readFileSync(repoFile(path), 'utf8')

describe('admin security system workflow contract', () => {
  const router = readRepoFile('src/frontend/src/router/index.ts')
  const nav = readRepoFile('src/frontend/src/layouts/accountNav.ts')
  const tabs = readRepoFile('src/frontend/src/components/admin/security/SecuritySystemTabs.vue')
  const layout = readRepoFile('src/frontend/src/views/admin/security/SecurityLayout.vue')
  const dashboard = readRepoFile('src/frontend/src/views/admin/security/SecurityDashboard.vue')
  const crawler = readRepoFile('src/frontend/src/views/admin/security/SecurityCrawler.vue')
  const pow = readRepoFile('src/frontend/src/views/admin/security/SecurityPow.vue')
  const riskControl = readRepoFile('src/frontend/src/views/admin/security/SecurityRiskControl.vue')
  const simulator = readRepoFile('src/frontend/src/views/admin/security/SecuritySimulator.vue')
  const challenges = readRepoFile('src/frontend/src/views/admin/security/SecurityChallenges.vue')
  const policies = readRepoFile('src/frontend/src/views/admin/security/SecurityPolicies.vue')
  const events = readRepoFile('src/frontend/src/views/admin/security/SecurityEvents.vue')
  const captcha = readRepoFile('src/frontend/src/views/admin/security/SecurityCaptcha.vue')
  const pospace = readRepoFile('src/frontend/src/views/admin/security/SecurityPoSpace.vue')
  const api = readRepoFile('src/frontend/src/api/security.ts')
  const endpoints = readRepoFile('src/backend/Modules/Endpoints/SecurityEndpoints.cs')
  const bridge = readRepoFile('src/backend/Infrastructure/Middlewares/SecurityBinaryBridgeMiddleware.cs')

  it('registers security system as a standalone admin route group', () => {
    expect(router).toContain("path: 'manage/security'")
    expect(router).toContain("name: 'ManageSecuritySystem'")
    expect(router).toContain("name: 'ManageSecurityDashboard'")
    expect(router).toContain("name: 'ManageSecurityCrawler'")
    expect(router).toContain("name: 'ManageSecurityPow'")
    expect(router).toContain("name: 'ManageSecurityRiskControl'")
    expect(router).toContain("name: 'ManageSecuritySimulator'")
    expect(router).toContain("name: 'ManageSecurityChallenges'")
    expect(router).toContain("name: 'ManageSecurityPolicies'")
    expect(router).toContain("name: 'ManageSecurityEvents'")
    expect(router).toContain("name: 'ManageSecurityCaptcha'")
    expect(router).toContain("name: 'ManageSecurityPoSpace'")
    expect(nav).toContain("label: '安全系统'")
    expect(nav).toContain("to: '/user/manage/security'")
    expect(tabs).toContain('安全总览')
    expect(tabs).toContain('RiskControl')
    expect(tabs).toContain('模拟器')
    expect(tabs).toContain('挑战状态')
    expect(tabs).toContain('策略版本')
    expect(tabs).toContain('风险事件')
    expect(tabs).toContain('Captcha')
    expect(tabs).toContain('PoSpace')
    expect(tabs).toContain('反爬虫系统')
    expect(tabs).toContain('PoW 系统')
  })

  it('keeps anti-crawler and PoW as sibling security capabilities', () => {
    expect(layout).toContain('PoW 不是反爬虫子配置')
    expect(layout).toContain('反爬虫只产生 crawler 类风险信号')
    expect(dashboard).toContain('antiCrawler')
    expect(dashboard).toContain('PoW')
    expect(dashboard).toContain('RiskControl')
    expect(dashboard).toContain('风险事件')
    expect(crawler).toContain('securityChallengeReference')
    expect(crawler).toContain('publicReadChallengeEnabled')
    expect(crawler).toContain('searchCrawlerVerificationEnabled')
    expect(crawler).not.toContain('PoW 策略已更新')
    expect(pow).toContain('PoW 只管理挑战与 Proof')
    expect(pow).toContain('反爬虫只写入爬虫风险')
  })

  it('adds RiskControl console pages without public JSON fallback', () => {
    expect(riskControl).toContain('getRiskControlConsole')
    expect(riskControl).toContain('activePolicy')
    expect(riskControl).toContain('riskEventAggregate')
    expect(simulator).toContain('simulateRiskControl')
    expect(simulator).toContain('requiredChallenges')
    expect(simulator).toContain('policyVersion')
    expect(challenges).toContain('getSecurityChallengeMetrics')
    expect(challenges).toContain('successRate')
    expect(challenges).toContain('failureRate')
    expect(policies).toContain('getSecurityPolicyConsole')
    expect(policies).toContain('policyVersions')
    expect(events).toContain('listSecurityRiskEvents')
    expect(events).toContain('eventAggregates')
    expect(captcha).toContain('captchaV1')
    expect(captcha).toContain('getSecurityChallengeMetrics')
    expect(pospace).toContain('argon2idPoSpaceV1')
    expect(pospace).toContain('getSecurityChallengeMetrics')
    expect(api).not.toContain('/api/admin/security')
    expect(api).not.toContain('fetch(')
    expect(api).not.toContain('application/json')
  })

  it('exposes security admin binary API client and internal-only backend endpoints', () => {
    expect(api).toContain('/api/binary')
    expect(api).toContain('/risk-control/overview')
    expect(api).toContain('/risk-control/simulate')
    expect(api).toContain('/challenges/overview')
    expect(api).toContain('/policies/overview')
    expect(api).toContain('/anti-crawler/overview')
    expect(api).toContain('/anti-crawler/options')
    expect(api).toContain('/anti-crawler/crawler-ranges/sync')
    expect(api).toContain('/risk/ip/reset')
    expect(api).toContain('/pow/options')
    expect(api).toContain('X-Fsus-Mfa-Proof')
    expect(endpoints).toContain('MapGet("/overview"')
    expect(endpoints).toContain('MapGet("/risk-control/overview"')
    expect(endpoints).toContain('MapPost("/risk-control/simulate"')
    expect(endpoints).toContain('MapGet("/challenges/overview"')
    expect(endpoints).toContain('MapGet("/policies/overview"')
    expect(endpoints).toContain('MapGet("/anti-crawler/overview"')
    expect(endpoints).toContain('MapPut("/anti-crawler/options"')
    expect(endpoints).toContain('MapPost("/anti-crawler/crawler-ranges/sync"')
    expect(endpoints).toContain('MapGet("/pow/overview"')
    expect(endpoints).toContain('MapPut("/pow/options"')
    expect(endpoints).toContain('RequireAdminSensitiveStepUpAsync')
    expect(endpoints).toContain('RecordSecurityAuditAsync')
    expect(endpoints).toContain('RequireAdminPermission(AdminPermissions.SystemConfig)')
    expect(endpoints).toContain('AddEndpointFilter<BinaryBridgeInternalOnlyFilter>()')
    expect(bridge).toContain('segments is ["risk-control", "overview"]')
    expect(bridge).toContain('segments is ["risk-control", "simulate"]')
    expect(bridge).toContain('segments is ["challenges", "overview"]')
    expect(bridge).toContain('segments is ["policies", "overview"]')
    expect(bridge).toContain('AedsFrameType.SecurityOverview')
  })
})
