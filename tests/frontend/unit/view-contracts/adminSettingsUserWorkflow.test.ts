import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'

const repoFile = (path: string): string => fileURLToPath(new URL(`../../../../${path}`, import.meta.url))
const readRepoFile = (path: string): string => readFileSync(repoFile(path), 'utf8')

describe('admin settings and user governance workflow contract', () => {
  const settingsPage = readRepoFile('src/frontend/src/views/admin/Settings.vue')
  const settingsComposable = readRepoFile('src/frontend/src/composables/useAdminSettingsPage.ts')
  const brandAssetUploadField = readRepoFile('src/frontend/src/components/admin/settings/BrandAssetUploadField.vue')
  const systemApi = readRepoFile('src/frontend/src/api/system.ts')
  const systemEndpoint = readRepoFile('src/backend/Modules/Endpoints/Binary/BinaryEndpoints.System.cs')
  const adminUserEndpoint = readRepoFile('src/backend/Modules/Endpoints/Binary/BinaryEndpoints.AdminUsers.cs')
  const userPage = readRepoFile('src/frontend/src/views/admin/UserManage.vue')
  const userComposable = readRepoFile('src/frontend/src/composables/useAdminUserManage.ts')
  const userHeader = readRepoFile('src/frontend/src/components/admin/users/UserManageHeader.vue')
  const userTable = readRepoFile('src/frontend/src/components/admin/users/UserManageTable.vue')
  const banDialog = readRepoFile('src/frontend/src/components/admin/users/UserBanDialog.vue')
  const adminApi = readRepoFile('src/frontend/src/api/admin.ts')

  it('keeps site metadata and media policy in separate tabs with guarded save semantics', () => {
    expect(settingsPage).toContain('label="站点信息"')
    expect(settingsPage).toContain('label="媒体策略"')
    expect(settingsPage).toContain('v-loading="loadingSite"')
    expect(settingsPage).toContain(':disabled="siteFormDisabled || !isSiteDirty"')
    expect(settingsPage).toContain('confirmSiteSave')
    expect(settingsPage).toContain('siteSearchPreview')
    expect(settingsComposable).toContain('originalSiteSnapshot')
    expect(settingsComposable).toContain('siteFormDisabled')
    expect(settingsComposable).toContain('siteLoadFailed')
    expect(settingsComposable).toContain('siteChangeSummary')
    expect(settingsComposable).toContain('作者名称不可为空')
    expect(settingsComposable).toContain('sanitizeKeywords()')
    expect(settingsPage).toContain('站点配置加载失败')
    expect(settingsPage).toContain('@click="loadSiteConfig"')
    expect(settingsPage).toContain('<h3 class="section-title">基础信息</h3>')
    expect(settingsPage).not.toContain('站点元信息')
    expect(settingsPage).not.toContain('text-[11px] font-bold tracking-normal mb-10 pb-4 border-b')
    expect(settingsPage).toContain('@apply m-0 text-xl')
    expect(settingsPage).toContain('settings-compliance-record-grid grid grid-cols-1')
    expect(settingsPage).toContain('xl:grid-cols-[minmax(0,1fr)_22rem]')
    expect(settingsPage).toContain('settings-compliance-toggle-row flex min-w-0 items-center gap-3')
    expect(settingsPage).not.toContain('label="部署区域"')
    expect(settingsPage).not.toContain('v-model="complianceForm.regionMode"')
    expect(settingsPage).not.toContain('value="mainland-cn"')
    expect(settingsComposable).not.toContain("regionMode: readStringField(source, 'regionMode', 'RegionMode')")
    expect(settingsComposable).not.toContain('regionMode: complianceForm.regionMode')
    expect(settingsComposable).toContain("await updateSiteComplianceConfig({ ...complianceForm, regionMode: 'global' }")
    expect(settingsPage).not.toContain(
      '<div class="text-[11px] font-bold text-[var(--fsusblog-text-muted)] mt-4 normal-case tracking-normal">\n                      关闭时不展示备案号和许可说明；基础版权与页脚导航仍会保留。',
    )
  })

  it('does not auto-save SEO text when OG image changes', () => {
    expect(settingsComposable).toContain('配置图已更新，请保存同步')
    expect(settingsComposable).toContain('配置图恢复上传成功，请保存同步')
    expect(settingsComposable).toContain('预览图已从待保存配置移除，请保存同步')
    expect(settingsComposable).toContain('handleImageDelete')
    expect(settingsComposable).toContain('deleteImage(current)')
    expect(settingsPage).toContain('上传只更新待保存配置')
    expect(settingsPage).toContain('这只会从待保存配置中移除当前预览图')
    expect(settingsPage).toContain('删除服务器文件')
  })

  it('exposes brand asset uploads and favicon set generation without SVG rasterization', () => {
    expect(settingsPage).toContain('BrandAssetUploadField')
    expect(settingsPage).toContain('handleBrandAssetUpload')
    expect(settingsPage).toContain('handleFaviconSetGeneration')
    expect(settingsPage).toContain('从图片生成图标组')
    expect(settingsPage).toContain('target-field="siteLogoUrl"')
    expect(settingsPage).toContain('target-field="adminLogoUrl"')
    expect(settingsPage).toContain('target-field="loginLogoUrl"')
    expect(settingsPage).toContain('target-field="faviconPngUrl"')
    expect(settingsComposable).toContain('type BrandAssetField')
    expect(settingsComposable).toContain('brandAssetUploadingField')
    expect(settingsComposable).toContain('iconSetGenerating')
    expect(settingsComposable).toContain('generateBrandIconSet')
    expect(settingsComposable).toContain('siteForm[assignment.field] = url')
    expect(settingsComposable).toContain('siteForm[targetField] = url')
    expect(settingsComposable).toContain('不支持 SVG 上传，请填写已清洗的 SVG URL')
    expect(settingsComposable).not.toContain('rasterToSvg')
    expect(settingsComposable).not.toContain('image/svg+xml')
  })

  it('uses the same preview-and-replace upload mode for brand assets', () => {
    expect(brandAssetUploadField).toContain('previewUrl')
    expect(brandAssetUploadField).toContain('previewLoaded')
    expect(brandAssetUploadField).toContain('previewFailed')
    expect(brandAssetUploadField).toContain('@load="handlePreviewLoad"')
    expect(brandAssetUploadField).toContain('@error="handlePreviewError"')
    expect(brandAssetUploadField).toContain('canShowPreview')
    expect(brandAssetUploadField).toContain('v-if="canShowPreview"')
    expect(brandAssetUploadField).toContain('v-if="!canShowPreview"')
    expect(brandAssetUploadField).toContain('image-replace-overlay')
    expect(brandAssetUploadField).toContain('点击更换')
    expect(settingsComposable).toContain('resolveBrandAssetPreviewUrl')
    expect(settingsComposable).toContain('parsed.origin === mountedBrowserBaseUrl.value')
    expect(settingsComposable).toContain("url.startsWith('//')")
    expect(settingsComposable).toContain("return url.startsWith('/') ? url : `/${url}`")
    expect(settingsPage).toContain(':preview-url="resolveBrandAssetPreviewUrl(\'siteLogoUrl\')"')
    expect(settingsPage).toContain(':preview-url="resolveBrandAssetPreviewUrl(\'adminLogoUrl\')"')
    expect(settingsPage).toContain(':preview-url="resolveBrandAssetPreviewUrl(\'loginLogoUrl\')"')
    expect(settingsPage).toContain(':preview-url="resolveBrandAssetPreviewUrl(\'faviconPngUrl\')"')
    expect(settingsPage).not.toContain('class="brand-asset-upload-field flex min-w-0 items-stretch gap-3"')
  })

  it('protects page editor content before switching static page slugs', () => {
    expect(settingsComposable).toContain('originalPageContent')
    expect(settingsComposable).toContain('isPageDirty')
    expect(settingsComposable).toContain('pendingPageSwitchSlug')
    expect(settingsComposable).toContain('requestPageSwitch')
    expect(settingsComposable).toContain('savePageAndSwitch')
    expect(settingsComposable).toContain('refreshPageCache')
    expect(systemApi).toContain('refreshPageData')
    expect(settingsComposable).toContain("{ value: 'copyright', label: '版权声明' }")
    expect(systemEndpoint).toContain('AllowedPageSlugs.Contains(dto.Slug')
    expect(systemEndpoint).toContain('AllowedPageSlugs.Contains(slug)')
    expect(settingsComposable).toContain('beforeunload')
    expect(settingsPage).toContain('@update:model-value="requestPageSwitch"')
    expect(settingsPage).toContain('维护关于、隐私政策、用户守则与版权声明页面的发布内容')
    expect(settingsPage).not.toContain('About、Archive')
    expect(settingsPage).toContain('强制刷新缓存')
    expect(settingsPage).toContain('保存并切换')
    expect(settingsPage).toContain('放弃修改')
  })

  it('syncs user filters to URL query and exposes reset chips', () => {
    expect(userComposable).toContain('useRoute')
    expect(userComposable).toContain('useRouter')
    expect(userComposable).toContain('hydrateQueryFromRoute')
    expect(userComposable).toContain('syncQueryToRoute')
    expect(userComposable).toContain('activeFilterChips')
    expect(userHeader).toContain('activeFilters')
    expect(userHeader).toContain("emit('reset')")
    expect(userHeader).toContain("emit('remove-filter', chip.key)")
    expect(userPage).toContain('@reset="resetFilters"')
  })

  it('shows anonymous account governance fields instead of user role and login metadata', () => {
    expect(adminUserEndpoint).toContain('request.Status is not 0 and not 1')
    expect(adminApi).toContain('accountId: number')
    expect(adminApi).toContain('identityKind: string')
    expect(adminApi).toContain('publicHandle?: string')
    expect(adminApi).toContain('passkeyInitialized: boolean')
    expect(adminApi).toContain('recoveryInitialized: boolean')
    expect(adminApi).toContain('anonymousCredentialStatus: string')
    expect(adminApi).toContain('anonymousCredentialLevel: string')
    expect(adminApi).toContain('riskFlags: number')
    expect(userComposable).toContain('displayHandle')
    expect(userComposable).toContain('identityKindLabel')
    expect(userComposable).toContain('credentialSummary')
    expect(userComposable).toContain('anonymousCredentialText')
    expect(userComposable).toContain('riskFlagsText')
    expect(userComposable).toContain('statusLabel')
    expect(userComposable).toContain('statusText: statusLabel')
    expect(userComposable).not.toContain('statusText: `${statusLabel} / ${statusCode}`')
    expect(userComposable).not.toContain('匿名凭据 ${item.anonymousCredentialStatus}/${item.anonymousCredentialLevel}')
    expect(userComposable).not.toContain("case 'basic':\n        return '基础级'")
    expect(userComposable).not.toContain('`${credentialStatusLabel(item.anonymousCredentialStatus)}，${credentialLevelLabel(item.anonymousCredentialLevel)}`')
    expect(userTable).toContain('row.displayHandle')
    expect(userTable).toContain('row.identityKindLabel')
    expect(userTable).toContain('row.credentialSummary')
    expect(userTable).toContain('匿名身份：{{ row.anonymousCredentialText }}')
    expect(userTable).toContain('row.anonymousCredentialText')
    expect(userTable).toContain('row.riskFlagsText')
    expect(userTable).toContain('row.statusText')
    expect(userTable).toContain('user-resource-list-identity-row flex items-center gap-3')
    expect(userTable).not.toContain('class="flex items-start gap-3"')
    expect(userTable).toContain('user-resource-list-meta')
    expect(userTable).toContain('user-resource-list-action-row')
    expect(userTable).toContain('user-resource-surface:has(.el-responsive-collection.is-compact)')
    expect(userTable).toContain('width: min(100%, 44rem);')
    expect(userTable).toContain('margin-inline: auto;')
    expect(userTable).toContain('border-radius: 0;')
    expect(userTable).toContain('layout="total, sizes, prev, pager, next"')
    expect(userTable).toContain('admin-data-surface__footer')
    expect(userTable).not.toContain('row.roleLabel')
    expect(userTable).not.toContain('row.lastLoginText')
    expect(adminApi).not.toContain('lastLoginIp')
    expect(userTable).not.toContain('用户目录 / Database')
    expect(userTable).not.toContain('p-8 border-t')
  })

  it('removes legacy reset-password production UI and API hooks', () => {
    for (const source of [userPage, userComposable, userHeader, userTable, adminApi]) {
      expect(source).not.toContain('reset-pwd')
      expect(source).not.toContain('AdminResetPwdDto')
      expect(source).not.toContain('AdminResetUserPasswordRequest')
      expect(source).not.toContain('adminResetPassword')
      expect(source).not.toContain('重置密码')
      expect(source).not.toContain('新密码')
      expect(source).not.toContain('UserResetPasswordDialog')
    }

    expect(userPage).not.toContain('@open-reset')
    expect(userComposable).not.toContain('resetDialog')
    expect(userComposable).not.toContain('canSubmitResetPassword')
    expect(userComposable).not.toContain('handleResetSubmit')
  })

  it('requires ban impact review, public preview, and username confirmation', () => {
    expect(userComposable).toContain('banReasonValidation')
    expect(userComposable).toContain('canSubmitBan')
    expect(userComposable).toContain('当前接口未返回封禁原因')
    expect(userTable).toContain('class="user-table-action-button"')
    expect(userTable).toContain(':deep(.user-table-action-button)')
    expect(userTable).not.toContain('.user-table-action-button.el-button')
    expect(userTable).toContain('min-height: 2.25rem;')
    expect(banDialog).toContain('当前封禁为永久封禁')
    expect(banDialog).toContain('封禁影响')
    expect(banDialog).toContain('账号持有者可见文案预览')
    expect(banDialog).toContain('confirmAccountLabel')
    expect(banDialog).toContain(':disabled="!canSubmit"')
  })
})
