import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'

const repoFile = (path: string): string => fileURLToPath(new URL(`../../../../${path}`, import.meta.url))
const readRepoFile = (path: string): string => readFileSync(repoFile(path), 'utf8')

describe('anonymous moderation governance workflow contract', () => {
  const router = readRepoFile('src/frontend/src/router/index.ts')
  const accountNav = readRepoFile('src/frontend/src/layouts/accountNav.ts')
  const queue = readRepoFile('src/frontend/src/components/admin/comment-moderation/CommentModerationQueue.vue')
  const queueComposable = readRepoFile('src/frontend/src/composables/useCommentModerationQueue.ts')
  const governance = readRepoFile('src/frontend/src/views/admin/moderation/AnonymousGovernancePlaceholder.vue')
  const commentModerationPage = readRepoFile('src/frontend/src/views/admin/CommentModeration.vue')
  const actionComposable = readRepoFile('src/frontend/src/composables/useCommentModerationActions.ts')
  const authoringApi = readRepoFile('src/frontend/src/api/authoring.ts')

  it('keeps anonymous governance under the existing manage moderation shell', () => {
    expect(router).toContain("path: 'manage/moderation'")
    expect(router).toContain("name: 'ManageAnonymousCommentPolicy'")
    expect(router).toContain("name: 'ManageAnonymousRisk'")
    expect(router).toContain("name: 'ManageAnonymousCredentials'")
    expect(router).toContain("name: 'ManageAnonymousNullifiers'")
    expect(router).toContain("name: 'ManageZkAnonymousStatus'")
    expect(accountNav).toContain("to: '/user/manage/moderation/anonymous-policy'")
    expect(accountNav).toContain("to: '/user/manage/moderation/anonymous-risk'")
    expect(accountNav).toContain("to: '/user/manage/moderation/anonymous-credentials'")
    expect(accountNav).toContain("to: '/user/manage/moderation/nullifiers'")
    expect(accountNav).toContain("to: '/user/manage/moderation/zk-anonymous'")
  })

  it('renders anonymous-safe actor metadata without requiring a visible userName', () => {
    expect(queueComposable).toContain('actorDisplayName')
    expect(queueComposable).toContain('authorModeLabel')
    expect(queueComposable).toContain('displayLanguageLabel')
    expect(queueComposable).toContain('anonymousScopeLabel')
    expect(queueComposable).toContain('credentialLevelLabel')
    expect(queueComposable).toContain('reputationBucketLabel')
    expect(queueComposable).toContain('accountAgeBucketLabel')
    expect(queueComposable).toContain('nullifierStatusLabel')
    expect(queueComposable).toContain('riskLabels')
    expect(queueComposable).toContain('isStrongAnonymous')
    expect(queue).toContain('row.actorDisplayName')
    expect(queue).toContain('authorModeLabel')
    expect(queue).toContain('displayLanguageLabel')
    expect(queue).toContain('anonymousScopeLabel')
    expect(queue).toContain('credentialLevelLabel')
    expect(queue).toContain('reputationBucketLabel')
    expect(queue).toContain('accountAgeBucketLabel')
    expect(queue).toContain('nullifierStatusLabel')
    expect(queue).toContain('riskLabels')
    expect(queue).not.toContain('{{ row.userName }}')
    expect(queue).not.toContain('row.nullifierHash')
  })

  it('keeps nullifier and credential actions permission-gated', () => {
    expect(queueComposable).toContain('canBlockAnonymousNullifier')
    expect(queueComposable).toContain('canRevokeAnonymousCredential')
    expect(queue).toContain('block-anonymous-nullifier')
    expect(queue).toContain('revoke-anonymous-credential')
    expect(queue).toContain('canBlockAnonymousNullifier')
    expect(queue).toContain('canRevokeAnonymousCredential')
    expect(queue).toContain('封禁 Nullifier')
    expect(queue).toContain('撤销匿名凭证')
  })

  it('connects anonymous governance actions to real API calls and queue refresh', () => {
    expect(authoringApi).toContain('blockAnonymousNullifier')
    expect(authoringApi).toContain('revokeAnonymousCredential')
    expect(actionComposable).toContain('applyBlockAnonymousNullifier')
    expect(actionComposable).toContain('applyRevokeAnonymousCredential')
    expect(actionComposable).toContain('ensureAdminSensitiveProof')
    expect(actionComposable).toContain('anonymousGovernanceErrorMessage')
    expect(actionComposable).toContain('error.status === 403')
    expect(actionComposable).toContain('error.status === 428')
    expect(actionComposable).toContain('error.status === 404')
    expect(actionComposable).toContain('error.status === 429')
    expect(actionComposable).toContain('当前账号无权限执行匿名治理操作')
    expect(actionComposable).toContain('匿名治理对象不存在或已失效，请刷新队列')
    expect(actionComposable).toContain('匿名治理操作过于频繁，请稍后再试')
    expect(commentModerationPage).toContain('applyBlockAnonymousNullifier(item, refreshAndPrune)')
    expect(commentModerationPage).toContain('applyRevokeAnonymousCredential(item, refreshAndPrune)')
    expect(commentModerationPage).not.toContain('Nullifier 封禁 API 尚未接入')
    expect(commentModerationPage).not.toContain('匿名凭证撤销 API 尚未接入')
    expect(governance).not.toContain('接口尚未接入')
  })

  it('surfaces policy, ZK, risk, nullifier, and credential governance controls', () => {
    expect(governance).toContain('useAdminStore')
    expect(governance).toContain('anonymousCommentsEnabled')
    expect(governance).toContain('publicOnlyMode')
    expect(governance).toContain('zkAnonymousEnabled')
    expect(governance).toContain('canConfigureAnonymousPolicy')
    expect(governance).toContain('canBlockAnonymousNullifier')
    expect(governance).toContain('canRevokeAnonymousCredential')
    expect(governance).toContain('setAnonymousCommentPolicy')
    expect(governance).toContain('el-switch')
    expect(governance).toContain('匿名评论')
    expect(governance).toContain('仅公开')
    expect(governance).toContain('ZK 匿名')
    expect(governance).toContain('Nullifier')
    expect(governance).toContain('credential')
    expect(governance).toContain('撤销')
    expect(governance).toContain(':title-level="2"')
    expect(governance).not.toMatch(/(^|\s)title-level="2"/u)
    expect(governance).not.toContain('reverseLookup')
  })
})
