import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'

const repoFile = (path: string): string => fileURLToPath(new URL(`../../../../${path}`, import.meta.url))
const readRepoFile = (path: string): string => readFileSync(repoFile(path), 'utf8')

describe('anonymous identity auth workflow contract', () => {
  const loginPage = readRepoFile('src/frontend/src/views/auth/Login.vue')
  const registerPage = readRepoFile('src/frontend/src/views/auth/Register.vue')
  const onboarding = readRepoFile('src/frontend/src/composables/useAnonymousOnboarding.ts')
  const loginComposable = readRepoFile('src/frontend/src/composables/useAuthLogin.ts')
  const authApi = readRepoFile('src/frontend/src/api/auth.ts')
  const authAdapter = readRepoFile('src/frontend/src/adapters/binary/authAdapter.ts')
  const binaryIndex = readRepoFile('src/frontend/src/adapters/binary/index.ts')
  const binaryRoutes = readRepoFile('src/frontend/src/generated/fsusBinaryRoutes.ts')
  const passkeyModal = readRepoFile('src/frontend/src/components/ui/PasskeyRegisterModal.vue')

  it('makes passkey login primary and removes the legacy password branch', () => {
    expect(loginPage).toContain('v-if="!requiresMfa"')
    expect(loginPage).toContain('使用通行密钥登录')
    expect(loginPage).toContain('Recovery Key')
    expect(loginPage).toContain('to="/recover"')
    expect(loginPage).toContain('value="totp"')
    expect(loginPage).toContain('value="recovery"')
    expect(loginPage).not.toContain('anonymousIdentityMode')
    expect(loginPage).not.toContain('v-else-if="!anonymousIdentityMode && !requiresMfa"')
    expect(loginPage).not.toContain('@submit.prevent="handleLogin"')
    expect(loginPage).not.toContain('loginData.username')
    expect(loginPage).not.toContain('loginData.password')
    expect(loginPage).not.toContain('autocomplete="username"')
    expect(loginPage).not.toContain('autocomplete="current-password"')
    expect(loginPage).not.toContain('输入你的用户名')
    expect(loginPage).not.toContain('输入你的密码')
    expect(loginPage).not.toContain('可继续使用密码登录')
    expect(loginPage).not.toContain('改用用户名密码登录')
  })

  it('keeps retired username/password identity out of the production auth main path', () => {
    expect(authApi).not.toContain('export interface RegisterDto')
    expect(authApi).not.toContain('export interface LoginDto')
    expect(authApi).not.toContain('export interface UpdatePasswordDto')
    expect(authApi).not.toContain("binaryUrl: '/api/binary/auth/login'")
    expect(authApi).not.toContain("binaryUrl: '/api/binary/auth/register'")
    expect(authApi).not.toContain("binaryUrl: '/api/binary/auth/update-password'")
    expect(authApi).not.toContain('FrameType.AuthLoginRequest')
    expect(authApi).not.toContain('FrameType.AuthRegisterRequest')
    expect(authApi).not.toContain('FrameType.AuthUpdatePasswordRequest')
    expect(authApi).not.toContain('function encodeAuthLoginRequest')
    expect(authApi).not.toContain('function encodeAuthRegisterRequest')
    expect(authApi).not.toContain('function encodeAuthUpdatePasswordRequest')
    expect(authApi).not.toContain('updatePassword')
    expect(binaryRoutes).not.toContain('binary_get_auth_find_username')
    expect(binaryRoutes).not.toContain('/api/binary/auth/find/{username}')
    expect(loginComposable).not.toContain("import { login")
    expect(loginComposable).not.toContain('usePow')
    expect(loginComposable).not.toContain('loginData')
    expect(loginComposable).not.toContain('handleLogin')
  })

  it('replaces password registration with passkey-first anonymous onboarding', () => {
    expect(registerPage).toContain('useAnonymousOnboarding')
    expect(registerPage).toContain('PasskeyRegisterModal')
    expect(registerPage).toContain('Recovery Key')
    expect(registerPage).toContain('我已保存 Recovery Key')
    expect(registerPage).toContain('TOTP 恢复码不是 Recovery Key')
    expect(registerPage).toContain('createAnonymousAccount')
    expect(registerPage).toContain('openPasskeyRegistration')
    expect(registerPage).not.toContain('registerData.password')
    expect(registerPage).not.toContain('confirm-password')
    expect(registerPage).not.toContain('autocomplete="username"')
    expect(registerPage).not.toContain('autocomplete="new-password"')
  })

  it('keeps public handle registration decoupled from username browser semantics', () => {
    expect(registerPage).toContain('name="publicHandle"')
    expect(registerPage).toContain('autocomplete="off"')
    expect(registerPage).not.toContain('autocomplete="username"')
    expect(onboarding).toContain('PUBLIC_HANDLE_CONSTRAINT')
    expect(onboarding).toContain('validatePublicHandle(value)')
    expect(onboarding).not.toContain('USERNAME_CONSTRAINT')
    expect(onboarding).not.toContain('validateUsername')
  })

  it('keeps recovery key plaintext in memory only and uses existing passkey assets', () => {
    expect(onboarding).toContain('recoveryKeyPlaintext')
    expect(onboarding).toContain('recoveryKeySaved')
    expect(onboarding).toContain('createRecoveryKey')
    expect(onboarding).toContain('bootstrapAnonymousAccount')
    expect(onboarding).not.toContain('register(')
    expect(onboarding).not.toContain('createEphemeralPassword')
    expect(onboarding).not.toContain('buildAnonymousUsername')
    expect(onboarding).toContain('usePasskeyManagement')
    expect(onboarding).not.toContain('localStorage')
    expect(onboarding).not.toContain('sessionStorage')
    expect(onboarding).not.toContain('indexedDB')
    expect(onboarding).not.toContain('console.')
    expect(onboarding).not.toContain('validateUsername')
    expect(onboarding).not.toContain('USERNAME_CONSTRAINT')
    expect(onboarding).toContain('validatePublicHandle(value)')
    expect(onboarding).toContain('PUBLIC_HANDLE_CONSTRAINT')
    expect(passkeyModal).toContain('recoverySessionToken?: string')
    expect(passkeyModal).toContain('beginRecoveryPasskeyRegistration')
    expect(passkeyModal).toContain('completeRecoveryPasskeyRegistration')
  })

  it('wires recovery key endpoints through AEDS frame adapters', () => {
    expect(authApi).toContain('createRecoveryKey')
    expect(authApi).toContain('rotateRecoveryKey')
    expect(authApi).toContain('verifyRecoveryKey')
    expect(authApi).toContain('beginRecoveryPasskeyRegistration')
    expect(authApi).toContain('completeRecoveryPasskeyRegistration')
    expect(authApi).toContain("binaryUrl: '/api/binary/auth/recovery-key/create'")
    expect(authApi).toContain("binaryUrl: '/api/binary/auth/recovery-key/verify'")
    expect(authApi).toContain('FrameType.RecoveryKeyVerifyRequest')
    expect(authApi).toContain('FrameType.RecoveryKeySessionRequest')
    expect(authApi).toContain('bootstrapAnonymousAccount')
    expect(authApi).toContain("binaryUrl: '/api/binary/auth/anonymous/bootstrap'")
    expect(authApi).toContain('FrameType.AuthAnonymousBootstrapRequest')
    expect(authAdapter).toContain('mapRecoveryKeyCreateResponseFromPayload')
    expect(authAdapter).toContain('mapRecoveryKeyVerifyResponseFromPayload')
    expect(binaryIndex).toContain('[FrameType.RecoveryKeyCreateResponse]: mapRecoveryKeyCreateResponseFromPayload')
    expect(binaryIndex).toContain('[FrameType.RecoveryKeyVerifyResponse]: mapRecoveryKeyVerifyResponseFromPayload')
  })
})
