import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'

const repoFile = (path: string): string => fileURLToPath(new URL(`../../../../${path}`, import.meta.url))
const readRepoFile = (path: string): string => readFileSync(repoFile(path), 'utf8')

describe('frontend performance workflow contract', () => {
  const binaryTransport = readRepoFile('src/frontend/src/services/binaryTransport.ts')
  const decodeWorker = readRepoFile('src/frontend/src/workers/wasmDecode.worker.ts')
  const localSearch = readRepoFile('src/frontend/src/services/localSearch.ts')
  const filterView = readRepoFile('src/frontend/src/composables/useFilterView.ts')
  const imageCompression = readRepoFile('src/frontend/src/utils/imageCompression.ts')
  const wasmImageCodec = readRepoFile('src/frontend/src/utils/wasmImageCodec.ts')
  const notificationStreamStore = readRepoFile('src/frontend/src/store/notificationStream.ts')
  const commentStream = readRepoFile('src/frontend/src/composables/useArticleCommentStream.ts')
  const viewTask = readRepoFile('src/frontend/src/composables/useViewTask.ts')
  const commentList = readRepoFile('src/frontend/src/components/article/ArticleCommentsVirtualList.vue')
  const publicCommentIsland = readRepoFile('src/frontend/src/public-renderers/PublicArticleCommentsIsland.vue')
  const messagesPage = readRepoFile('src/frontend/src/views/user/Messages.vue')
  const markdownAdapter = readRepoFile('src/frontend/src/components/ui/MarkdownEditorAdapter.vue')
  const markdownRenderer = readRepoFile('src/frontend/src/components/ui/MarkdownRenderer.vue')
  const markdownRenderBudgetCheck = readRepoFile('tests/frontend/checks/perf/check-markdown-render-budget.mjs')
  const domBudgetCheck = readRepoFile('tests/frontend/checks/perf/check-dom-budget.mjs')
  const routeRenderPressureCheck = readRepoFile('tests/frontend/checks/perf/check-route-render-pressure.mjs')
  const frontendRenderPressureLane = readRepoFile('tools/test/lanes/frontend-render-pressure.sh')
  const entry = readRepoFile('src/frontend/src/bootstrap/entry.ts')
  const publicShell = readRepoFile('src/frontend/src/bootstrap/publicShell.ts')
  const appRuntime = readRepoFile('src/frontend/src/components/runtime/AppRuntime.vue')
  const fullApp = readRepoFile('src/frontend/src/bootstrap/fullApp.ts')
  const homeView = readRepoFile('src/frontend/src/composables/useHomeView.ts')
  const publicHomeContent = readRepoFile('src/frontend/src/components/public/pages/PublicHomePageContent.vue')
  const humanReadProof = readRepoFile('src/frontend/src/composables/useHumanReadProof.ts')
  const nonCriticalResources = readRepoFile('src/frontend/src/bootstrap/nonCriticalResources.ts')
  const serviceWorkerRuntime = readRepoFile('src/frontend/src/services/serviceWorkerRuntime.ts')
  const telemetryBus = readRepoFile('src/frontend/src/services/telemetryBus.ts')
  const telemetryService = readRepoFile('src/frontend/src/services/telemetryService.ts')
  const packageJson = readRepoFile('src/frontend/package.json')

  it('keeps normal AEDS worker aborts on a cancel protocol instead of worker reset', () => {
    expect(binaryTransport).toContain('const WORKER_IDLE_TTL_MS = 30000')
    expect(binaryTransport).toContain('function scheduleWorkerIdleTerminate')
    expect(binaryTransport).toContain('function postWorkerCancel')
    expect(binaryTransport).toContain("type: 'cancel'")
    expect(binaryTransport).toContain("emitRumMetric('binary_worker_init_count'")
    expect(binaryTransport).not.toContain("resetWorker(createAbortLikeError('binary_decode_aborted'))")

    expect(decodeWorker).toContain('const canceledRequests = new Set<number>()')
    expect(decodeWorker).toContain('let wasmReadyPromise: Promise<boolean> | null = null')
    expect(decodeWorker).toContain('function ensureWasmReady')
    expect(decodeWorker).toContain("event.data.type === 'cancel'")
    expect(decodeWorker).toContain('postDecodeResponse(response)')
    expect(decodeWorker).toContain('isRequestCanceled(requestId)')
  })

  it('removes redundant image, wasm codec, and notification stream batch copies', () => {
    expect(imageCompression).toContain('rgba: imageData.data')
    expect(imageCompression).toContain('new Blob([encoded as unknown as BlobPart], { type: mimeType })')
    expect(imageCompression).not.toContain('Uint8Array.from(imageData.data)')
    expect(imageCompression).not.toContain('Uint8Array.from(encoded)')

    expect(wasmImageCodec).toContain('let simdSupportCache: boolean | null = null')
    expect(wasmImageCodec).toContain('rgba: Uint8Array | Uint8ClampedArray')
    expect(wasmImageCodec).toContain('return decodeUtf8(view.buffer.slice')
    expect(wasmImageCodec).not.toContain('decodeUtf8(Uint8Array.from(view))')

    expect(notificationStreamStore).toContain('Object.freeze(patches)')
    expect(notificationStreamStore).not.toContain('Object.freeze([...patches])')
  })

  it('keeps search index bytes out of long-lived JS state', () => {
    expect(localSearch).toContain('let loadedEntryKeys = new Set<string>()')
    expect(localSearch).toContain('let activeManifest: SearchManifest | null = null')
    expect(localSearch).toContain('const EMPTY_SEARCH_PACKAGE = buildSearchPackage([])')
    expect(localSearch).toContain('const SEARCH_ASSET_FETCH_CONCURRENCY = 2')
    expect(localSearch).toContain('function mapWithConcurrency')
    expect(localSearch).toContain('selectInitialRoles(manifest)')
    expect(localSearch).toContain('preloadBackgroundSearchPhase(manifest, generation)')
    expect(localSearch).toContain('scheduleDeepSearchPhase(manifest, generation)')
    expect(localSearch).toContain('type CombinedAbortSignal')
    expect(localSearch).toContain('combinedSignal.cleanup()')
    expect(localSearch).toContain('function shouldPreloadBackgroundShard')
    expect(localSearch).toContain('deviceMemory')
    expect(localSearch).toContain('saveData')
    expect(localSearch).toContain('requestIdleCallback')
    expect(localSearch).toContain("emitSearchPhaseMetric('initial'")
    expect(localSearch).not.toContain('Promise.all(roles.map')
    expect(filterView).not.toContain('await loadDeepSearchIndex(signal)')
    expect(localSearch).not.toContain('loadedEntries')
  })

  it('guards cooperative loading state and reply maps without broad object copies', () => {
    expect(viewTask).toContain('let runSeq = 0')
    expect(viewTask).toContain('const seq = ++runSeq')
    expect(viewTask).toContain('seq === runSeq')

    expect(commentStream).toContain('reactive<Record<string, boolean>>({})')
    expect(commentStream).toContain('loadingReplies[rootId] = true')
    expect(commentStream).toContain('delete loadingReplies[rootId]')
    expect(commentStream).toContain('const replyControllerByRoot = new Map<string, AbortController>()')
    expect(commentStream).toContain('COMMENT_CONTENT_CONSTRAINT.replyRenderLimit')
    expect(commentStream).not.toContain('const replyTask = useAbortableTask()')
    expect(commentStream).not.toContain('loadingReplies.value = {')
  })

  it('keeps message inbox patch signatures and time formatting off derived row churn', () => {
    expect(messagesPage).toContain('const formatTimeCache = new Map<string, string>()')
    expect(messagesPage).toContain('formatTimeCache.get(input)')
    expect(messagesPage).toContain('formatTimeCache.set(input, formatted)')

    const conversationSignatureStart = messagesPage.indexOf('const conversationSignature = computed')
    const messageSignatureStart = messagesPage.indexOf('const messageSignature = computed')
    expect(conversationSignatureStart).toBeGreaterThanOrEqual(0)
    expect(messageSignatureStart).toBeGreaterThan(conversationSignatureStart)
    const conversationSignature = messagesPage.slice(conversationSignatureStart, messageSignatureStart)
    const messageSignature = messagesPage.slice(messageSignatureStart, messagesPage.indexOf('const contextAccountText', messageSignatureStart))

    expect(conversationSignature).toContain('conversations.value')
    expect(conversationSignature).not.toContain('visibleConversationRows.value')
    expect(messageSignature).toContain('detail.value?.messages')
    expect(messageSignature).not.toContain('visibleMessageRows.value')
    expect(messageSignature).not.toContain('message.body')
  })

  it('keeps article comment stream push and delete paths on in-place shallowRef triggers', () => {
    expect(commentStream).toContain("import { reactive, ref, shallowRef, triggerRef } from 'vue'")
    expect(commentStream).toContain('const notifyThreadsChanged = () => triggerRef(threads)')
    expect(commentStream).toContain('threads.value.push(item)')
    expect(commentStream).toContain('threads.value.unshift(thread)')
    expect(commentStream).toContain('target.repliesPreview.push(reply)')
    expect(commentStream).toContain('notifyThreadsChanged()')
    expect(commentStream).not.toContain('const merged = [...threads.value]')
    expect(commentStream).not.toContain('const nextThreads = [...threads.value]')
    expect(commentStream).not.toContain('[thread, ...threads.value]')
  })

  it('keeps DOM and markdown render pressure budgets wired into frontend gates', () => {
    expect(packageJson).toContain('check:dom-depth-static')
    expect(packageJson).toContain('check:dom-budget')
    expect(packageJson).toContain('check:route-render-pressure')
    expect(packageJson).toContain('check:markdown-render-budget')

    expect(markdownAdapter).toContain('MARKDOWN_PREVIEW_DEBOUNCE_MS = 250')
    expect(markdownAdapter).toContain('LARGE_PREVIEW_CONTENT_BYTES = 80 * 1024')
    expect(markdownAdapter).toContain('v-if="isPreviewMounted"')
    expect(markdownAdapter).toContain('refreshManualPreview')
    expect(markdownRenderer).toContain('@features-activated')
    expect(markdownRenderer).toContain("emit('features-activated'")
    expect(markdownRenderer).not.toContain('markdownActivationService')
    expect(packageJson).toContain('"@ozwasyd/element-plus": "1.5.1"')
    expect(markdownRenderBudgetCheck).toContain("packageJson.dependencies?.['@ozwasyd/element-plus'] === '1.5.1'")
    expect(frontendRenderPressureLane).toContain('source "$ROOT_DIR/tools/test/legacy-test.sh"')
    expect(frontendRenderPressureLane).toContain('require_debug_stack')
    expect(frontendRenderPressureLane).toContain('export FSUSBLOG_BASE_URL="$DEBUG_BACKEND_URL"')
    expect(frontendRenderPressureLane).toContain('export PLAYWRIGHT_BASE_URL="$DEBUG_FRONTEND_URL"')
    expect(domBudgetCheck).toMatch(/for \(const route of routeBudgets\) \{\n\s+const page = await context\.newPage\(\)/u)
    expect(domBudgetCheck).toContain('await page.close().catch(() => {})')
    expect(routeRenderPressureCheck).toMatch(/for \(const route of routes\) \{\n\s+const page = await context\.newPage\(\)/u)
    expect(routeRenderPressureCheck).toContain('await page.close().catch(() => {})')

    expect(commentList).toContain('COMMENT_CONTENT_CONSTRAINT.rootRenderLimit')
    expect(commentList).toContain('visibleThreadItems')
    expect(publicCommentIsland).toContain('visibleRootLimit')
    expect(messagesPage).toContain('CONVERSATION_RENDER_WINDOW')
    expect(messagesPage).toContain('MESSAGE_RENDER_WINDOW')
    expect(messagesPage).toContain('visibleConversationRows')
    expect(messagesPage).not.toContain('v-show="showDetailPane"')
  })

  it('keeps full app FsusUI registration scoped to required plugins', () => {
    expect(fullApp).toContain("import { installFsusUiLoading } from '@/fsusui/feedback'")
    expect(fullApp).toContain('installFsusUiLoading(app)')
    expect(fullApp).not.toContain("import ElementPlus from '@ozwasyd/element-plus'")
    expect(fullApp).not.toContain('app.use(ElementPlus)')
  })

  it('keeps the public telemetry cold path on the lightweight event bus', () => {
    expect(telemetryBus).toContain("export const TELEMETRY_EVENT = 'fsus:telemetry'")
    expect(telemetryBus).toContain("export const RUM_METRIC_EVENT = 'fsus:rum-metric'")
    expect(telemetryBus).toContain('drainPendingTelemetry')
    expect(telemetryBus).toContain('drainPendingRumMetrics')
    expect(telemetryBus).not.toContain('@/api/')
    expect(telemetryBus).not.toContain('@/generated/')
    expect(telemetryBus).not.toContain('@wasm/')

    expect(entry).toContain("import { registerServiceWorker } from '@/services/serviceWorkerRuntime'")
    expect(entry).not.toContain('@/services/telemetryService')
    expect(publicShell).toContain("from '@/services/telemetryBus'")
    expect(publicShell).not.toContain('@/services/telemetryService')
    expect(serviceWorkerRuntime).toContain("from '@/services/telemetryBus'")
    expect(serviceWorkerRuntime).not.toContain('@/services/telemetryService')
    expect(serviceWorkerRuntime).toContain('function scheduleServiceWorkerUpdate')
    expect(serviceWorkerRuntime).toContain('scheduleServiceWorkerUpdate(registration)')
    expect(serviceWorkerRuntime).toContain("window.addEventListener('load'")
    expect(serviceWorkerRuntime).toContain('requestIdleCallback')
    expect(serviceWorkerRuntime).not.toContain('then(async (registration)')
    expect(serviceWorkerRuntime.indexOf('scheduleServiceWorkerUpdate(registration)')).toBeLessThan(serviceWorkerRuntime.indexOf('return registration'))

    expect(nonCriticalResources).toContain("import('@/services/telemetryService')")
    expect(telemetryService).toContain("from '@/services/telemetryBus'")
    expect(telemetryService).toContain('drainPendingTelemetry')
    expect(telemetryService).toContain('drainPendingRumMetrics')
  })

  it('unblocks public loader removal from non-critical stylesheet readiness', () => {
    expect(publicShell).toContain('const CRITICAL_STYLE_READY_TIMEOUT_MS = 450')
    expect(publicShell).toContain('const FULL_STYLESHEET_VALIDATION_TIMEOUT_MS = 1500')
    expect(publicShell).toContain('function listCriticalShellStylesheets')
    expect(publicShell).toContain('function ensureCriticalPublicShellStylesReady')
    expect(publicShell).toContain('function validatePublicShellStylesheetsInBackground')
    expect(publicShell).toContain('await ensureCriticalPublicShellStylesReady(styleLinks)')
    expect(publicShell).toContain('validatePublicShellStylesheetsInBackground(styleLinks)')
    expect(publicShell).toContain("readiness: 'background'")
    expect(publicShell).toContain('ensureEmergencyPublicShellStyle()')
    expect(publicShell).not.toContain('await Promise.all(styleLinks.map((link) => waitForStylesheet(link)))')
  })

  it('keeps article comments and PoW prewarm out of the public article first screen', () => {
    expect(publicShell).not.toContain("import { mountArticleCommentsIsland")
    expect(publicShell).toContain("import('@/public-renderers/commentsIsland')")
    expect(publicShell).toContain('function scheduleArticleCommentsIsland')
    expect(publicShell).toContain("payload.pageKind === 'ArticleDetail'")
    expect(publicShell).toContain("window.location.hash === '#comments'")
    expect(publicShell).toContain('new IntersectionObserver')
    expect(publicShell).toContain("rootMargin: '900px 0px 900px 0px'")
    expect(publicShell).toContain('scheduleDynamicIslands(payload)')

    expect(appRuntime).toContain('if (!isPublicRouteNow())')
    expect(appRuntime).toContain("import('@/composables/usePow')")
    expect(appRuntime.indexOf('if (!isPublicRouteNow())')).toBeLessThan(appRuntime.indexOf("import('@/composables/usePow')"))
  })

  it('defers home secondary article lists until the post-list region approaches viewport', () => {
    expect(publicShell).not.toContain("from '@/public-renderers/homeHotArticlesIsland'")
    expect(publicShell).toContain("import('@/public-renderers/homeHotArticlesIsland')")
    expect(publicShell).toContain('function scheduleHomeHotArticlesIsland')
    expect(publicShell).toContain('HOME_HOT_ARTICLES_SENTINEL_ID')
    expect(publicShell).toContain('HOME_HOT_ARTICLES_FALLBACK_DELAY_MS = 2500')
    expect(publicShell).toContain("payload.pageKind !== 'Home'")
    expect(publicShell).toContain('rootMargin: HOME_HOT_ARTICLES_ROOT_MARGIN')
    expect(publicShell).not.toContain('void mountHomeHotArticlesIsland(payload.routeKey)')

    expect(homeView).toContain('HOME_SECONDARY_CONTENT_SENTINEL_ID')
    expect(homeView).toContain('HOME_SECONDARY_LIST_FALLBACK_DELAY_MS = 2500')
    expect(homeView).toContain('const scheduleSecondaryListLoad')
    expect(homeView).toContain('new IntersectionObserver')
    expect(homeView).toContain('if (!secondaryListsLoaded && !secondaryListRequestInFlight)')
    expect(homeView).not.toContain('void loadFeaturedArticles(!hasServerHydrationView)')

    expect(publicHomeContent).toContain('id="fsus-home-secondary-content-sentinel"')
    expect(publicHomeContent.indexOf('id="fsus-home-secondary-content-sentinel"')).toBeLessThan(publicHomeContent.indexOf('<slot name="featured" />'))
    expect(publicHomeContent.indexOf('<slot name="featured" />')).toBeLessThan(publicHomeContent.indexOf('<PublicArticleList'))
  })

  it('requests human-read proof challenges only after readable dwell becomes visible', () => {
    expect(humanReadProof).toContain('const READABLE_ROOT_VISIBLE_THRESHOLD = 0.25')
    expect(humanReadProof).toContain('const scheduleChallengeRequest')
    expect(humanReadProof).toContain('const requestChallenge')
    expect(humanReadProof).toContain('const requestVersion = runtimeVersion')
    expect(humanReadProof).toContain('bindFallbackVisibility(target)')
    expect(humanReadProof).toContain('updateVisibility(rootIntersecting.value)')
    expect(humanReadProof).toContain('if (!visible.value || challenge.value')
    expect(humanReadProof).toContain('challengeRequestTimer = setTimeout')
    expect(humanReadProof).toContain('void requestChallenge()')
    expect(humanReadProof).toContain('requestHumanReadChallenge({')
  })
})
