import { existsSync, readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'

const repoFile = (path: string): string => fileURLToPath(new URL(`../../../../${path}`, import.meta.url))
const readRepoFile = (path: string): string => readFileSync(repoFile(path), 'utf8')
const readRepoFileIfExists = (path: string): string => existsSync(repoFile(path)) ? readRepoFile(path) : ''

describe('admin markdown editor workflow contract', () => {
  const contracts = readRepoFile('src/frontend/src/ui-contracts/markdownEditor.ts')
  const commands = readRepoFile('src/frontend/src/components/ui/markdown-editor/commands.ts')
  const textEditor = readRepoFile('src/frontend/src/components/ui/MarkdownTextEditor.vue')
  const adapter = readRepoFile('src/frontend/src/components/ui/MarkdownEditorAdapter.vue')
  const articleBodyPreview = readRepoFileIfExists('src/frontend/src/components/admin/article/ArticleBodyMarkdownPreview.vue')
  const writeEditor = readRepoFile('src/frontend/src/components/admin/article/ArticleWriteEditor.vue')
  const writeSidebar = readRepoFile('src/frontend/src/components/admin/article/ArticleWriteSidebar.vue')
  const writePage = readRepoFile('src/frontend/src/views/admin/article/Write.vue')
  const writeComposable = readRepoFile('src/frontend/src/composables/useAdminArticleWrite.ts')

  it('supports split preview without dropping write or preview modes', () => {
    expect(contracts).toContain("export type MarkdownEditorMode = 'write' | 'split' | 'preview'")
    expect(adapter).toContain('value="split"')
    expect(adapter).toContain("mode === 'write' || mode === 'split'")
    expect(adapter).toContain('v-if="isPreviewMounted"')
    expect(adapter).toContain("mode.value === 'preview' || mode.value === 'split'")
    expect(adapter).toContain('editor-shell__body--split')
  })

  it('renders write-page preview through the same article body shell as public articles', () => {
    expect(adapter).toContain('previewComponent?: Component')
    expect(adapter).toContain('const resolvedPreviewComponent = computed(() => props.previewComponent ?? provider.value.previewComponent)')
    expect(adapter).toContain(':is="resolvedPreviewComponent"')
    expect(writeEditor).toContain("import ArticleBodyMarkdownPreview from '@/components/admin/article/ArticleBodyMarkdownPreview.vue'")
    expect(writeEditor).toContain(':preview-component="ArticleBodyMarkdownPreview"')
    expect(articleBodyPreview).toContain("import ArticleDetailBody from '@/components/public/ArticleDetailBody.vue'")
    expect(articleBodyPreview).toContain("import MarkdownRenderer from '@/components/ui/MarkdownRenderer.vue'")
    expect(articleBodyPreview).toContain('<ArticleDetailBody>')
    expect(articleBodyPreview).toContain('mode="article"')
  })

  it('routes Ctrl/Cmd+S to draft save while Ctrl/Cmd+Enter keeps the submit confirmation path', () => {
    expect(textEditor).toContain('@save="emitSave"')
    expect(textEditor).toContain('@submit="emitSubmit"')
    expect(textEditor).toContain('function emitSave(): void')
    expect(textEditor).toContain("emit('on-draft-save')")
    expect(textEditor).toContain("emit('on-save')")
    expect(textEditor).toContain('function emitSubmit(): void')
    expect(textEditor).toContain("emit('on-submit')")
    expect(writeEditor).toContain('@draft-save="$emit(\'draft-save\')"')
    expect(writePage).toContain('@draft-save="saveDraftNow"')
    expect(writePage).not.toContain('@save="requestSubmit"')
  })

  it('inserts reusable assets at the editor cursor before falling back to append', () => {
    expect(textEditor).toContain('defineExpose')
    expect(textEditor).toContain('insertMarkdownAtCursor')
    expect(adapter).toContain('insertMarkdownAtCursor')
    expect(writeEditor).toContain('insertMarkdownAtCursor')
    expect(writePage).toContain('@insert="insertAssetIntoEditor"')
    expect(writeComposable).toContain('insertAtCursor?.(`\\n${markdown}\\n`)')
  })

  it('keeps editing available during image uploads and replaces upload placeholders', () => {
    expect(textEditor).toContain(':disabled="editorDisabled"')
    expect(textEditor).toContain('图片上传中')
    expect(textEditor).toContain('fsus-upload-placeholder://')
    expect(textEditor).toContain('replaceUploadPlaceholders')
    expect(textEditor).toContain('可重新粘贴或点击图片按钮重试')
  })

  it('uses grouped author-friendly toolbar terminology and native textarea undo', () => {
    expect(contracts).toContain('MarkdownEditorCommandGroup')
    expect(commands).toContain("label: '一级标题'")
    expect(commands).toContain("label: '公式'")
    expect(commands).toContain("label: '流程图'")
    expect(textEditor).toContain('ElMarkdownEditor')
    expect(textEditor).toContain('fsusUiCommands')
    expect(textEditor).toContain("type BlogCommandKey = Exclude<MarkdownEditorCommandKey, 'undo' | 'redo' | 'image' | 'save'>")
    expect(textEditor).toContain('fsusCommandKeys.has(command.key as BlogCommandKey)')
    expect(textEditor).toContain(':primary-command-keys="primaryCommandKeys"')
    expect(textEditor).toContain(':action-overflow-keys="actionOverflowKeys"')
    expect(textEditor).toContain('command-overflow-label="格式工具"')
    expect(textEditor).toContain('mobile-layout="auto"')
    expect(textEditor).toContain('editor-profile="prose"')
    expect(textEditor).toContain('interaction-profile="auto"')
    expect(textEditor).toContain(':writing-placeholder="writingPlaceholder"')
    expect(textEditor).toContain("const primaryCommandKeys: readonly BlogCommandKey[] = ['h1', 'h2', 'bold', 'italic', 'quote', 'link']")
    expect(textEditor).toContain("const actionOverflowKeys = ['image'] as const")
    expect(textEditor).toContain('image-action-label="上传图片"')
  })

  it('delegates mobile touch sizing to FsusUI and hides split mode on touch or narrow screens', () => {
    expect(adapter).not.toContain(':deep(.el-markdown-editor__command)')
    expect(adapter).not.toContain(':deep(.el-markdown-editor__action)')
    expect(adapter).not.toContain('min-height: 36px;')
    expect(adapter).toContain("import { useMediaQuery } from '@/composables/useMediaQuery'")
    expect(adapter).toContain("const isNarrowEditor = useMediaQuery('(max-width: 767px)', false)")
    expect(adapter).toContain("const isTouchEditor = useMediaQuery('(hover: none) and (pointer: coarse)', false)")
    expect(adapter).toContain('const hideSplitMode = computed(() => isNarrowEditor.value || isTouchEditor.value)')
    expect(adapter).toContain('v-if="!hideSplitMode"')
    expect(adapter).toContain("if (hide && mode.value === 'split')")
  })

  it('exposes writing status, inspector sections, and secondary view controls', () => {
    expect(textEditor).toContain('Intl as typeof Intl')
    expect(textEditor).toContain('{{ readingTimeText }}')
    expect(textEditor).toContain("readingEstimate.value.effectiveChars === 0 ? '少于 1 分钟' : `约 ${readingMinutes.value} 分钟`")
    expect(textEditor).toContain('第 {{ cursorLine }} 行，第 {{ cursorColumn }} 列')
    expect(textEditor).toContain('v-if="editorStateText"')
    expect(textEditor).not.toContain('准备编辑')
    expect(writePage).toContain('label="文章标题"')
    expect(writePage).toContain('class="write-title-input"')
    expect(writePage).toContain('placeholder="写下文章标题"')
    expect(writePage).toContain('font-size: clamp(2.25rem, 5vw, 4rem);')
    expect(writePage).toContain('--write-title-inline-inset: clamp(1rem, 3vw, 1.5rem);')
    expect(writePage).toContain('padding: 0 var(--write-title-inline-inset);')
    expect(writePage).not.toContain('calc(var(--write-title-inline-inset) + 4.5rem)')
    expect(writePage).toContain('@opened="focusQuickCategoryInput"')
    expect(writePage).toContain('@opened="focusQuickTagInput"')
    expect(writePage).toContain('ref="quickCategoryInputRef"')
    expect(writePage).toContain('ref="quickTagInputRef"')
    expect(writePage).toContain('class="write-inspector"')
    expect(writePage).toContain('class="write-inspector-section"')
    expect(writePage).toContain('ElCollapseTransition')
    expect(writePage).toContain("import { ElCollapseTransition } from '@/fsusui/motion'")
    expect(writePage).toContain('aria-controls="write-inspector-rights"')
    expect(writePage).toContain(':aria-expanded="rightsInspectorOpen"')
    expect(writePage).toContain('type="button"')
    expect(writePage).toContain('write-inspector-summary__action')
    expect(writePage).toContain('write-inspector-summary__chevron')
    expect(writePage).toContain('@click="toggleResourcesInspector"')
    expect(writePage).toContain('const checkInspectorUserToggled = ref(false)')
    expect(writePage).toContain('const checkInspectorVisible = computed(() => checkInspectorOpen.value)')
    expect(writePage).toContain('checkInspectorUserToggled.value = true')
    expect(writePage).not.toContain('const checkInspectorVisible = computed(() => checkInspectorOpen.value || seoIssues.value.length > 0')
    expect(writePage).not.toContain('@click.prevent="toggleInspectorSection"')
    expect(writePage).not.toContain('const toggleInspectorSection = (event: MouseEvent): void')
    expect(writePage).not.toContain("details.classList.add('is-opening')")
    expect(writePage).not.toContain("details.classList.add('is-closing')")
    expect(writePage).not.toContain('.write-inspector-section::details-content')
    expect(writePage).not.toContain('interpolate-size: allow-keywords;')
    expect(writePage).not.toContain('grid-template-rows 220ms cubic-bezier(0.22, 1, 0.36, 1)')
    expect(writeSidebar).toContain('ElCollapseTransition')
    expect(writeSidebar).toContain("import { ElCollapseTransition } from '@/fsusui/motion'")
    expect(writeSidebar).toContain('aria-controls="article-sidebar-publish"')
    expect(writeSidebar).toContain(':aria-expanded="publishSectionOpen"')
    expect(writeSidebar).toContain('type="button"')
    expect(writeSidebar).not.toContain('@click.prevent="toggleSidebarSection"')
    expect(writeSidebar).not.toContain('const toggleSidebarSection = (event: MouseEvent): void')
    expect(writeSidebar).not.toContain("details.classList.add('is-opening')")
    expect(writeSidebar).not.toContain("details.classList.add('is-closing')")
    expect(writeSidebar).not.toContain('.article-sidebar-section::details-content')
    expect(writeSidebar).not.toContain('interpolate-size: allow-keywords;')
    expect(writePage).toContain('内容检查')
    expect(writePage).toContain('阅读预览')
    expect(writePage).toContain('版本')
    expect(writePage).toContain('资源')
    expect(writePage).toContain('editorLayoutMode')
    expect(writePage).toContain('write-grid--wide')
    expect(writePage).toContain('grid-template-columns: minmax(0, 1fr) minmax(16rem, min(22rem, 38%));')
  })

  it('keeps compact editor metrics right aligned on the primary status row', () => {
    expect(textEditor).toMatch(
      /@media \(max-width: 620px\)[\s\S]*\.markdown-text-editor__status \{\n\s*display: grid;\n\s*grid-template-columns: minmax\(0, 1fr\) auto;\n\s*align-items: center;\n\s*\}/
    )
    expect(textEditor).toMatch(
      /@media \(max-width: 620px\)[\s\S]*\.markdown-text-editor__status-group--primary \{\n\s*grid-column: 1;\n\s*grid-row: 1;\n\s*\}/
    )
    expect(textEditor).toMatch(
      /@media \(max-width: 620px\)[\s\S]*\.markdown-text-editor__status-group--metrics \{\n\s*grid-column: 2;\n\s*grid-row: 1;\n\s*align-items: flex-start;\n\s*justify-content: flex-end;\n\s*flex-wrap: wrap;\n\s*\}/
    )
    expect(textEditor).toMatch(
      /@media \(max-width: 620px\)[\s\S]*\.markdown-text-editor__status-group--secondary \{\n\s*grid-column: 1 \/ -1;\n\s*grid-row: 2;\n\s*align-items: flex-start;\n\s*justify-content: flex-start;\n\s*flex-wrap: wrap;\n\s*flex-direction: row;\n\s*\}/
    )
  })

  it('keeps quick taxonomy creation actionable without duplicate success toasts', () => {
    expect(writeComposable).toContain("const result = await createCategory(trimmed")
    expect(writeComposable).toContain('articleForm.categoryId = result.id')
    expect(writeComposable).toContain("const result = await createTag(trimmed")
    expect(writeComposable).toContain('articleForm.tagIds = [...articleForm.tagIds, result.id]')
    expect(writeComposable).toContain("taskFeedback.succeed('分类已创建并选中', trimmed, 'article-taxonomy')")
    expect(writeComposable).toContain("taskFeedback.succeed('标签已创建并关联', trimmed, 'article-taxonomy')")
    expect(writeComposable).not.toContain("toast.success('分类已创建并选中')")
    expect(writeComposable).not.toContain("toast.success('标签已创建并关联')")
    expect(writeComposable).not.toContain("showErrorToast(error, '分类创建失败，请稍后重试')")
    expect(writeComposable).not.toContain("showErrorToast(error, '标签创建失败，请稍后重试')")
  })
})
