import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'

const repoFile = (path: string): string => fileURLToPath(new URL(`../../../../${path}`, import.meta.url))
const readRepoFile = (path: string): string => readFileSync(repoFile(path), 'utf8')

describe('user facing workflow contract', () => {
  const messagesPage = readRepoFile('src/frontend/src/views/user/Messages.vue')
  const messagesConversationList = readRepoFile('src/frontend/src/components/user/messages/MessagesConversationList.vue')
  const messagesThreadPanel = readRepoFile('src/frontend/src/components/user/messages/MessagesThreadPanel.vue')
  const messagesInbox = readRepoFile('src/frontend/src/composables/useAccountMessagesInbox.ts')
  const loginPage = readRepoFile('src/frontend/src/views/auth/Login.vue')
  const loginComposable = readRepoFile('src/frontend/src/composables/useAuthLogin.ts')
  const registerPage = readRepoFile('src/frontend/src/views/auth/Register.vue')
  const articleDetail = readRepoFile('src/frontend/src/views/ArticleDetail.vue')
  const articleDetailComposable = readRepoFile('src/frontend/src/composables/useArticleDetailView.ts')
  const articleTocComposable = readRepoFile('src/frontend/src/composables/article/useArticleToc.ts')
  const articleCodeCopyComposable = readRepoFile('src/frontend/src/composables/article/useCodeBlockCopy.ts')
  const articleLightboxComposable = readRepoFile('src/frontend/src/composables/article/useArticleImageLightbox.ts')
  const commentList = readRepoFile('src/frontend/src/components/article/ArticleCommentsVirtualList.vue')
  const publicArticleList = readRepoFile('src/frontend/src/components/public/PublicArticleList.vue')
  const publicArticleDetail = readRepoFile('src/frontend/src/components/public/pages/PublicArticleDetailPageContent.vue')
  const router = readRepoFile('src/frontend/src/router/index.ts')
  const app = readRepoFile('src/frontend/src/App.vue')
  const publicShell = readRepoFile('src/frontend/src/bootstrap/publicShell.ts')
  const homeView = readRepoFile('src/frontend/src/views/Home.vue')
  const homeContent = readRepoFile('src/frontend/src/components/public/pages/PublicHomePageContent.vue')
  const homeComposable = readRepoFile('src/frontend/src/composables/useHomeView.ts')
  const filterContent = readRepoFile('src/frontend/src/components/public/pages/PublicFilterPageContent.vue')
  const filterComposable = readRepoFile('src/frontend/src/composables/useFilterView.ts')
  const archiveContent = readRepoFile('src/frontend/src/components/public/pages/PublicArchivePageContent.vue')
  const readingPageFrame = readRepoFile('src/frontend/src/components/public/PublicReadingPageFrame.vue')
  const profilePage = readRepoFile('src/frontend/src/views/user/Profile.vue')
  const mfaSetupModal = readRepoFile('src/frontend/src/components/ui/MfaSetupModal.vue')
  const userCommentsPage = readRepoFile('src/frontend/src/views/user/Comments.vue')
  const userCommentsComposable = readRepoFile('src/frontend/src/composables/useUserCommentsPage.ts')
  const aboutContent = readRepoFile('src/frontend/src/components/public/pages/PublicAboutPageContent.vue')
  const forbiddenPage = readRepoFile('src/frontend/src/views/error/403.vue')
  const notFoundPage = readRepoFile('src/frontend/src/views/error/404.vue')

  it('protects message replies with per-conversation drafts and URL state', () => {
    expect(messagesInbox).toContain('replyDrafts')
    expect(messagesInbox).toContain('pendingConversationId')
    expect(messagesInbox).toContain("name: 'UserMessage'")
    expect(messagesInbox).toContain('query.conversation = selectedConversationId.value')
    expect(messagesThreadPanel).toContain('replyDisabled || !replyBody.trim()')
    expect(messagesPage).toContain('showMobileTicketCompose')
    expect(messagesConversationList).toContain('conversationListCopy.newTicketCta')
  })

  it('keeps auth copy and MFA modes aligned with backend expectations', () => {
    expect(loginComposable).toContain("type MfaMode = 'totp' | 'recovery'")
    expect(loginPage).toContain('copy.description')
    expect(loginPage).toContain('value="totp"')
    expect(loginPage).toContain('value="recovery"')
    expect(loginPage).toContain('copy.passkeyFailureHint')
    expect(loginPage).toContain('to="/recover"')
    expect(loginPage).toContain('copy.recoverLink')
    expect(loginPage).toContain('v-if="!requiresMfa"')
    expect(loginPage).not.toContain('anonymousIdentityMode')
    expect(loginComposable).not.toContain('loginData')
    expect(registerPage).toContain('copy.title')
    expect(registerPage).toContain('copy.recoveryKeySavedCheckbox')
    expect(registerPage).not.toContain('autocomplete="new-password"')
  })

  it('routes guest comment replies through login and keeps comment actions explicit', () => {
    expect(commentList).toContain("{{ isLoggedIn ? '回复' : '登录后回复' }}")
    expect(articleDetailComposable).toContain('redirect: commentsRedirectPath()')
    expect(articleDetailComposable).toContain("return `${current}#comments`")
    expect(articleDetailComposable).toContain('内容摘要')
    expect(articleDetailComposable).toContain("toast.success('已提交审核')")
    expect(commentList).toContain('COMMENT_CONTENT_CONSTRAINT.replyRenderLimit')
    expect(articleDetail).toContain('加载更多评论')
    expect(articleDetail).toContain('article-comments-load-more')
    expect(publicArticleDetail).toContain('id="comments"')
    expect(publicArticleList).toContain('`阅读全文：${item.title}`')
    expect(publicArticleList).toContain('public-article-tag el-tag el-tag--small el-tag--light')
    expect(publicArticleList).not.toContain('<UiTag')
  })

  it('keeps public article detail constrained to a readable width', () => {
    expect(publicArticleDetail).toContain('data-readable-region')
    expect(publicArticleDetail).toContain('max-w-[760px]')
    expect(publicArticleDetail).not.toContain('max-w-4xl')
  })

  it('keeps article reading aids progressive and hash navigation stable', () => {
    expect(router).toContain('if (to.hash)')
    expect(router).toContain("to.hash === '#top'")
    expect(router).toContain('el: to.hash')
    expect(router).not.toContain('Ensure scroll to top on every navigation completion')
    expect(app).not.toContain('Ensure top reset for shell-to-SPA anchor navigation')
    expect(publicShell).toContain("window.location.hash === '#comments'")
    expect(publicShell).toContain("action === 'activate-comments'")
    expect(publicArticleDetail).toContain('<slot name="header-actions" />')
    expect(articleDetail).toContain('<ArticleReadingProgress')
    expect(articleDetail).toContain('<ArticleTocPanel')
    expect(articleDetail).toContain('<ArticleImageLightbox')
    expect(articleDetail).not.toContain('<ArticleMobileActionBar')
    expect(articleDetail).toContain('handleArticleRenderComplete')
    expect(articleDetail).not.toContain('navigateToComments')
    expect(articleTocComposable).toContain("querySelectorAll<HTMLElement>('h2, h3')")
    expect(articleTocComposable).toContain('IntersectionObserver')
    expect(articleCodeCopyComposable).toContain("ENHANCED_ATTR = 'data-fsus-code-copy'")
    expect(articleCodeCopyComposable).toContain("button.textContent = '复制'")
    expect(articleLightboxComposable).toContain("const link = image.closest('a')")
    expect(articleLightboxComposable).toContain('return !(link instanceof HTMLAnchorElement && link.href)')
  })

  it('syncs public list/filter pagination and exposes useful empty/navigation affordances', () => {
    expect(homeComposable).toContain('parsePageQuery(route.query.page)')
    expect(homeComposable).toContain('nextQuery.page = String(page)')
    expect(homeComposable).toContain('HOME_HOT_ARTICLE_PREFETCH_COUNT = 10')
    expect(homeComposable).toContain('HOME_HOT_ARTICLE_DISPLAY_COUNT = 5')
    expect(homeContent).toContain('usePublicSiteTitle')
    expect(homeContent).toContain('usePublicSiteDescription')
    expect(homeComposable).not.toContain('usePublicSiteTitle')
    expect(homeComposable).not.toContain('usePublicSiteDescription')
    expect(homeComposable).not.toContain('initialSiteTitleText')
    expect(homeComposable).not.toContain('initialSiteDescriptionText')
    expect(homeView).not.toContain(':site-title-text=')
    expect(homeView).not.toContain(':site-description-text=')
    expect(homeContent).not.toContain('siteTitleText ||')
    expect(homeComposable).not.toContain('getHotArticles(8')
    expect(filterComposable).toContain('parsePageQuery(route.query.page)')
    expect(filterComposable).toContain('delete nextQuery.page')
    expect(homeContent).toContain('HomeFeedSurface')
    expect(homeContent).toContain('fsus-home-secondary-content-sentinel')
    expect(filterContent).toContain('view.empty.actionText')
    expect(archiveContent).toContain('年份快速导航')
    expect(archiveContent).toContain('#archive-year-')
  })

  it('routes profile settings to the anonymous identity center', () => {
    expect(profilePage).toContain('profileCopy.pageTitle')
    expect(profilePage).toContain("router.replace({ name: 'UserIdentityOverview' })")
    expect(profilePage).toContain('profileCopy.openIdentityCta')
    expect(profilePage).not.toContain('账号信息')
    expect(profilePage).not.toContain('当前密码')
    expect(profilePage).not.toContain('确认新密码')
    expect(profilePage).not.toContain('UNKNOWN IP')
    expect(profilePage).not.toContain('Permanent Deletion')
    expect(mfaSetupModal).toContain('copyRecoveryCodes')
    expect(mfaSetupModal).toContain('downloadRecoveryCodes')
    expect(mfaSetupModal).toContain('copyOtpAuthUrl')
    expect(mfaSetupModal).toContain('copySecret')
    expect(mfaSetupModal).not.toContain(':href="otpAuthUrl"')
    expect(mfaSetupModal).not.toContain('在 App 中直接打开')
    expect(mfaSetupModal).toContain('copy.savedRecoveryCodesCheckbox')
  })

  it('keeps user comments and error recovery paths searchable and reversible', () => {
    expect(userCommentsComposable).toContain('filteredList')
    expect(userCommentsComposable).toContain("type CommentTimeFilter = 'all' | '7d' | '30d'")
    expect(userCommentsComposable).toContain('删除公开评论')
    expect(userCommentsComposable).toContain('只会移除这条公开评论记录')
    expect(userCommentsPage).toContain('userCommentSearch')
    expect(userCommentsPage).toContain('userCommentTimeFilter')
    expect(userCommentsPage).toContain('公开评论记录')
    expect(userCommentsPage).toContain('匿名评论不进入账号记录')
    expect(userCommentsPage).toContain('暂无公开评论记录')
    expect(aboutContent).toContain('回到首页')
    expect(forbiddenPage).toContain('redirect: route.fullPath')
    expect(notFoundPage).toContain('to="/search"')
    expect(notFoundPage).toContain('to="/archive"')
  })

  it('keeps archive and static public pages on one shared reading frame', () => {
    expect(readingPageFrame).toContain('public-reading-page-frame')
    expect(readingPageFrame).toContain('min-height: clamp(24rem, 48vh, 34rem);')
    expect(readingPageFrame).toContain('max-width: 48rem;')
    expect(readingPageFrame).toContain('padding-inline: 0;')
    expect(readingPageFrame).not.toContain('padding-inline: 1.25rem;')
    expect(readingPageFrame).not.toContain('padding-inline: 2rem;')
    expect(archiveContent).toContain('PublicReadingPageFrame')
    expect(aboutContent).toContain('PublicReadingPageFrame')
    expect(archiveContent).not.toContain("view.yearGroups.length > 0 ? 'min-h-screen' : ''")
    expect(archiveContent).not.toContain('blog-page-shell max-w-3xl mx-auto px-5 sm:px-8 flex flex-col')
    expect(aboutContent).not.toContain('blog-page-shell max-w-3xl mx-auto px-5 sm:px-8 flex flex-col')
    expect(aboutContent).not.toContain('view.footer.siteTitle')
    expect(archiveContent).not.toContain('v-else class="relative pb-32"')
    expect(archiveContent).toContain('v-if="view.yearGroups.length > 0"')
    expect(archiveContent).not.toContain('max-w-4xl mx-auto px-6 sm:px-12')
    expect(archiveContent).not.toContain('pt-16 sm:pt-24')
    expect(archiveContent).not.toContain('py-24 sm:py-32 md:py-48 text-center')
  })
})
