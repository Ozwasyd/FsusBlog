import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';
import test from 'node:test';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const source = 'src/shared/Contracts/AuthSystem/user-session-authentication-contract.json';
const script = path.join(root, 'tools/contracts/generate-auth-session-contract.mjs');
const catalog = JSON.parse(fs.readFileSync(path.join(root, source), 'utf8'));
const { isCurrentSessionAuthentication, isCurrentIdentityKind, sessionModeFromWire } = await import(pathToFileURL(path.join(root, 'src/frontend/src/generated/authSessionContract.ts')));

test('current projections are exactly generated by the sole contract owner', () =>
{
    const result = spawnSync(process.execPath, [script, '--check'], { encoding: 'utf8' });
    assert.equal(result.status, 0, `${result.stdout}\n${result.stderr}`);
});

for (const combination of catalog.combinations)
{
    test(`frontend admits ${combination.method}/${combination.strength} with both current durations`, () =>
    {
        for (const durationPolicy of Object.values(catalog.durationPolicies))
        {
            for (const sessionMode of Object.values(catalog.modes))
            {
            assert.equal(isCurrentSessionAuthentication({
                authenticationMethod: catalog.methods[combination.method],
                authenticationStrength: catalog.strengths[combination.strength],
                durationPolicy,
                sessionMode
            }), true);
            }
        }
    });
}

for (const invalid of [
    null,
    {},
    { authenticationMethod: 'other', authenticationStrength: 'webauthn_uv', durationPolicy: 'browser_session', sessionMode: 'normal' },
    { authenticationMethod: 'passkey', authenticationStrength: 'legacy_verified', durationPolicy: 'browser_session', sessionMode: 'normal' },
    { authenticationMethod: 'passkey', authenticationStrength: 'legacy_unverified', durationPolicy: 'browser_session', sessionMode: 'normal' },
    { authenticationMethod: 'passkey', authenticationStrength: 'recovery', durationPolicy: 'browser_session', sessionMode: 'normal' },
    { authenticationMethod: 'passkey', authenticationStrength: 'webauthn_uv', durationPolicy: 'unknown', sessionMode: 'normal' },
    { authenticationMethod: ' passkey ', authenticationStrength: 'webauthn_uv', durationPolicy: 'browser_session', sessionMode: 'normal' }
])
{
    test(`frontend refuses an unsupported authentication projection ${JSON.stringify(invalid)}`, () =>
    {
        assert.equal(isCurrentSessionAuthentication(invalid), false);
    });
}

test('current identity values are exact and wire modes refuse unknown byte values', () =>
{
    assert.equal(isCurrentIdentityKind('anonymous_account'), true);
    assert.equal(isCurrentIdentityKind('admin_principal'), true);
    for (const invalid of ['', ' anonymous_account ', 'ANONYMOUS_ACCOUNT', 'legacy_user', null])
    {
        assert.equal(isCurrentIdentityKind(invalid), false);
    }
    assert.equal(sessionModeFromWire(0), 'normal');
    assert.equal(sessionModeFromWire(1), 'restricted');
    assert.equal(sessionModeFromWire(2), 'revoked');
    assert.equal(sessionModeFromWire(3), undefined);
    assert.equal(isCurrentSessionAuthentication({
        authenticationMethod: 'passkey', authenticationStrength: 'webauthn_uv',
        durationPolicy: 'browser_session', sessionMode: 'unknown'
    }), false);
});

for (const retired of ['other', 'legacy_verified', 'legacy_unverified'])
{
    test(`generator refuses to reintroduce retired ${retired}`, () =>
    {
        const fixture = fs.mkdtempSync(path.join(os.tmpdir(), 'fsus1771-contract-'));
        try
        {
            const changed = structuredClone(catalog);
            changed.methods.Retired = retired;
            const target = path.join(fixture, source);
            fs.mkdirSync(path.dirname(target), { recursive: true });
            fs.writeFileSync(target, JSON.stringify(changed));
            const result = spawnSync(process.execPath, [script, '--root', fixture], { encoding: 'utf8' });
            assert.notEqual(result.status, 0);
            assert.match(result.stderr, /Invalid authentication catalog/u);
            assert.equal(fs.existsSync(path.join(fixture, 'src/frontend/src/generated/authSessionContract.ts')), false);
        }
        finally
        {
            fs.rmSync(fixture, { recursive: true, force: true });
        }
    });
}

for (const [key, name, wire] of [['methods', 'RecoveryKey', 'recovery_key'], ['strengths', 'Recovery', 'recovery']])
{
    test(`generator refuses ${wire} without an actual producer combination`, () =>
    {
        const fixture = fs.mkdtempSync(path.join(os.tmpdir(), 'fsus1771-contract-'));
        try
        {
            const changed = structuredClone(catalog);
            changed[key][name] = wire;
            const target = path.join(fixture, source);
            fs.mkdirSync(path.dirname(target), { recursive: true });
            fs.writeFileSync(target, JSON.stringify(changed));
            const result = spawnSync(process.execPath, [script, '--root', fixture], { encoding: 'utf8' });
            assert.notEqual(result.status, 0);
            assert.match(result.stderr, /no current producer combination/u);
            assert.equal(fs.existsSync(path.join(fixture, 'src/shared/Contracts/AuthSystem/UserSessionAuthenticationContract.generated.cs')), false);
        }
        finally
        {
            fs.rmSync(fixture, { recursive: true, force: true });
        }
    });
}
