import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { formatPropertyReadTypeScript } from './format-generated-property-value-read-typescript.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const read = file => readFileSync(path.join(root, file), 'utf8');
const specText = read('src/shared/Contracts/Validation/author-article-selection-wire.json');
const spec = JSON.parse(specText);
const owner = read(spec.contractSource);
for (const [name, fields] of Object.entries(spec.records)) {
    const actual = owner.match(new RegExp(`public sealed record ${name}\\(([\\s\\S]*?)\\);`));
    if (!actual || JSON.stringify(actual[1].split(',').map(field => field.trim())) !== JSON.stringify(fields)) throw new Error(`selection contract drift:${name}`);
}
for (const [name, expected] of Object.entries({ SchemaVersion: 1, MaxSiteScopeLength: 128, PermissionTokenLength: 64, RequestPayloadBytes: 100, MaxResponsePayloadBytes: 626 })) {
    if (!owner.includes(`public const int ${name} = ${expected};`)) throw new Error(`selection bound drift:${name}`);
}
const protocol = JSON.parse(read('src/shared/Contracts/Validation/aeds-protocol.json'));
for (const [name, value] of Object.entries(spec.roots)) {
    const active = protocol.frameTypes.find(frame => frame.name === name);
    if (!active || active.value !== value.value || active.goldenFamily !== spec.family) throw new Error(`selection registration drift:${name}`);
}
if (spec.requestPayloadBytes !== 100 || spec.maxResponsePayloadBytes !== 626 || spec.siteScopeMaxUtf16 !== 128
    || spec.siteScopeMaxUtf8 !== 512 || spec.nativeError.value !== 17 || spec.schemaVersion !== 1) throw new Error('selection wire owner drift');
const header = `// <auto-generated by tools/contracts/generate-author-article-selection-wire.mjs>\n// Shared contract and wire owner SHA256 ${createHash('sha256').update(owner + specText).digest('hex')}; Int64 stays lossless.\n`;
const outputs = [
    ['cs', 'src/core/Cache/PodBinaryCodec.AuthorArticleSelection.Generated.cs'],
    ['ts', 'src/frontend/src/codecs/binary/authorArticleSelectionWire.generated.ts'],
    ['hpp', 'src/frontend/wasm/aeds/include/author_article_selection_wire.generated.hpp']
];
for (const [extension, output] of outputs) {
    let text = header + read(`tools/contracts/author-article-selection-wire-templates/wire.${extension}.inc`);
    if (extension === 'ts') text = await formatPropertyReadTypeScript(text, root, output);
    if (process.argv.includes('--check')) {
        if (read(output) !== text) { process.stderr.write(`stale:${output}\n`); process.exitCode = 1; }
    } else writeFileSync(path.join(root, output), text);
}
