import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { formatPropertyReadTypeScript } from './format-generated-property-value-read-typescript.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const read = file => readFileSync(path.join(root, file), 'utf8');
const specText = read('src/shared/Contracts/Validation/document-export-source-options-wire.json');
const spec = JSON.parse(specText);
const owner = read(spec.contractSource);
const codec = read(spec.managedCodecSource);
const hash = text => createHash('sha256').update(text).digest('hex');
if (hash(codec) !== spec.managedCodecSha256)
{
    throw new Error('document-export-source-options managed codec drift');
}
for (const [name, fields] of Object.entries(spec.records))
{
    const actual = owner.match(new RegExp(`public (?:sealed record|readonly record struct) ${name}\\(([\\s\\S]*?)\\);`));
    if (!actual || JSON.stringify(actual[1].split(',').map(field => field.trim())) !== JSON.stringify(fields))
    {
        throw new Error(`document-export-source-options model drift:${name}`);
    }
}
const protocol = JSON.parse(read('src/shared/Contracts/Validation/aeds-protocol.json'));
for (const [name, expected] of Object.entries(spec.roots))
{
    const active = protocol.frameTypes.find(frame => frame.name === name);
    const reserved = (protocol.reservedFrameValues ?? []).find(frame => frame.name === name);
    if (active ? active.value !== expected.value || active.goldenFamily !== expected.family : !reserved || reserved.value !== expected.value || reserved.ownerIssue !== 3735)
    {
        throw new Error(`document-export-source-options registration drift:${name}`);
    }
}
if (spec.payloadRevision !== 1 || spec.maximumChoices !== 50 || spec.privateMaximumBindingsPerScope !== 512 || spec.choiceIdLength !== 64 || spec.maximumDraftKeyUtf16 !== 96 || spec.maximumLabelUtf16 !== 256 || spec.nativeError.value !== 19)
{
    throw new Error('document-export-source-options bounds drift');
}
const camel = name => name[0].toLowerCase() + name.slice(1);
const short = name => name.replace('CoreModel', '');
const fields = Object.fromEntries(Object.entries(spec.records).map(([name, values]) => [short(name), values.map(field =>
{
    const index = field.lastIndexOf(' ');
    return [camel(field.slice(index + 1)), short(field.slice(0, index))];
})]));
const type = value => value.endsWith('?') ? `${type(value.slice(0, -1))} | null` : value.startsWith('IReadOnlyList<') ? `readonly ${type(value.slice(14, -1))}[]` : ({ int: 'number', long: 'string', string: 'string', bool: 'boolean' }[value] ?? value);
const declarations = Object.entries(fields).map(([name, values]) => `export interface ${name} {\n${values.map(([key, value]) => `    ${key}: ${type(value)};`).join('\n')}\n}\n`).join('');
const schemas = `const schemas: Readonly<Record<string, readonly (readonly [string, string])[]>> = ${JSON.stringify(fields, null, 4)};\n`;
const budgets = `const budgets: Readonly<Record<string, number>> = ${JSON.stringify(Object.fromEntries(Object.values(spec.roots).map(value => [short(value.model), value.maxPayloadBytes])), null, 4)};\n`;
const exports = Object.values(spec.roots).map(value =>
{
    const name = short(value.model);
    return `export function encode${name}(value: ${name}): Uint8Array { return encodeRoot('${name}', value); }\nexport function decode${name}(payload: Uint8Array): ${name} { return decodeRoot('${name}', payload) as unknown as ${name}; }\n`;
}).join('');
const header = `// <auto-generated by tools/contracts/generate-document-export-source-options-wire.mjs>\n// Exact Shared/model/managed owner SHA256 ${hash(specText + owner + codec)}; wire validation only.\n`;
for (const [extension, output] of [['ts', 'src/frontend/src/codecs/binary/documentExportSourceOptionsWire.generated.ts'], ['hpp', 'src/frontend/wasm/aeds/include/document_export_source_options_wire.generated.hpp']])
{
    let text = header + (extension === 'ts' ? declarations + schemas + budgets : '') + read(`tools/contracts/document-export-source-options-wire-templates/wire.${extension}.inc`) + (extension === 'ts' ? exports : '');
    if (extension === 'hpp')
    {
        text = text.replace('@@BUDGET_CASES@@', Object.values(spec.roots).map(value => `        case ${value.value}:return ${value.maxPayloadBytes};`).join('\n'));
    }
    if (extension === 'ts')
    {
        if (!existsSync(path.join(root, output)))
        {
            if (process.argv.includes('--check'))
            {
                throw new Error(`missing:${output}`);
            }
            writeFileSync(path.join(root, output), text);
        }
        text = await formatPropertyReadTypeScript(text, root, output);
    }
    if (process.argv.includes('--check'))
    {
        if (read(output) !== text)
        {
            process.stderr.write(`stale:${output}\n`);
            process.exitCode = 1;
        }
    }
    else
    {
        writeFileSync(path.join(root, output), text);
    }
}
