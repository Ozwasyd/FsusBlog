import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const checkOnly = process.argv.includes('--check');
const sources = {
    contract: 'src/shared/Contracts/Validation/Security/perception-character-v3-contract.json',
    aeds: 'src/shared/Contracts/Validation/aeds-protocol.json',
    sharedContract: 'src/shared/Contracts/Security/PerceptionCharacterV3Contracts.cs',
    sharedPods: 'src/shared/Contracts/Models/PerceptionCharacterV3Pods.cs',
    coreCodec: 'src/core/Cache/PodBinaryCodec.PerceptionCharacterV3.cs',
    frontendCodec: 'src/frontend/src/codecs/binary/securityRequestEncoder.ts',
    frontendAdapter: 'src/frontend/src/adapters/binary/securityAdapter.ts'
};

const bytes = Object.fromEntries(await Promise.all(Object.entries(sources).map(async ([name, relative]) =>
    [name, await readFile(path.join(root, relative))])));
const contract = JSON.parse(bytes.contract);
const aeds = JSON.parse(bytes.aeds);

const sha256 = value => createHash('sha256').update(value).digest('hex');
const frame = name =>
{
    const entry = aeds.frameTypes.find(candidate => candidate.name === name);
    if (!entry)
    {
        throw new Error(`AEDS frame ${name} is missing`);
    }
    return entry.value;
};

const schemaMaterial = Buffer.concat([
    bytes.aeds,
    bytes.sharedContract,
    bytes.sharedPods,
    bytes.coreCodec,
    bytes.frontendCodec,
    bytes.frontendAdapter
]);
const projection = {
    schema: 'fsusblog.security.perception-character-v3-release-target.v1',
    algorithm: contract.algorithm,
    wireName: contract.wireName,
    contractDigest: sha256(bytes.contract),
    aedsSchemaFingerprint: sha256(schemaMaterial),
    frames: {
        issueRequest: frame('SecurityChallengeIssueRequest'),
        verifyRequest: frame('SecurityChallengeVerifyRequest'),
        issueResponse: frame('SecurityChallengeIssueResponse'),
        verifyResponse: frame('SecurityChallengeVerifyResponse')
    },
    unionKind: 14,
    media: {
        visual: {
            mediaType: contract.media.visual.mediaType,
            physicalWidth: contract.raster.physicalWidth,
            physicalHeight: contract.raster.physicalHeight,
            displayWidth: contract.raster.displayWidth,
            displayHeight: contract.raster.displayHeight,
            maximumBytes: contract.media.visual.maximumBytes
        },
        audio: {
            mediaType: contract.media.audio.mediaType,
            maximumBytes: contract.media.audio.maximumBytes
        }
    }
};
projection.targetFingerprint = sha256(Buffer.from(JSON.stringify(projection)));

const json = `${JSON.stringify(projection, null, 2)}\n`;
const cs = `// <auto-generated />
// Generated by tools/contracts/generate-perception-character-v3-release-target.mjs.

namespace FsusBlog.Server.Services.Security;

public static class PerceptionCharacterV3ReleaseTarget
{
    public const string Schema = "${projection.schema}";
    public const string Algorithm = "${projection.algorithm}";
    public const string WireName = "${projection.wireName}";
    public const string ContractDigest = "${projection.contractDigest}";
    public const string AedsSchemaFingerprint = "${projection.aedsSchemaFingerprint}";
    public const string TargetFingerprint = "${projection.targetFingerprint}";
}
`;

const outputs = [
    ['src/shared/Contracts/Validation/Security/perception-character-v3-release-target.json', json],
    ['src/frontend/public/generated/perception-character-v3-release-target.json', json],
    ['src/backend/Services/Security/PerceptionCharacterV3ReleaseTarget.Generated.cs', cs]
];

let drift = false;
for (const [relative, expected] of outputs)
{
    const absolute = path.join(root, relative);
    let current = '';
    try
    {
        current = await readFile(absolute, 'utf8');
    }
    catch (error)
    {
        if (error?.code !== 'ENOENT')
        {
            throw error;
        }
    }
    if (current === expected)
    {
        continue;
    }
    if (checkOnly)
    {
        drift = true;
        process.stderr.write(`[perception-character-v3-release-target] stale ${relative}\n`);
    }
    else
    {
        await writeFile(absolute, expected);
    }
}

if (drift)
{
    process.exitCode = 1;
}
else
{
    process.stdout.write(`[perception-character-v3-release-target] ${checkOnly ? 'in sync' : 'generated'} ${projection.targetFingerprint}\n`);
}
