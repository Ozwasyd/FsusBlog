if (process.argv.includes('--check'))
{
    check(csharpPath, csharp);
    check(typescriptPath, typescript);
    console.log('[pospace-v1-contract] generated files are in sync');
}
else
{
    writeFileSync(csharpPath, csharp);
    writeFileSync(typescriptPath, typescript);
    console.log('[pospace-v1-contract] generated C# and TypeScript contracts');
}

function validate(value)
{
    const materialFields = [
        'domain',
        'challengeId',
        'action',
        'routeKey',
        'subjectHash',
        'clientIpHash',
        'deviceFpHash',
        'policyVersion',
        'nonceHex',
        'targetDurationMs'
    ];
    for (const key of ['memoryKib', 'iterations', 'lanes', 'targetDurationMs'])
    {
        const range = value[key];
        if (!Number.isSafeInteger(range?.min) || !Number.isSafeInteger(range?.max)
      || !Number.isSafeInteger(range?.default) || range.min > range.default || range.default > range.max)
        {
            throw new Error(`invalid ${key} range`);
        }
    }
    if (!Array.isArray(value.unsupportedReasons) || new Set(value.unsupportedReasons).size !== value.unsupportedReasons.length)
    {
        throw new Error('unsupportedReasons must be a unique array');
    }
    if (!Array.isArray(value.materialFields)
    || JSON.stringify(value.materialFields) !== JSON.stringify(materialFields))
    {
        throw new Error('materialFields must match the canonical derive order');
    }
}

function check(file, expected)
{
    if (readFileSync(file, 'utf8') !== expected)
    {
        throw new Error(`${path.relative(root, file)} is stale; run node tools/contracts/generate-pospace-v1-contract.mjs`);
    }
}
