import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const manifestRelative = 'src/shared/Contracts/Validation/public-representation-coordinate.json';
const manifestPath = path.join(root, manifestRelative);
const checkOnly = process.argv.includes('--check');
const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));

const fail = (message) =>
{
    throw new Error(`[public-representation-coordinate] ${message}`);
};

if (manifest.schema !== 'fsusblog.public-representation-coordinate.v1' || manifest.coordinateVersion !== 1)
{
    fail('unsupported schema or coordinateVersion');
}
if (manifest.digestAlgorithm !== 'sha256' || manifest.canonicalSerialization !== 'length-prefixed-utf8-v1')
{
    fail('digest authority must remain sha256 with length-prefixed-utf8-v1 serialization');
}

const fieldNames = new Set();
for (const field of manifest.fields ?? [])
{
    if (!/^[a-z][A-Za-z0-9]*$/u.test(field.name) || fieldNames.has(field.name))
    {
        fail(`invalid or duplicate field ${field.name}`);
    }
    fieldNames.add(field.name);
}
for (const name of manifest.invariants ?? [])
{
    if (!fieldNames.has(name))
    {
        fail(`unknown invariant ${name}`);
    }
}

const transitionIds = new Set();
for (const transition of manifest.transitions ?? [])
{
    if (!/^[a-z][a-z0-9-]*$/u.test(transition.id) || transitionIds.has(transition.id))
    {
        fail(`invalid or duplicate transition ${transition.id}`);
    }
    transitionIds.add(transition.id);
    for (const name of [...transition.preserves, ...transition.seals])
    {
        if (!fieldNames.has(name))
        {
            fail(`${transition.id} references unknown field ${name}`);
        }
    }
}

const csType = (field) =>
{
    if (field.type === 'string' || field.type === 'sha256')
    {
        return 'string';
    }
    if (field.type === 'uint8')
    {
        return 'byte';
    }
    if (field.type === 'uint64')
    {
        return 'ulong';
    }
    fail(`unsupported C# field type ${field.type}`);
};
const tsType = (field) => field.type === 'uint8' ? 'number' : 'string';
const csName = (name) => name[0].toUpperCase() + name.slice(1);
const enumName = (id) => id.split('-').map((part) => part[0].toUpperCase() + part.slice(1)).join('');
const notice = `Generated from ${manifestRelative}; do not edit by hand.`;

const csharp = `// <auto-generated />\n// ${notice}\n\nnamespace FsusBlog.Shared.Contracts.Validation;\n\n/// <summary>Identifies one immutable public representation across storage, transport, and browser projections.</summary>\npublic sealed record PublicRepresentationCoordinate(\n${manifest.fields.map((field) => `    ${csType(field)} ${csName(field.name)}`).join(',\n')});\n\n/// <summary>Lists public representation transitions governed by the canonical coordinate contract.</summary>\npublic enum PublicRepresentationTransition : byte\n{\n${manifest.transitions.map((transition, index) => `    ${enumName(transition.id)} = ${index + 1}`).join(',\n')}\n}\n\n/// <summary>Exposes the generated public representation coordinate schema and invariant set.</summary>\npublic static class PublicRepresentationCoordinateContract\n{\n    public const int Version = ${manifest.coordinateVersion};\n    public const string Schema = \"${manifest.schema}\";\n    public const string DigestAlgorithm = \"${manifest.digestAlgorithm}\";\n    public const string CanonicalSerialization = \"${manifest.canonicalSerialization}\";\n\n    public static readonly IReadOnlyList<string> Invariants =\n    [\n${manifest.invariants.map((name) => `        \"${name}\",`).join('\n')}\n    ];\n}\n`;

const typescript = `// ${notice}\n\nexport const PUBLIC_REPRESENTATION_COORDINATE_SCHEMA = '${manifest.schema}' as const\nexport const PUBLIC_REPRESENTATION_COORDINATE_VERSION = ${manifest.coordinateVersion} as const\nexport const PUBLIC_REPRESENTATION_INVARIANTS = ${JSON.stringify(manifest.invariants, null, 2)} as const\nexport const PUBLIC_REPRESENTATION_TRANSITIONS = ${JSON.stringify(manifest.transitions.map((item) => item.id), null, 2)} as const\n\nexport type PublicRepresentationCoordinate = Readonly<{\n${manifest.fields.map((field) => `  ${field.name}: ${tsType(field)}`).join('\n')}\n}>\n\nexport type PublicRepresentationTransition = typeof PUBLIC_REPRESENTATION_TRANSITIONS[number]\n`;

const cpp = `// ${notice}\n#pragma once\n\n#include <array>\n#include <cstdint>\n#include <string_view>\n\nnamespace FsusBlog::PublicRepresentation\n{\ninline constexpr std::uint8_t kCoordinateVersion = ${manifest.coordinateVersion}U;\ninline constexpr std::string_view kSchema = \"${manifest.schema}\";\ninline constexpr std::array<std::string_view, ${manifest.fields.length}> kCoordinateFields = {\n${manifest.fields.map((field) => `    \"${field.name}\",`).join('\n')}\n};\ninline constexpr std::array<std::string_view, ${manifest.transitions.length}> kTransitions = {\n${manifest.transitions.map((transition) => `    \"${transition.id}\",`).join('\n')}\n};\n} // namespace FsusBlog::PublicRepresentation\n`;

const outputs = [
    ['src/shared/Contracts/Validation/PublicRepresentationCoordinate.Generated.cs', csharp],
    ['tools/contracts/generated/public-representation-coordinate.evidence.ts', typescript],
    ['src/frontend/wasm/aeds/include/public_representation_coordinate.hpp', cpp]
];

let drift = false;
for (const [relative, expected] of outputs)
{
    const target = path.join(root, relative);
    let current = '';
    try
    {
        current = await readFile(target, 'utf8');
    }
    catch
    {
    // A missing generated surface is drift in check mode.
    }
    if (current === expected)
    {
        continue;
    }
    if (checkOnly)
    {
        console.error(`[public-representation-coordinate] ${relative} is stale`);
        drift = true;
    }
    else
    {
        await writeFile(target, expected);
        console.log(`[public-representation-coordinate] wrote ${relative}`);
    }
}

if (drift)
{
    process.exitCode = 1;
}
else if (checkOnly)
{
    console.log('[public-representation-coordinate] generated surfaces are in sync');
}
