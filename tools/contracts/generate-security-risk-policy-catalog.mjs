import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const catalogPath = 'src/shared/Contracts/Security/SecurityRiskPolicyCatalog.cs';
const challengePath = 'src/shared/Contracts/Security/SecurityChallengeContracts.cs';
const outputPath = 'src/frontend/src/contracts/securityRiskPolicyCatalog.generated.ts';

export function renderSecurityRiskPolicyCatalog(catalog, challenge)
{
    const classes = [...catalog.matchAll(/public static class (\w+)\s*\{([\s\S]*?)\n\}/gu)];
    if (classes.length !== 4)
    {
        throw new Error('The current risk catalog must contain all four canonical authorities.');
    }
    const blocks = classes.map(([, name, body]) =>
    {
        const values = [...body.matchAll(/public const (?:string|int) (\w+) = ("[^"]+"|\d+);/gu)];
        if (values.length === 0 || new Set(values.map(([, key]) => key)).size !== values.length)
        {
            throw new Error(`Empty or duplicated catalog: ${name}`);
        }
        return `export const ${name} = {\n${values.map(([, key, value]) => `    ${key}: ${value}`).join(',\n')}\n} as const;\n\nexport type ${name}Value = typeof ${name}[keyof typeof ${name}];\n`;
    });
    const enumBody = challenge.match(/enum SecurityChallengeKind : byte\s*\{([\s\S]*?)\n\}/u)?.[1];
    const kinds = [...(enumBody ?? '').matchAll(/(\w+)\s*=\s*(\d+)/gu)];
    const wireNames = [...challenge.matchAll(/SecurityChallengeKind\.(\w+)\s*=>\s*"([^"]+)"/gu)];
    const wireMap = new Map(wireNames.map(([, kind, wire]) => [kind, wire]));
    if (kinds.length === 0 || kinds.some(([ , kind]) => kind !== 'Unknown' && !wireMap.has(kind)))
    {
        throw new Error('Challenge wire catalog is not exhaustive.');
    }
    return `// Generated by tools/contracts/generate-security-risk-policy-catalog.mjs; do not edit.\n\n${blocks.join('\n')}\nexport const securityChallengeKindWireNames = {\n${kinds.map(([, kind, value]) => `    ${value}: '${kind === 'Unknown' ? 'unknown' : wireMap.get(kind)}'`).join(',\n')}\n} as const;\n`;
}

export function generateSecurityRiskPolicyCatalog({ check = false } = {})
{
    const rendered = renderSecurityRiskPolicyCatalog(fs.readFileSync(path.join(root, catalogPath), 'utf8'), fs.readFileSync(path.join(root, challengePath), 'utf8'));
    const destination = path.join(root, outputPath);
    if (check)
    {
        if (fs.readFileSync(destination, 'utf8') !== rendered)
        {
            throw new Error('Current risk policy projection is stale; run the canonical generator.');
        }
    }
    else
    {
        fs.writeFileSync(destination, rendered);
    }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url))
{
    generateSecurityRiskPolicyCatalog({ check: process.argv.includes('--check') });
}
