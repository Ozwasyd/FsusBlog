import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { formatPropertyReadTypeScript } from './format-generated-property-value-read-typescript.mjs';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const schemaPath = 'src/shared/Contracts/Validation/writing-aid-preference-wire.json';
const read = name => readFileSync(path.join(root, name), 'utf8');
const sha = value => createHash('sha256').update(value).digest('hex');
const schema = JSON.parse(read(schemaPath));
const inputs = [schemaPath, ...schema.owners.map(owner => owner.path)];
for (const owner of schema.owners) {
    if (!existsSync(path.join(root, owner.path))) throw new Error(`writing_aid_preference_owner_missing: ${owner.path}`);
    if (sha(read(owner.path)) !== owner.sha256) throw new Error(`writing_aid_preference_owner_drift: ${owner.path}`);
}
if (schema.schemaVersion !== 1 || schema.receiptMaximumPayloadBytes !== 1434 || schema.snapshotMaximumPayloadBytes !== 612 || schema.updatePayloadBytes !== 80) throw new Error('writing_aid_preference_layout_drift');
const expectedFrames = { WritingAidPreferenceSnapshotResponse: 272, WritingAidPreferenceUpdateRequest: 273, WritingAidPreferenceReceiptResponse: 274 };
if (JSON.stringify(schema.frames) !== JSON.stringify(expectedFrames)) throw new Error('writing_aid_preference_reserved_frame_drift');
const protocolPath = 'src/shared/Contracts/Validation/aeds-protocol.json';
const protocol = JSON.parse(read(protocolPath));
for (const [name, value] of Object.entries(schema.frames)) {
    const frame = protocol.frameTypes.find(frame => frame.name === name);
    if (!frame || frame.value !== value || frame.goldenFamily !== 'writing-aid-preference') throw new Error(`writing_aid_preference_protocol_owner_drift: ${name}`);
}
inputs.push(protocolPath);
const ownerIdentity = sha(schema.owners.map(owner => read(owner.path)).join('\n'));
const notice = `// <auto-generated by tools/contracts/generate-writing-aid-preference-wire.mjs>\n// Sole typed domain/POD/codec owners SHA256 ${ownerIdentity}; private family payload v1.\n`;
const template = name => `tools/contracts/writing-aid-preference-wire-templates/${name}`;
let ts = read(template('wire.ts.inc'));
const constants = ts.match(/const shaConstants = \[([^\]]+)\];/)[1];
const outputs = [
    ['src/core/Cache/PodBinaryCodec.WritingAidPreferenceReceipt.Generated.cs', notice + read(template('receipt.cs.inc'))],
    ['src/frontend/src/codecs/binary/writingAidPreferenceWire.generated.ts', notice + ts],
    ['src/frontend/wasm/aeds/include/writing_aid_preference_wire.generated.hpp', notice + read(template('wire.hpp.inc')).replace('__SHA_CONSTANTS__',constants)]
];
inputs.push(template('receipt.cs.inc'),template('wire.ts.inc'),template('wire.hpp.inc'),'tools/contracts/generate-writing-aid-preference-wire.mjs','tools/contracts/format-generated-property-value-read-typescript.mjs');
const check = process.argv.includes('--check');
for (let [name, content] of outputs) {
    // The formatter requires this generated module to be present in the actual project.
    if (name.endsWith('.ts')) {
        if (!existsSync(path.join(root,name))) {
            if (check) throw new Error(`writing_aid_preference_generated_missing: ${name}`);
            writeFileSync(path.join(root,name),content);
        }
        content = await formatPropertyReadTypeScript(content,root,name);
    }
    if (check) {
        if (!existsSync(path.join(root,name)) || read(name) !== content) throw new Error(`writing_aid_preference_generated_drift: ${name}`);
    } else writeFileSync(path.join(root,name),content);
}
console.log(JSON.stringify({mode:check?'check':'generate',ownerIdentity,sourceOwnerCommit:schema.sourceOwnerCommit,inputs:inputs.map(name=>({path:name,sha256:sha(read(name))})),outputs:outputs.map(([name])=>({path:name,sha256:sha(read(name))}))}));
