#!/usr/bin/env node
// Derive the set of index/constraint names that the migration catalog may add
// on top of the CodeFirst entity projection (FKs, indexes, check constraints).
// CurrentSchemaStartupVerifier compares the live schema against the entity
// projection only; the migration-created links were never part of that
// projection, so the verifier would otherwise fail closed on every database
// that has run a migration. The Server still never references the migration
// assembly: this generated register is compiled into the Server project.

import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const definitionsDir = join(root, 'src/migration/Definitions');
const outPath = join(
    root,
    'src/backend/Infrastructure/SchemaMigration/SchemaAllowedExtraLinkNames.generated.cs'
);

const files = readdirSync(definitionsDir).filter((file) => file.endsWith('.cs'));
const names = new Set();
for (const file of files)
{
    const content = readFileSync(join(definitionsDir, file), 'utf8');
    // Step declarations carry the link name in a string literal.
    for (const match of content.matchAll(/(?:EnsureIndexStep|CreateIndexStep|DropIndexStep)\(\s*"([a-z0-9_]+)"/g))
    {
        names.add(match[1]);
    }
    // SQL templates declare constraints inline.
    for (const match of content.matchAll(/\bCONSTRAINT\s+"?((?:fk|ck|ux|idx)_[a-z0-9_]+)"?/g))
    {
        names.add(match[1]);
    }
    for (const match of content.matchAll(/CREATE\s+(?:UNIQUE\s+)?INDEX\s+(?:CONCURRENTLY\s+)?(?:IF NOT EXISTS\s+)?(?:[a-z0-9_]+\s*\.\s*)?"?((?:idx|ux)_[a-z0-9_]+)"?/g))
    {
        names.add(match[1]);
    }
}

const digest = createHash('sha256').update([...names].sort().join('\n')).digest('hex');
const generatedAt = new Date().toISOString();

const code = `// <auto-generated />
// Generated by tools/db/generate-schema-allowed-extra-links.mjs from
// src/migration/Definitions/*.cs. Do not edit by hand.
// Source digest: sha256:${digest}
// Generated at: ${generatedAt}

namespace FsusBlog.Server.Infrastructure.SchemaMigration;

internal static class SchemaAllowedExtraLinkNames
{
    public static IReadOnlySet<string> Names { get; } = new HashSet<string>(StringComparer.Ordinal)
    {
${[...names].sort().map((name) => `        "${name}",`).join('\n')}
    };
}
`;

writeFileSync(outPath, code);
console.log(
    `[generate-schema-allowed-extra-links] wrote ${names.size} link names digest sha256:${digest} (source ${files.length} definition files)`
);
