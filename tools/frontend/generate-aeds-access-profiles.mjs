#!/usr/bin/env node
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const sourcePath = path.join(root, 'src/shared/Contracts/Validation/aeds-access-profiles.json');
const source = JSON.parse(await readFile(sourcePath, 'utf8'));

if (source.schemaVersion !== 1 || source.wireProtocolVersion !== 2 || source.frameHeaderBytes !== 16)
{
    throw new Error('aeds_access_profile_schema_invalid');
}

const ids = new Set();
for (const profile of source.profiles)
{
    if (!profile.id || ids.has(profile.id) || !Array.isArray(profile.supportedRecordBytes))
    {
        throw new Error('aeds_access_profile_invalid');
    }
    ids.add(profile.id);
}

const generatedNotice = 'Generated from src/shared/Contracts/Validation/aeds-access-profiles.json. Do not edit.';
const pascal = (value) => value[0].toUpperCase() + value.slice(1);
const csharpProfiles = source.profiles.map((profile, index) => `    ${pascal(profile.id)} = ${index + 1},`).join('\n');
const tsProfiles = source.profiles.map((profile) => `  ${profile.id}: '${profile.id}',`).join('\n');
const cppProfiles = source.profiles.map((profile, index) => `    ${pascal(profile.id)} = ${index + 1},`).join('\n');
const offsets = source.articleList.offsets;

const csharp = `// <auto-generated />
// ${generatedNotice}

namespace FsusBlog.Core.Cache;

public enum AedsAccessProfileId
{
    Unknown = 0,
${csharpProfiles}
}

internal static class AedsArticleListAccessProfile
{
    internal const int CursorMagic = ${source.articleList.cursorMagic};
    internal const int TagRecordBytes = ${source.articleList.tagRecordBytes};
    internal static ReadOnlySpan<int> SupportedPublicCardRecordBytes => [${source.profiles[0].supportedRecordBytes.join(', ')}];
    internal static ReadOnlySpan<int> FallbackPublicCardRecordBytes => [${source.profiles[0].fallbackRecordBytes.join(', ')}];
${Object.entries(offsets).map(([name, value]) => `    internal const int ${pascal(name)}Offset = ${value};`).join('\n')}
}
`;

const typescript = `// ${generatedNotice}
export const AEDS_ACCESS_PROFILE = Object.freeze({
${tsProfiles}
} as const)

export type AedsAccessProfileId = typeof AEDS_ACCESS_PROFILE[keyof typeof AEDS_ACCESS_PROFILE]

export const ARTICLE_LIST_ACCESS = Object.freeze({
  cursorMagic: ${source.articleList.cursorMagic},
  cursorVersions: [${source.articleList.cursorVersions.join(', ')}] as const,
  tagRecordBytes: ${source.articleList.tagRecordBytes},
  supportedPublicCardRecordBytes: [${source.profiles[0].supportedRecordBytes.join(', ')}] as const,
  fallbackPublicCardRecordBytes: [${source.profiles[0].fallbackRecordBytes.join(', ')}] as const,
  offsets: Object.freeze(${JSON.stringify(offsets, null, 2)})
})
`;

const cpp = `// ${generatedNotice}
#pragma once
#include <cstddef>
#include <cstdint>

namespace FsusBlog::AedsAccess
{
enum class ProfileId : std::uint8_t
{
    Unknown = 0,
${cppProfiles}
};

inline constexpr std::int32_t ArticleListCursorMagic = ${source.articleList.cursorMagic};
inline constexpr std::size_t ArticleListTagRecordBytes = ${source.articleList.tagRecordBytes}u;
inline constexpr std::size_t PublicCardCurrentRecordBytes = ${source.profiles[0].supportedRecordBytes.at(-1)}u;
inline constexpr std::size_t PublicCardLegacyRecordBytes = ${source.profiles[0].supportedRecordBytes[0]}u;
inline constexpr std::size_t PublicCardFallbackRecordBytes = ${source.profiles[0].fallbackRecordBytes[0]}u;
${Object.entries(offsets).map(([name, value]) => `inline constexpr std::size_t ${pascal(name)}Offset = ${value}u;`).join('\n')}
}
`;

const outputs = [
    [path.join(root, 'src/core/Cache/AedsAccessProfiles.Generated.cs'), csharp],
    [path.join(root, 'src/frontend/src/generated/aedsAccessProfiles.ts'), typescript],
    [path.join(root, 'src/frontend/wasm/aeds/include/aeds_access_profiles.generated.hpp'), cpp]
];

if (process.argv.includes('--check'))
{
    for (const [outputPath, expected] of outputs)
    {
        const actual = await readFile(outputPath, 'utf8').catch(() => '');
        if (actual !== expected)
        {
            throw new Error(`aeds_access_profile_generated_drift:${path.relative(root, outputPath)}`);
        }
    }
}
else
{
    await Promise.all(outputs.map(([outputPath, contents]) => writeFile(outputPath, contents)));
}
