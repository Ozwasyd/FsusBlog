#!/usr/bin/env node
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export function renderAedsAccessProfileOutputs(source)
{
    if (Object.keys(source).sort().join(',') !== 'frameHeaderBytes,profiles,schemaVersion,wireProtocolVersion')
    {
        throw new Error('aeds_access_profile_schema_invalid');
    }
    if (source.schemaVersion !== 1 || source.wireProtocolVersion !== 2 || source.frameHeaderBytes !== 16)
    {
        throw new Error('aeds_access_profile_schema_invalid');
    }

    const ids = new Set();
    for (const profile of source.profiles)
    {
        if (!profile.id || ids.has(profile.id) || profile.wireLayout !== profile.frame
        || Object.keys(profile).sort().join(',') !== 'defaultEnabled,deferredFields,frame,id,ignoredFields,optionalFields,outputContract,requiredFields,semanticValidations,wireLayout')
        {
            throw new Error('aeds_access_profile_invalid');
        }
        ids.add(profile.id);
    }

    const generatedNotice = 'Generated from src/shared/Contracts/Validation/aeds-access-profiles.json. Do not edit.';
    const pascal = (value) => value[0].toUpperCase() + value.slice(1);
    const csharpProfiles = source.profiles.map((profile, index) => `    ${pascal(profile.id)} = ${index + 1},`).join('\n');
    const tsProfiles = source.profiles.map((profile) => `  ${profile.id}: '${profile.id}',`).join('\n');
    const cppProfiles = source.profiles.map((profile, index) => `    ${pascal(profile.id)} = ${index + 1},`).join('\n');


    const csharp = `// <auto-generated />
// ${generatedNotice}

namespace FsusBlog.Core.Cache;

public enum AedsAccessProfileId
{
    Unknown = 0,
${csharpProfiles}
}
`;

    const typescript = `// ${generatedNotice}
export const AEDS_ACCESS_PROFILE = Object.freeze({
${tsProfiles}
} as const)

export type AedsAccessProfileId = typeof AEDS_ACCESS_PROFILE[keyof typeof AEDS_ACCESS_PROFILE]
`;

    const cpp = `// ${generatedNotice}
#pragma once
#include <cstddef>
#include <cstdint>

namespace FsusBlog::AedsAccess
{
enum class ProfileId : std::uint8_t
{
    Unknown = 0,
${cppProfiles}
};

}
`;

    return [
        ['src/core/Cache/AedsAccessProfiles.Generated.cs', csharp],
        ['src/frontend/src/generated/aedsAccessProfiles.ts', typescript],
        ['src/frontend/wasm/aeds/include/aeds_access_profiles.generated.hpp', cpp]
    ];
}

async function main()
{
    const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
    const source = JSON.parse(await readFile(path.join(root, 'src/shared/Contracts/Validation/aeds-access-profiles.json'), 'utf8'));
    for (const [relativePath, expected] of renderAedsAccessProfileOutputs(source))
    {
        const outputPath = path.join(root, relativePath);
        if (process.argv.includes('--check'))
        {
            const actual = await readFile(outputPath, 'utf8').catch(() => '');
            if (actual !== expected)
            {
                throw new Error(`aeds_access_profile_generated_drift:${relativePath}`);
            }
        }
        else
        {
            await writeFile(outputPath, expected);
        }
    }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url))
{
    await main();
}
