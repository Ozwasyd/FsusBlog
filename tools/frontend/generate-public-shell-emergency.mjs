#!/usr/bin/env node

import { mkdir, readFile, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = fileURLToPath(new URL('../..', import.meta.url));
const frontendRoot = path.join(repoRoot, 'src', 'frontend');
const sourceRelativePath = 'src/assets/public-shell-foundation.css';
const publicOutputRelativePath = 'public/public-shell-emergency.css';
const serverOutputRelativePath = 'dist/server/public-shell-emergency.css';
const sourcePath = path.join(frontendRoot, sourceRelativePath);
const publicOutputPath = path.join(frontendRoot, publicOutputRelativePath);
const serverOutputPath = process.env.FSUSBLOG_FRONTEND_DIST_ROOT
    ? path.join(path.resolve(process.env.FSUSBLOG_FRONTEND_DIST_ROOT), 'server/public-shell-emergency.css')
    : path.join(frontendRoot, serverOutputRelativePath);
const banner = [
    '/* Generated by tools/frontend/generate-public-shell-emergency.mjs. */',
    '/* Source: src/assets/public-shell-foundation.css emergency:keep blocks. Do not edit this file directly. */',
    ''
].join('\n');

async function pathExists(file)
{
    try
    {
        await stat(file);
        return true;
    }
    catch
    {
        return false;
    }
}

function extractEmergencyCss(source)
{
    const blocks = [];
    const markerPattern = /\/\*\s*emergency:keep-(start|end)[\s\S]*?\*\//g;
    let activeStart = null;
    let match;

    while ((match = markerPattern.exec(source)) !== null)
    {
        const marker = match[1];
        if (marker === 'start')
        {
            if (activeStart !== null)
            {
                throw new Error('nested emergency:keep-start marker is not allowed');
            }
            activeStart = markerPattern.lastIndex;
            continue;
        }

        if (activeStart === null)
        {
            throw new Error('emergency:keep-end marker without matching start');
        }

        const block = source.slice(activeStart, match.index).trim();
        if (block.length > 0)
        {
            blocks.push(block);
        }
        activeStart = null;
    }

    if (activeStart !== null)
    {
        throw new Error('emergency:keep-start marker without matching end');
    }

    if (blocks.length === 0)
    {
        throw new Error('missing emergency:keep blocks in src/assets/public-page.css');
    }

    return `${banner}${blocks.join('\n\n')}\n`;
}

async function readText(file)
{
    return readFile(file, 'utf8');
}

async function writeOutput(file, contents)
{
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, contents, 'utf8');
}

async function checkOutput(file, expected)
{
    if (!(await pathExists(file)))
    {
        throw new Error(`missing generated output: ${path.relative(repoRoot, file)}`);
    }

    const actual = await readText(file);
    if (actual !== expected)
    {
        throw new Error(`stale generated output: ${path.relative(repoRoot, file)}`);
    }
}

async function main()
{
    const source = await readText(sourcePath);
    const output = extractEmergencyCss(source);
    const checkOnly = process.argv.includes('--check');
    const publicOnly = process.argv.includes('--public-only');

    if (checkOnly)
    {
        await checkOutput(publicOutputPath, output);
        if (!publicOnly && await pathExists(serverOutputPath))
        {
            await checkOutput(serverOutputPath, output);
        }
        console.log('[generate-public-shell-emergency] ok');
        return;
    }

    await writeOutput(publicOutputPath, output);
    if (!publicOnly)
    {
        await writeOutput(serverOutputPath, output);
    }
    console.log(`[generate-public-shell-emergency] wrote ${path.relative(repoRoot, publicOutputPath)}`);
    if (!publicOnly)
    {
        console.log(`[generate-public-shell-emergency] wrote ${path.relative(repoRoot, serverOutputPath)}`);
    }
}

main().catch((error) =>
{
    console.error('[generate-public-shell-emergency] fatal:', error instanceof Error ? error.message : String(error));
    process.exit(1);
});
