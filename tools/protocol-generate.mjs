import { readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const notice = '// Generated by tools/protocol-generate.mjs from wire.schema.json.';
const entries = Object.entries;
const camel = name => name[0].toLowerCase() + name.slice(1);
const literal = (value, strings) => strings ? JSON.stringify(value) : value;
const primitive = {
  i32: ['int', 'I32', 4],
  i32s: ['IReadOnlyList<int>', 'I32s', 4],
  i64: ['long', 'I64', 8],
  bool: ['bool', 'Bool', 1],
  uuid: ['Guid', 'Uuid', 16],
  text: ['string', 'Text', 4],
};
const enumWidths = {
  u8: { csType: 'byte', csWrite: 'Byte', csRead: 'Byte', tsField: 'enumU8', minBytes: 1, min: 0, max: 0xff },
};
// Groups are flat, ordered field tuples, not record inheritance: frames and
// validation remain record-owned. Reject invalid groups even when unused.
const identifier = value => typeof value === 'string' && /^[A-Z][A-Za-z0-9]*$/.test(value);
const object = value => value !== null && typeof value === 'object' && !Array.isArray(value);

export function compileSchema(schema) {
  const { header, frameTypes, routes, headers, limits, layouts, enums = {}, embeddedRecords = {}, records, fieldGroups } = schema;
  const surface = [
    ['WireHeader', header],
    ['WireLimits', limits],
    ['WireLayouts', layouts],
    ['WireRoutes', routes, true],
    ['WireHeaders', headers, true],
  ];

  if (!object(enums)) throw new Error('Invalid enums');
  if (!object(embeddedRecords)) throw new Error('Invalid embeddedRecords');
  if (!object(fieldGroups)) throw new Error('Invalid fieldGroups');
  if (!object(records)) throw new Error('Invalid records');

  const typeNames = new Set();
  for (const [name, definition] of entries(enums)) {
    if (!identifier(name)) throw new Error(`Invalid enum name: ${name}`);
    if (typeNames.has(name)) throw new Error(`Duplicate type name: ${name}`);
    typeNames.add(name);
    if (!object(definition) || Object.keys(definition).length !== 2 ||
        typeof definition.type !== 'string' || !Object.hasOwn(enumWidths, definition.type) ||
        !object(definition.values) || entries(definition.values).length === 0)
      throw new Error(`Invalid enum definition: ${name}`);
    const width = enumWidths[definition.type];
    const seenValues = new Set();
    for (const [member, value] of entries(definition.values)) {
      if (!identifier(member) || !Number.isInteger(value) || value < width.min || value > width.max || seenValues.has(value))
        throw new Error(`Invalid enum member: ${name}.${member}`);
      seenValues.add(value);
    }
  }

  for (const [name, record] of entries(embeddedRecords)) {
    if (!identifier(name)) throw new Error(`Invalid embedded record name: ${name}`);
    if (typeNames.has(name)) throw new Error(`Duplicate type name: ${name}`);
    typeNames.add(name);
    if (!object(record) || Object.keys(record).length !== 1 || !Object.hasOwn(record, 'fields'))
      throw new Error(`Invalid embedded record definition: ${name}`);
  }

  function validateFields(fields, owner) {
    if (!Array.isArray(fields) || fields.length === 0)
      throw new Error(`Invalid fields: ${owner}`);
    const names = new Set();
    for (const field of fields) {
      if (!Array.isArray(field) || !identifier(field[0]) || typeof field[1] !== 'string')
        throw new Error(`Invalid field: ${owner}`);
      const [name, type, arg1, arg2] = field;
      if (Object.hasOwn(primitive, type)) {
        const bounded = type === 'text' || type === 'i32s';
        if (field.length !== (bounded ? 3 : 2) ||
            (bounded && (!identifier(arg1) || !Object.hasOwn(limits, arg1))))
          throw new Error(`Invalid field type or bound: ${owner}.${name}`);
      } else if (type === 'enum') {
        if (field.length !== 3 || !identifier(arg1) || !Object.hasOwn(enums, arg1))
          throw new Error(`Invalid enum field: ${owner}.${name}`);
      } else if (type === 'record') {
        if (field.length !== 3 || !identifier(arg1) || !Object.hasOwn(embeddedRecords, arg1))
          throw new Error(`Invalid embedded record field: ${owner}.${name}`);
      } else if (type === 'list') {
        if (field.length !== 4 || !identifier(arg1) || !Object.hasOwn(embeddedRecords, arg1) ||
            !identifier(arg2) || !Object.hasOwn(limits, arg2))
          throw new Error(`Invalid list field: ${owner}.${name}`);
      } else {
        throw new Error(`Invalid field: ${owner}`);
      }
      if (names.has(camel(name))) throw new Error(`Duplicate field: ${owner}.${name}`);
      names.add(camel(name));
    }
    return fields;
  }

  function expandFields(rawFields, owner) {
    if (!Array.isArray(rawFields)) throw new Error(`Invalid fields: ${owner}`);
    const fields = rawFields.flatMap(field => {
      if (Array.isArray(field)) return [field];
      if (!object(field) || Object.keys(field).length !== 1 || !identifier(field.group) ||
          !Object.hasOwn(fieldGroups, field.group))
        throw new Error(`Invalid field group reference: ${owner}`);
      return fieldGroups[field.group];
    });
    return validateFields(fields, owner);
  }

  for (const [name, fields] of entries(fieldGroups)) {
    if (!identifier(name)) throw new Error(`Invalid field group name: ${name}`);
    validateFields(fields, `fieldGroups.${name}`);
  }

  const embeddedMap = new Map(entries(embeddedRecords).map(([name, record]) =>
    [name, expandFields(record.fields, `embeddedRecords.${name}`)]));
  const embeddedOrder = [];
  const embeddedMinBytes = new Map();
  const visitState = new Map();
  function visitEmbedded(name) {
    const state = visitState.get(name);
    if (state === 1) throw new Error(`Cyclic embedded record: ${name}`);
    if (state === 2) return embeddedMinBytes.get(name);
    visitState.set(name, 1);
    let minBytes = 0;
    for (const [, type, arg1] of embeddedMap.get(name)) {
      if (Object.hasOwn(primitive, type)) minBytes += primitive[type][2];
      else if (type === 'enum') minBytes += enumWidths[enums[arg1].type].minBytes;
      else if (type === 'record') minBytes += visitEmbedded(arg1);
      else if (type === 'list') {
        visitEmbedded(arg1);
        minBytes += 4;
      }
    }
    visitState.set(name, 2);
    embeddedMinBytes.set(name, minBytes);
    embeddedOrder.push([name, embeddedMap.get(name)]);
    return minBytes;
  }
  for (const name of embeddedMap.keys()) visitEmbedded(name);

  const methods = entries(records).map(([name, record]) => {
    if (!identifier(name)) throw new Error(`Invalid record name: ${name}`);
    if (typeNames.has(name)) throw new Error(`Duplicate type name: ${name}`);
    typeNames.add(name);
    if (!object(record)) throw new Error(`Invalid record: ${name}`);
    const frame = record.frame ?? name;
    if (typeof frame !== 'string' || !Object.hasOwn(frameTypes, frame))
      throw new Error(`Invalid frame reference: ${name}.${frame}`);
    return [name, { ...record, frame, fields: expandFields(record.fields, name) }];
  });

  function csFieldType(field) {
    const [, type, arg1] = field;
    if (Object.hasOwn(primitive, type)) return primitive[type][0];
    if (type === 'enum' || type === 'record') return arg1;
    if (type === 'list') return `IReadOnlyList<${arg1}>`;
    throw new Error(`Unsupported field type: ${type}`);
  }

  function csWrite(target, field) {
    const [name, type, arg1, arg2] = field;
    if (Object.hasOwn(primitive, type))
      return `writer.${primitive[type][1]}(${target}.${name}${arg1 ? `, WireLimits.${arg1}` : ''});`;
    if (type === 'enum' || type === 'record')
      return `Write${arg1}(writer, ${target}.${name});`;
    if (type === 'list')
      return `writer.List(${target}.${name}, WireLimits.${arg2}, Write${arg1});`;
    throw new Error(`Unsupported field type: ${type}`);
  }

  function csRead(field) {
    const [, type, arg1, arg2] = field;
    if (Object.hasOwn(primitive, type))
      return `reader.${primitive[type][1]}(${arg1 ? `WireLimits.${arg1}` : ''})`;
    if (type === 'enum' || type === 'record')
      return `Read${arg1}(ref reader)`;
    if (type === 'list')
      return `reader.List(WireLimits.${arg2}, ${embeddedMinBytes.get(arg1)}, Read${arg1})`;
    throw new Error(`Unsupported field type: ${type}`);
  }

  function tsFieldExpr(field) {
    const [, type, arg1, arg2] = field;
    if (Object.hasOwn(primitive, type))
      return `podField.${type}${arg1 ? `(WireLimits.${arg1})` : ''}`;
    if (type === 'enum')
      return `/* @__PURE__ */ podField.${enumWidths[enums[arg1].type].tsField}(${arg1})`;
    if (type === 'record')
      return `${camel(arg1)}Field`;
    if (type === 'list')
      return `/* @__PURE__ */ podField.list(${camel(arg1)}Field, WireLimits.${arg2}, ${embeddedMinBytes.get(arg1)})`;
    throw new Error(`Unsupported field type: ${type}`);
  }

  const cs = [notice, 'namespace FsusBlog.V2.Contracts;', '',
    'public enum FrameType : ushort', '{',
    ...entries(frameTypes).map(([n, v]) => `    ${n} = ${v},`), '}', '',
    ...entries(enums).flatMap(([name, { type, values }]) => [
      `public enum ${name} : ${enumWidths[type].csType}`, '{',
      ...entries(values).map(([member, value]) => `    ${member} = ${value},`), '}', '',
    ]),
    ...surface.flatMap(([kind, values, strings]) => [
      `public static class ${kind}`, '{',
      ...entries(values).map(([n, v]) => `    public const ${strings ? 'string' : 'int'} ${n} = ${literal(v, strings)};`),
      '}', '',
    ]),
    ...embeddedOrder.map(([name, fields]) =>
      `public sealed record ${name}(${fields.map(field => `${csFieldType(field)} ${field[0]}`).join(', ')});`),
    ...methods.map(([name, { fields }]) =>
      `public sealed record ${name}(${fields.map(field => `${csFieldType(field)} ${field[0]}`).join(', ')});`),
    '', 'public static partial class Wire', '{',
    ...entries(enums).flatMap(([name, { type, values }]) => {
      const { csType, csWrite: writeMethod, csRead: readMethod } = enumWidths[type];
      const pattern = Object.keys(values).map(member => `${name}.${member}`).join(' or ');
      return [
        `    private static void Write${name}(Writer writer, ${name} value) => writer.${writeMethod}(value switch`,
        '    {',
        `        ${pattern} => (${csType})value,`,
        '        _ => throw new ProtocolException("Invalid AEDS enum value"),',
        '    });', '',
        `    private static ${name} Read${name}(ref Reader reader) => (${name})reader.${readMethod}() switch`,
        '    {',
        `        var value and (${pattern}) => value,`,
        '        _ => throw new ProtocolException("Invalid AEDS enum value"),',
        '    };', '',
      ];
    }),
    ...embeddedOrder.flatMap(([name, fields]) => [
      `    private static void Write${name}(Writer writer, ${name} record)`,
      '    {',
      ...fields.map(field => `        ${csWrite('record', field)}`),
      '    }', '',
      `    private static ${name} Read${name}(ref Reader reader) =>`,
      `        new ${name}(${fields.map(csRead).join(', ')});`, '',
    ]),
    ...methods.flatMap(([name, { fields, frame }]) => [
      `    public static byte[] Encode${name}(${name} value) =>`,
      `        EncodeRecord(FrameType.${frame}, value, Validate, static (writer, record) =>`,
      '        {',
      ...fields.map(field => `            ${csWrite('record', field)}`),
      '        });', '',
      `    public static ${name} Decode${name}(ReadOnlySpan<byte> frame) =>`,
      `        DecodeRecord<${name}>(FrameType.${frame}, frame, static (ref Reader reader) =>`,
      `            new ${name}(${fields.map(csRead).join(', ')}), Validate);`,
      '',
    ]),
    '}', '',
  ].join('\n');

  const emittedGroups = new Set();
  const tsMember = field => `  ${camel(field[0])}: ${tsFieldExpr(field)},`;
  const groupName = field => `_group${field.group}`;
  function tsRecord(name, fields, embedded) {
    const declarations = [];
    const members = fields.map(field => {
      if (Array.isArray(field)) return tsMember(field);
      const group = groupName(field);
      if (!emittedGroups.has(group)) {
        declarations.push(`const ${group} = {`, ...fieldGroups[field.group].map(tsMember), '};');
        emittedGroups.add(group);
      }
      return `  ...${group},`;
    });
    let layout = `${camel(name)}Fields`;
    if (fields.length === 1 && !Array.isArray(fields[0])) layout = groupName(fields[0]);
    else declarations.push(`const ${layout} = {`, ...members, '};');
    return [...declarations, `export interface ${name} extends PodValue<typeof ${layout}> {}`,
      embedded ? `const ${camel(name)}Field = /* @__PURE__ */ podField.record<${name}>(${layout});` :
        `export const [encode${name}, decode${name}] = /* @__PURE__ */ definePodRecord<${name}>(${layout});`, ''];
  }

  const ts = [notice,
    `import { definePodRecord, podField, type PodValue } from './pod-record.ts';`, '',
    ...[['FrameType', frameTypes], ...surface].flatMap(([name, values, strings]) => [
      `export const ${name} = {`,
      ...entries(values).map(([n, v]) => `  ${n}: ${literal(v, strings)},`),
      '} as const;', '',
    ]),
    'export type FrameType = typeof FrameType[keyof typeof FrameType];', '',
    ...entries(enums).flatMap(([name, { values }]) => [
      `export const ${name} = {`,
      ...entries(values).map(([member, value]) => `  ${member}: ${value},`),
      '} as const;', '',
      `export type ${name} = typeof ${name}[keyof typeof ${name}];`, '',
    ]),
    ...embeddedOrder.flatMap(([name]) => tsRecord(name, embeddedRecords[name].fields, true)),
    ...methods.flatMap(([name]) => tsRecord(name, records[name].fields, false)),
  ].join('\n');

  const frameRanges = [];
  for (const id of Object.values(frameTypes).sort((left, right) => left - right)) {
    const previous = frameRanges.at(-1);
    if (!Number.isInteger(id) || id < 0 || id > 0xffff || previous?.[1] === id)
      throw new Error(`Invalid or duplicate uint16 frame ID: ${id}`);
    if (previous && id === previous[1] + 1) previous[1] = id;
    else frameRanges.push([id, id]);
  }

  const cpp = [notice, '#pragma once', '#include <stddef.h>', '#include <stdint.h>', '',
    'namespace fsus::wire {',
    ...[['header', header], ['limits', limits], ['layouts', layouts]].flatMap(([kind, values]) => [
      `namespace ${kind} {`,
      ...entries(values).map(([n, v]) => `inline constexpr uint32_t ${n} = ${v};`),
      '}', '',
    ]),
    'enum class FrameType : uint16_t {',
    ...entries(frameTypes).map(([n, v]) => `    ${n} = ${v},`), '};', '',
    'namespace detail {',
    'struct FrameRange { uint16_t first, last; };',
    'inline constexpr FrameRange frameRanges[] = {',
    ...frameRanges.map(([first, last]) => `    {${first}, ${last}},`),
    '};',
    '}', '',
    'constexpr bool known(FrameType type) {',
    '    const auto id = static_cast<uint16_t>(type);',
    '    size_t low = 0, high = sizeof(detail::frameRanges) / sizeof(detail::FrameRange);',
    '    while (low < high) {',
    '        const size_t middle = low + (high - low) / 2;',
    '        const auto &range = detail::frameRanges[middle];',
    '        if (id < range.first) high = middle;',
    '        else if (id > range.last) low = middle + 1;',
    '        else return true;',
    '    }',
    '    return false;',
    '}', '',
    '#pragma pack(push, 1)',
    'struct FrameHeader {',
    '    uint32_t magic;',
    '    uint8_t version;',
    '    uint8_t size;',
    '    uint16_t flags;',
    '    FrameType type;',
    '    uint32_t payloadLength;',
    '    uint16_t payloadCrc;',
    '};',
    '#pragma pack(pop)',
    'static_assert(sizeof(FrameHeader) == header::HeaderSize);',
    ...[['version', 'VersionOffset'], ['size', 'LengthOffset'], ['flags', 'FlagsOffset'], ['type', 'TypeOffset'], ['payloadLength', 'PayloadLengthOffset'], ['payloadCrc', 'CrcOffset']]
      .map(([field, constant]) => `static_assert(offsetof(FrameHeader, ${field}) == header::${constant});`),
    '}', '',
  ].join('\n');

  return {
    'src/Contracts/Wire.Generated.cs': cs,
    'src/Contracts/wire.generated.ts': ts,
    'src/ProtocolWasm/wire.generated.hpp': cpp,
  };
}

if (process.argv[1] && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))) {
  const repo = fileURLToPath(new URL('..', import.meta.url));
  const schema = JSON.parse(readFileSync(`${repo}/src/Contracts/wire.schema.json`, 'utf8'));
  const outputs = compileSchema(schema);
  for (const [path, expected] of entries(outputs)) {
    const file = `${repo}/${path}`;
    if (process.argv.includes('--check')) {
      if (readFileSync(file, 'utf8') !== expected) {
        console.error(`${path} is out of date`);
        process.exitCode = 1;
      }
    } else {
      writeFileSync(file, expected);
    }
  }
}
