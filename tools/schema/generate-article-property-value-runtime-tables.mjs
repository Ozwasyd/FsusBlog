import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const input = 'src/migration/Definitions/ArticlePropertyValueMigrationDefinitions.cs';
const output = 'src/backend/Infrastructure/SchemaMigration/ArticlePropertyValueRuntimeTables.Generated.cs';
export function generateRuntimeTables(source)
{
    const offers = [...source.matchAll(/new RawSqlStep\("""([\s\S]+?)"""\)/gu)];
    if (offers.length !== 1) throw new Error('article_property_value_migration_sql_missing');
    const lines = offers[0][1].replace(/^\s*\n/u, '').trimEnd().split('\n');
    const indentation = Math.min(...lines.filter(line => line.trim()).map(line => line.match(/^ */u)[0].length));
    const sql = lines.map(line => line.slice(indentation)).join('\n');
    const statements = [];
    let pending = [];
    for (const line of sql.split('\n'))
    {
        pending.push(line);
        if (line.trimEnd().endsWith(';'))
        {
            statements.push(pending.join('\n').replace(/^\n+|\n+$/gu, ''));
            pending = [];
        }
    }
    if (pending.some(line => line.trim())) throw new Error('article_property_value_unterminated_sql');
    const tables = [];
    for (const statement of statements)
    {
        const name = statement.match(/^CREATE TABLE IF NOT EXISTS (\w+)\s*\(/u)?.[1];
        if (name)
        {
            tables.push({ name, sql: statement, additionalSql: [] });
            continue;
        }
        const indexTarget = statement.match(/^CREATE (?:UNIQUE )?INDEX IF NOT EXISTS \w+\s+ON (\w+)\(/u)?.[1];
        const table = tables.find(candidate => candidate.name === indexTarget);
        if (!table) throw new Error('article_property_value_unowned_sql_statement');
        table.additionalSql.push(statement);
    }
    const names = tables.map(table => table.name);
    if (names.length !== 7 || new Set(names).size !== 7 || names.some(name => !name.startsWith('article_property_value_')))
        throw new Error('article_property_value_runtime_table_set_invalid');
    const rawLiteral = (statement, indent) => `${indent}"""\n${statement.split('\n').map(line => `${indent}${line}`).join('\n')}\n${indent}"""`;
    const entries = tables.map(table =>
    {
        let entry = `        new("${table.name}",\n${rawLiteral(table.sql, '            ')}`;
        if (table.additionalSql.length)
            entry += `,\n            AdditionalSql:\n            [\n${table.additionalSql.map(statement => rawLiteral(statement, '                ')).join(',\n')}\n            ]`;
        return `${entry})`;
    }).join(',\n');
    const code = `// <auto-generated by tools/schema/generate-article-property-value-runtime-tables.mjs>\n// Source: ${input}\nnamespace FsusBlog.Server.Infrastructure.SchemaMigration;\n\ninternal static class ArticlePropertyValueRuntimeTables\n{\n    internal static IReadOnlyList<CurrentSchemaRuntimeRollupTable> Tables { get; } =\n    [\n${entries}\n    ];\n}\n`;
    return { code, tables, statements };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url))
{
    const generated = generateRuntimeTables(readFileSync(path.join(root, input), 'utf8'));
    if (process.argv.includes('--check'))
    {
        if (readFileSync(path.join(root, output), 'utf8') !== generated.code)
            throw new Error('article_property_value_runtime_tables_drift');
    }
    else writeFileSync(path.join(root, output), generated.code);
}
