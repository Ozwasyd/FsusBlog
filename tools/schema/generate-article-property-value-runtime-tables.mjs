import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const input = 'src/migration/Definitions/ArticlePropertyValueMigrationDefinitions.cs';
const output = 'src/backend/Infrastructure/SchemaMigration/ArticlePropertyValueRuntimeTables.Generated.cs';
const source = readFileSync(path.join(root, input), 'utf8');
const sql = source.match(/new RawSqlStep\("""([\s\S]+?)"""\)/u)?.[1];
if (sql === undefined) throw new Error('article_property_value_migration_sql_missing');
const sections = sql.trim().split(/(?=CREATE TABLE IF NOT EXISTS )/u).filter(Boolean);
const names = sections.map(section => section.match(/^CREATE TABLE IF NOT EXISTS (\w+)\s*\(/u)?.[1]);
if (names.length !== 7 || new Set(names).size !== 7 || names.some(name => !name?.startsWith('article_property_value_')))
    throw new Error('article_property_value_runtime_table_set_invalid');
const entries = sections.map((section, index) =>
    `        new("${names[index]}",\n            """\n${section.trim().split('\n').map(line => `            ${line.trimStart()}`).join('\n')}\n            """)`).join(',\n');
const generated = `// <auto-generated by tools/schema/generate-article-property-value-runtime-tables.mjs>\n// Source: ${input}\nnamespace FsusBlog.Server.Infrastructure.SchemaMigration;\n\ninternal static class ArticlePropertyValueRuntimeTables\n{\n    internal static IReadOnlyList<CurrentSchemaRuntimeRollupTable> Tables { get; } =\n    [\n${entries}\n    ];\n}\n`;
if (process.argv.includes('--check'))
{
    if (readFileSync(path.join(root, output), 'utf8') !== generated)
        throw new Error('article_property_value_runtime_tables_drift');
}
else writeFileSync(path.join(root, output), generated);
