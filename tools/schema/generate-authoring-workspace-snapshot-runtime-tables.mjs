import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
export const persistencePath = 'src/backend/Services/Authoring/AuthoringWorkspaceSnapshotPostgresPersistence.cs';
export const migrationPath = 'src/migration/Definitions/AuthoringWorkspaceSnapshotMigrationDefinitions.cs';
const outputPath = 'src/backend/Infrastructure/SchemaMigration/AuthoringWorkspaceSnapshotRuntimeTables.Generated.cs';

function normalize(sql)
{
    return sql.trim().split('\n').map(line => line.trim()).filter(Boolean).join('\n');
}

function dedent(sql)
{
    const lines = sql.replace(/^\s*\n/u, '').trimEnd().split('\n');
    const indentation = Math.min(...lines.filter(line => line.trim()).map(line => line.match(/^ */u)[0].length));
    return lines.map(line => line.slice(indentation)).join('\n');
}

export function generateRuntimeTables(persistenceSource, migrationSource)
{
    const offers = [...persistenceSource.matchAll(/public const string SchemaSql = """([\s\S]+?)""";/gu)];
    const migrations = [...migrationSource.matchAll(/new RawSqlStep\("""([\s\S]+?)"""\)/gu)];
    if (offers.length !== 1 || migrations.length !== 1)
        throw new Error('authoring_workspace_snapshot_sql_owner_required');
    const offer = normalize(offers[0][1]);
    const sql = normalize(migrations[0][1]);
    if (!sql.startsWith('CREATE TABLE IF NOT EXISTS authoring_workspace_snapshot (')
        || sql.replace('CREATE TABLE IF NOT EXISTS ', 'CREATE TABLE ') !== offer)
        throw new Error('authoring_workspace_snapshot_sql_offer_drift');
    if ((sql.match(/CREATE TABLE /gu) ?? []).length !== 1
        || (sql.match(/;/gu) ?? []).length !== 1
        || !sql.includes('REFERENCES admin_principal(id) ON DELETE CASCADE')
        || !sql.includes("CHECK (workspace_id = 'default')")
        || !sql.includes('CHECK (revision BETWEEN 1 AND 9007199254740991)')
        || !sql.includes('CHECK (octet_length(snapshot_bytes) BETWEEN 1 AND 65536)')
        || !sql.includes('PRIMARY KEY (user_id, site_id, workspace_id)'))
        throw new Error('authoring_workspace_snapshot_bounded_single_row_required');
    const code = `// <auto-generated by tools/schema/generate-authoring-workspace-snapshot-runtime-tables.mjs>\n// Source: ${migrationPath}; parity owner: ${persistencePath}\nnamespace FsusBlog.Server.Infrastructure.SchemaMigration;\n\ninternal static class AuthoringWorkspaceSnapshotRuntimeTables\n{\n    internal static IReadOnlyList<CurrentSchemaRuntimeRollupTable> Tables { get; } =\n    [\n        new("authoring_workspace_snapshot",\n            """\n${dedent(migrations[0][1]).split('\n').map(line => `            ${line}`).join('\n')}\n            """)\n    ];\n}\n`;
    return {
        code,
        receipt: {
            schema: 'fsusblog.authoring-workspace-snapshot-sql-parity.v1',
            table: 'authoring_workspace_snapshot',
            persistenceSourceDigest: createHash('sha256').update(persistenceSource).digest('hex'),
            migrationSourceDigest: createHash('sha256').update(migrationSource).digest('hex'),
            normalizedSqlDigest: createHash('sha256').update(sql).digest('hex'),
            runtimeSourceDigest: createHash('sha256').update(code).digest('hex')
        }
    };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url))
{
    const generated = generateRuntimeTables(
        readFileSync(path.join(root, persistencePath), 'utf8'),
        readFileSync(path.join(root, migrationPath), 'utf8'));
    if (process.argv.includes('--check'))
    {
        if (readFileSync(path.join(root, outputPath), 'utf8') !== generated.code)
            throw new Error('authoring_workspace_snapshot_runtime_tables_drift');
    }
    else writeFileSync(path.join(root, outputPath), generated.code);
    console.log(JSON.stringify(generated.receipt));
}
