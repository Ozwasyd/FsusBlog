import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { validateJsonSchema } from '../test-matrix/schema-validator/validate.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const hash = bytes => createHash('sha256').update(bytes).digest('hex');

export function generatePublicAssetPolicy(bytes)
{
    const policy = JSON.parse(bytes);
    const schema = JSON.parse(fs.readFileSync(path.join(root, 'config/security/public-asset-delivery.schema.json'), 'utf8'));
    const errors = validateJsonSchema(policy, schema);
    if (errors.length) throw new Error(`public_asset_delivery_policy_invalid: ${errors.join('; ')}`);
    const { gateway } = policy;
    const inputSha256 = hash(bytes);
    const zones = `    # Generated by tools/security/public-asset-policy.mjs; input-sha256=${inputSha256}\n`
        + `    limit_req_zone $binary_remote_addr zone=fsus_public_asset_limit:10m rate=${gateway.requestsPerSecond}r/s;\n`
        + '    limit_conn_zone $binary_remote_addr zone=fsus_public_asset_connections:10m;\n'
        + '    map $status $fsus_public_asset_cache_control {\n'
        + '        default "no-store";\n'
        + `        200 "${policy.headers['Cache-Control']}";\n`
        + `        304 "${policy.headers['Cache-Control']}";\n`
        + '    }\n'
        + '    map $status $fsus_public_asset_retry_after {\n'
        + '        default "";\n'
        + `        429 "${policy.kestrel.windowSeconds}";\n`
        + '    }';
    // Keep terminal rejection in Kestrel so methods, ranges, hidden/temporary
    // files and errors retain the same no-store semantics through both lanes.
    const location = `        # Generated by tools/security/public-asset-policy.mjs; input-sha256=${inputSha256}\n`
        + `        location ^~ ${policy.routePrefix}/ {\n`
        + `            limit_req zone=fsus_public_asset_limit burst=${gateway.burst} nodelay;\n`
        + '            limit_req_status 429;\n'
        + `            limit_conn fsus_public_asset_connections ${gateway.connectionsPerIp};\n`
        + '            limit_conn_status 429;\n'
        + `            limit_rate_after ${gateway.rateAfterBytes};\n`
        + `            limit_rate ${gateway.rateBytesPerSecond};\n`
        + '            more_set_headers "Cache-Control: $fsus_public_asset_cache_control";\n'
        + '            more_set_headers "Retry-After: $fsus_public_asset_retry_after";\n'
        + Object.entries(policy.headers).filter(([name]) => name !== 'Cache-Control').map(([name, value]) => `            more_set_headers "${name}: ${value}";\n`).join('')
        + '            proxy_buffering off;\n'
        + '            proxy_pass http://fsusblog_kestrel;\n'
        + '            proxy_set_header Host $host;\n'
        + '            proxy_set_header X-Real-IP $remote_addr;\n'
        + '            proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;\n'
        + '            proxy_set_header X-Forwarded-Proto $scheme;\n'
        + '            proxy_set_header X-Forwarded-Host $host;\n'
        // Do not override upstream no-store on errors with immutable caching.
        // Successful and application rejection headers come from the same policy.
        + '        }';
    const documentation = `<!-- Generated by tools/security/public-asset-policy.mjs; do not edit. -->\n\n`
        + `Policy: \`config/security/public-asset-delivery.json\`, SHA-256 \`${inputSha256}\`.\n\n`
        + `Route: \`${policy.routePrefix}/\`. Methods: ${policy.methods.join(', ')}. Maximum bytes: ${policy.maxFileBytes}.\n\n`
        + `Kestrel: ${policy.kestrel.permitLimit} requests per ${policy.kestrel.windowSeconds} seconds per trusted client IP, queue ${policy.kestrel.queueLimit}.\n\n`
        + `OpenResty: ${gateway.requestsPerSecond} requests/second, burst ${gateway.burst}, ${gateway.connectionsPerIp} connections per IP; ${gateway.rateBytesPerSecond} bytes/second after ${gateway.rateAfterBytes} bytes.\n\n`
        + Object.entries(policy.headers).map(([name, value]) => `- ${name}: \`${value}\``).join('\n') + '\n';
    return { zones, location, documentation, inputSha256 };
}

function replaceBlock(source, name, content, fallback)
{
    const start = `# BEGIN GENERATED PUBLIC ASSET ${name}`;
    const end = `# END GENERATED PUBLIC ASSET ${name}`;
    if (source.includes(start))
    {
        const first = source.indexOf(start);
        const last = source.indexOf(end, first);
        if (last < first || source.indexOf(start, first + start.length) >= 0) throw new Error('public_asset_generated_block_invalid');
        return source.slice(0, first) + `${start}\n${content}\n${name === 'ZONES' ? '    ' : '        '}${end}` + source.slice(last + end.length);
    }
    if (!source.includes(fallback)) throw new Error('public_asset_gateway_anchor_missing');
    return source.replace(fallback, `${start}\n${content}\n${name === 'ZONES' ? '    ' : '        '}${end}\n\n${fallback}`);
}

export function renderPublicAssetGateway(source, generated)
{
    const withZones = replaceBlock(source, 'ZONES', generated.zones, '    upstream fsusblog_kestrel {');
    return replaceBlock(withZones, 'LOCATION', generated.location, '        # Ticket-bearing external paths must never enter the combined access log.');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href)
{
    const generated = generatePublicAssetPolicy(fs.readFileSync(path.join(root, 'config/security/public-asset-delivery.json')));
    const configPath = path.join(root, 'ops/gateway/production-openresty.conf');
    const outputs = new Map([
        [configPath, renderPublicAssetGateway(fs.readFileSync(configPath, 'utf8'), generated)],
        [path.join(root, 'docs/security/public-asset-delivery-policy.generated.md'), generated.documentation]
    ]);
    for (const [destination, contents] of outputs)
    {
        if (process.argv.includes('--check'))
        {
            if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== contents) throw new Error(`public_asset_generated_output_stale: ${path.relative(root, destination)}`);
        }
        else
        {
            fs.mkdirSync(path.dirname(destination), { recursive: true });
            fs.writeFileSync(destination, contents);
        }
    }
    console.log(JSON.stringify({ inputSha256: generated.inputSha256, outputs: [...outputs].map(([file, contents]) => ({ path: path.relative(root, file), sha256: hash(contents) })) }));
}
